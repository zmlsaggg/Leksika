#include "байткод.h"
#include "компилятор.h"
#include "машина.h"
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

typedef struct {
    char данные[256];
    size_t длина;
} БуферВывода;

static int проверить(const char *имя, int условие)
{
    printf("%s: %s\n", условие ? "OK" : "FAIL", имя);
    return условие ? 0 : 1;
}

static int вывести(void *контекст, const char *данные, size_t длина)
{
    БуферВывода *буфер = (БуферВывода *)контекст;
    if (длина > sizeof(буфер->данные) - буфер->длина) return 0;
    memcpy(буфер->данные + буфер->длина, данные, длина);
    буфер->длина += длина;
    return 1;
}

int main(void)
{
    int ошибок = 0;
    char ошибка[512] = {0};
    const char *исходник =
        "правило удвоить принимает число повторять\n"
        "    вернуть число умножить на два.\n"
        "конец правила.\n"
        "пусть итог равно удвоить(21).\n"
        "сказать речь Ответ: (итог) конец речи.\n"
        "вернуть итог.";

    ЛексусСкомпилированнаяПрограмма скомпилировано;
    int ok = лексус_скомпилировать(исходник, strlen(исходник),
                                    &скомпилировано, ошибка, sizeof(ошибка));
    ошибок += проверить("компилятор создаёт программу с таблицами функций",
                        ok && скомпилировано.число_инструкций > 0 &&
                        скомпилировано.число_функций == 1 &&
                        скомпилировано.число_вызовов == 1);
    if (!ok) {
        fprintf(stderr, "Ошибка компиляции: %s\n", ошибка);
        return 1;
    }

    ошибок += проверить("каждая инструкция имеет позицию исходника",
                        скомпилировано.число_позиций == скомпилировано.число_инструкций &&
                        скомпилировано.позиции != NULL);

    ЛексусПрограмма исходная = {
        скомпилировано.код, скомпилировано.число_инструкций,
        скомпилировано.константы, скомпилировано.число_констант,
        скомпилировано.регистры,
        скомпилировано.функции, скомпилировано.число_функций,
        скомпилировано.вызовы, скомпилировано.число_вызовов,
        скомпилировано.позиции, скомпилировано.число_позиций
    };

    unsigned char *бинарный = NULL;
    size_t длина = 0;
    ok = лексус_байткод_сериализовать(&исходная, &бинарный, &длина,
                                      ошибка, sizeof(ошибка));
    ошибок += проверить("сериализация в переносимый .lekb", ok &&
                        бинарный != NULL && длина > 48 &&
                        memcmp(бинарный, "LEKSBC01", 8) == 0);
    if (!ok) {
        fprintf(stderr, "Ошибка сериализации: %s\n", ошибка);
        лексус_скомпиляцию_освободить(&скомпилировано);
        return 1;
    }

    ЛексусБинарныйМодуль модуль;
    ok = лексус_байткод_загрузить(бинарный, длина, &модуль,
                                  ошибка, sizeof(ошибка));
    ошибок += проверить("десериализация проверяет и восстанавливает модуль",
                        ok && модуль.число_инструкций == исходная.число_инструкций &&
                        модуль.число_констант == исходная.число_констант &&
                        модуль.число_функций == исходная.число_функций &&
                        модуль.число_вызовов == исходная.число_вызовов &&
                        модуль.число_позиций == исходная.число_позиций);
    if (!ok) {
        fprintf(stderr, "Ошибка загрузки: %s\n", ошибка);
        free(бинарный);
        лексус_скомпиляцию_освободить(&скомпилировано);
        return 1;
    }

    ЛексусПрограмма представление;
    лексус_байткод_модуль_представить(&модуль, &представление);
    БуферВывода вывод = {{0}, 0};
    ЛексусСредаИсполнения среда = {
        &вывод, NULL, вывести, ЛЕКСУС_РАЗРЕШИТЬ_ВЫВОД, NULL
    };
    ЛексусЗначение результат = лексус_ничто();
    ok = лексус_машина_исполнить_со_средой(&представление, 100000,
                                            &среда, &результат,
                                            ошибка, sizeof(ошибка));
    ЛексусЗначение ожидание = лексус_ничто();
    (void)лексус_число_создать("42", &ожидание);
    int равны = 0;
    if (ok) (void)лексус_равно(результат, ожидание, &равны);
    вывод.данные[вывод.длина] = '\0';
    ошибок += проверить("VM исполняет загруженный модуль с вызовом правила",
                        ok && равны &&
                        strcmp(вывод.данные, "Ответ: 42\n") == 0);
    if (!ok) fprintf(stderr, "Ошибка VM: %s\n", ошибка);
    лексус_значение_освободить(&результат);
    лексус_значение_освободить(&ожидание);

    unsigned char *повреждённый = (unsigned char *)malloc(длина);
    if (повреждённый) memcpy(повреждённый, бинарный, длина);
    if (повреждённый && длина > 48) повреждённый[48] ^= 0x40;
    ЛексусБинарныйМодуль плохой;
    ошибка[0] = '\0';
    int принят = повреждённый &&
        лексус_байткод_загрузить(повреждённый, длина, &плохой,
                                  ошибка, sizeof(ошибка));
    ошибок += проверить("контрольная сумма обнаруживает повреждение секции",
                        !принят && strstr(ошибка, "контрольная сумма") != NULL);
    free(повреждённый);

    ошибка[0] = '\0';
    принят = лексус_байткод_загрузить(бинарный, длина - 1, &плохой,
                                      ошибка, sizeof(ошибка));
    ошибок += проверить("загрузчик отклоняет усечённый файл",
                        !принят && strstr(ошибка, "размер") != NULL);

    unsigned char *неизвестная = (unsigned char *)malloc(длина);
    if (неизвестная) {
        memcpy(неизвестная, бинарный, длина);
        неизвестная[8] = 2;
    }
    ошибка[0] = '\0';
    принят = неизвестная &&
        лексус_байткод_загрузить(неизвестная, длина, &плохой,
                                  ошибка, sizeof(ошибка));
    ошибок += проверить("загрузчик отклоняет несовместимую версию формата",
                        !принят && strstr(ошибка, "версия") != NULL);
    free(неизвестная);

    лексус_байткод_модуль_очистить(&модуль);
    free(бинарный);
    лексус_скомпиляцию_освободить(&скомпилировано);

    printf("Итого: %s\n", ошибок ? "есть ошибки" : "все проверки пройдены");
    return ошибок ? 1 : 0;
}
