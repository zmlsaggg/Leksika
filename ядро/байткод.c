#include "байткод.h"
#include <stdio.h>
_Static_assert(sizeof(ЛексусИнструкция) == 8, "Лексус bytecode instruction must be 8 bytes");
static void fail(char *p,size_t n,const char *s){if(p&&n)snprintf(p,n,"%s",s);}
static int reg_ok(const ЛексусПрограмма*p,uint8_t r){return r<p->регистры;}
int лексус_байткод_проверить(const ЛексусПрограмма*p,char*err,size_t n){
 if(!p||!p->код||!p->число_инструкций||!p->регистры||p->регистры>256){fail(err,n,"пустая программа или нет регистров");return 0;}
 if(p->число_инструкций>UINT32_MAX||p->число_констант>UINT32_MAX){fail(err,n,"слишком много инструкций");return 0;}
 if(p->число_констант&&!p->константы){fail(err,n,"нет таблицы констант");return 0;}
 if(p->число_функций&&!p->функции){fail(err,n,"нет таблицы функций");return 0;}
 if(p->число_вызовов&&!p->вызовы){fail(err,n,"нет таблицы вызовов");return 0;}
 for(size_t i=0;i<p->число_функций;++i){
  const ЛексусФункция*f=&p->функции[i];
  if(f->вход>=p->число_инструкций||(f->число_параметров&&!f->параметры)){fail(err,n,"неверное описание функции");return 0;}
  for(size_t j=0;j<f->число_параметров;++j){
   if(!reg_ok(p,f->параметры[j])){fail(err,n,"параметр функции использует неверный регистр");return 0;}
   for(size_t k=0;k<j;++k)if(f->параметры[k]==f->параметры[j]){fail(err,n,"параметры функции повторяют регистр");return 0;}
  }
 }
 for(size_t i=0;i<p->число_вызовов;++i){
  const ЛексусВызов*c=&p->вызовы[i];
  if(c->функция>=p->число_функций||!reg_ok(p,c->назначение)||
     (c->число_аргументов&&!c->аргументы)){fail(err,n,"неверное описание вызова");return 0;}
  if(c->число_аргументов!=p->функции[c->функция].число_параметров){fail(err,n,"число аргументов не совпадает с параметрами функции");return 0;}
  for(size_t j=0;j<c->число_аргументов;++j)if(!reg_ok(p,c->аргументы[j])){fail(err,n,"аргумент вызова использует неверный регистр");return 0;}
 }
 for(size_t i=0;i<p->число_инструкций;++i){const ЛексусИнструкция*x=&p->код[i];
  switch(x->операция){
   case ЛЕКСУС_ОП_КОНСТАНТА:
    if(!reg_ok(p,x->назначение)||x->операнд>=p->число_констант){fail(err,n,"неверный регистр или индекс константы");return 0;}break;
   case ЛЕКСУС_ОП_КОПИЯ: case ЛЕКСУС_ОП_НЕ: case ЛЕКСУС_ОП_ЦЕЛОЕ:
    if(!reg_ok(p,x->назначение)||!reg_ok(p,x->а)){fail(err,n,"операция использует неверный регистр");return 0;}break;
   case ЛЕКСУС_ОП_ВВОД:
    if(!reg_ok(p,x->назначение)){fail(err,n,"ввод использует неверный регистр");return 0;}break;
   case ЛЕКСУС_ОП_ПРОВЕРИТЬ:
    if(!reg_ok(p,x->а)||!reg_ok(p,x->б)){fail(err,n,"проверка использует неверный регистр");return 0;}break;
   case ЛЕКСУС_ОП_ПЕРЕЧЕНЬ_СОЗДАТЬ:
    if(!reg_ok(p,x->назначение)){fail(err,n,"создание перечня использует неверный регистр");return 0;}break;
   case ЛЕКСУС_ОП_ПЕРЕЧЕНЬ_ДОБАВИТЬ:
    if(!reg_ok(p,x->а)||!reg_ok(p,x->б)){fail(err,n,"добавление в перечень использует неверный регистр");return 0;}break;
   case ЛЕКСУС_ОП_ИТЕРАЦИЯ_НАЧАТЬ:
    if(!reg_ok(p,x->а)||x->операнд>=p->число_инструкций){fail(err,n,"начало обхода использует неверный регистр или адрес");return 0;}break;
   case ЛЕКСУС_ОП_ИТЕРАЦИЯ_ШАГ:
    if(!reg_ok(p,x->назначение)||!reg_ok(p,x->а)||x->операнд>=p->число_инструкций){fail(err,n,"шаг обхода использует неверный регистр или адрес");return 0;}break;
   case ЛЕКСУС_ОП_ИТЕРАЦИЯ_ПРЕРВАТЬ:
    if(x->операнд>=p->число_инструкций){fail(err,n,"выход из обхода указывает за пределы программы");return 0;}break;
   case ЛЕКСУС_ОП_СЛОЖИТЬ: case ЛЕКСУС_ОП_ВЫЧЕСТЬ:
   case ЛЕКСУС_ОП_УМНОЖИТЬ: case ЛЕКСУС_ОП_РАЗДЕЛИТЬ: case ЛЕКСУС_ОП_РАВНО:
   case ЛЕКСУС_ОП_БОЛЬШЕ: case ЛЕКСУС_ОП_МЕНЬШЕ:
   case ЛЕКСУС_ОП_НЕБОЛЬШЕ: case ЛЕКСУС_ОП_НЕМЕНЬШЕ:
   case ЛЕКСУС_ОП_И: case ЛЕКСУС_ОП_ИЛИ:
    if(!reg_ok(p,x->назначение)||!reg_ok(p,x->а)||!reg_ok(p,x->б)){fail(err,n,"арифметика использует неверный регистр");return 0;}break;
   case ЛЕКСУС_ОП_ПЕРЕХОД:
    if(x->операнд>=p->число_инструкций){fail(err,n,"адрес перехода вне программы");return 0;}break;
   case ЛЕКСУС_ОП_ПОВТОРИТЬ_НАЧАЛО:
    if(!reg_ok(p,x->а)||x->операнд>=p->число_инструкций){fail(err,n,"начало счётного цикла использует неверный регистр или адрес");return 0;}break;
   case ЛЕКСУС_ОП_ПОВТОРИТЬ_ШАГ:
    if(x->операнд>=p->число_инструкций){fail(err,n,"шаг счётного цикла указывает за пределы программы");return 0;}break;
   case ЛЕКСУС_ОП_ПОВТОРИТЬ_ПРЕРВАТЬ:
    if(x->операнд>=p->число_инструкций){fail(err,n,"выход из счётного цикла указывает за пределы программы");return 0;}break;
   case ЛЕКСУС_ОП_ПЕРЕХОД_ЕСЛИ_ЛОЖЬ:
    if(!reg_ok(p,x->а)||x->операнд>=p->число_инструкций){fail(err,n,"условный переход использует неверный регистр или адрес");return 0;}break;
   case ЛЕКСУС_ОП_ВОЗВРАТ:
    if(!reg_ok(p,x->а)){fail(err,n,"возврат использует неверный регистр");return 0;}break;
   case ЛЕКСУС_ОП_ПОКАЗАТЬ:
    if(!reg_ok(p,x->назначение)){fail(err,n,"вывод использует неверный регистр");return 0;}break;
   case ЛЕКСУС_ОП_ВЫЗОВ:
    if(x->операнд>=p->число_вызовов){fail(err,n,"вызов ссылается на неизвестный дескриптор");return 0;}break;
   case ЛЕКСУС_ОП_СТОП: break;
   default: fail(err,n,"неизвестный код операции");return 0;
  }
 }
 return 1;
}
