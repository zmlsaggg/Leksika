#ifndef ЛЕКСУС_КОМПИЛЯТОР_H
#define ЛЕКСУС_КОМПИЛЯТОР_H
#include "байткод.h"
#include <stddef.h>
#include <stdint.h>

enum {
    ЛЕКСУС_ПРОФИЛЬ_БЕЗ_ИЗМЕНЕНИЙ = 0u,
    ЛЕКСУС_ПРОФИЛЬ_18_ПЛЮС = 1u,
    ЛЕКСУС_ПРОФИЛЬ_ЗУМЕР = 2u
};

typedef struct {
    ЛексусИнструкция *код;
    size_t число_инструкций;
    ЛексусЗначение *константы;
    size_t число_констант;
    uint16_t регистры;
    ЛексусФункция *функции;
    size_t число_функций;
    ЛексусВызов *вызовы;
    size_t число_вызовов;
    uint8_t *память_ссылок;
} ЛексусСкомпилированнаяПрограмма;

/*
 * Первый нативный компилятор поддерживает проверяемое подмножество:
 * объявления и изменение переменных, сказать/что, спросить, вернуть, ветвления и циклы.
 * Выражения: числа цифрами и словами (126 словоформ, множители до миллиарда),
 * дроби через «запятая», обычные речевые литералы «речь … конец речи», имена, скобки,
 * да/нет/ничто, унарные минус/не, арифметика, равенство,
 * числовые сравнения, логические и/или, ветвления «если/иначе если/иначе», циклы «пока» и «повторить N раз».
 * Правила с параметрами и вызовы с аргументами компилируются в нативные кадры VM. Интерполяция выражений в речи пока не поддерживается.
 * Служебные слова нельзя использовать как имена переменных.
 * Максимум 254 переменные; два регистра остаются для вычислений.
 *
 * Неизвестные и неподдерживаемые конструкции отклоняются с диагностикой:
 * компилятор не делегирует их старому исполнителю.
 */
int лексус_скомпилировать(const char *исходник, size_t длина,
                          ЛексусСкомпилированнаяПрограмма *результат,
                          char *ошибка, size_t размер_ошибки);
int лексус_скомпилировать_с_профилями(const char *исходник, size_t длина,
                                      unsigned профили,
                                      ЛексусСкомпилированнаяПрограмма *результат,
                                      char *ошибка, size_t размер_ошибки);
void лексус_скомпиляцию_освободить(ЛексусСкомпилированнаяПрограмма *программа);
#endif
