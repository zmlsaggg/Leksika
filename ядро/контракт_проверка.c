#include "компилятор.h"
#include "машина.h"
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

typedef enum { ОЖИДАЕТ_ЧИСЛО, ОЖИДАЕТ_ЛОГИКУ } ВидОжидания;
typedef struct {
    const char *имя;
    const char *исходник;
    ВидОжидания вид;
    const char *ожидается;
    const char *ошибка;
} ПроверкаКонтракта;

static unsigned всего=0, провалено=0;

static void проверить(const char *имя,int условие)
{
    ++всего;
    printf("%s: %s — %s\n",условие?"OK":"FAIL",имя,
           условие?"контракт соблюдён":"контракт нарушен");
    if(!условие) ++провалено;
}

static int содержит(const char *строка,const char *фрагмент)
{
    return строка&&фрагмент&&strstr(строка,фрагмент)!=NULL;
}

static int выполнить(const char *исходник,ЛексусЗначение *результат,
                     char *ошибка,size_t размер)
{
    ЛексусСкомпилированнаяПрограмма скомпилировано;
    if(!лексус_скомпилировать(исходник,strlen(исходник),
                             &скомпилировано,ошибка,размер)) return 0;
    ЛексусПрограмма программа={
        скомпилировано.код,скомпилировано.число_инструкций,
        скомпилировано.константы,скомпилировано.число_констант,
        скомпилировано.регистры,
        скомпилировано.функции,скомпилировано.число_функций,
        скомпилировано.вызовы,скомпилировано.число_вызовов
    };
    int ok=лексус_машина_исполнить(&программа,1000000,
                                   результат,ошибка,размер);
    лексус_скомпиляцию_освободить(&скомпилировано);
    return ok;
}

static int равно_ожиданию(ЛексусЗначение факт,const ПроверкаКонтракта *тест)
{
    ЛексусЗначение ожидание=лексус_ничто();
    ЛексусОшибка ошибка;
    if(тест->вид==ОЖИДАЕТ_ЧИСЛО)
        ошибка=лексус_число_создать(тест->ожидается,&ожидание);
    else
        ожидание=лексус_логическое(strcmp(тест->ожидается,"да")==0),
        ошибка.код=ЛЕКСУС_ОК,ошибка.сообщение=NULL;
    int равны=0;
    if(ошибка.код==ЛЕКСУС_ОК)
        ошибка=лексус_равно(факт,ожидание,&равны);
    int ok=ошибка.код==ЛЕКСУС_ОК&&равны;
    лексус_значение_освободить(&ожидание);
    return ok;
}

int main(void)
{
    puts("Исполняемый контракт Лексики — этап 0");
    static const ПроверкаКонтракта таблица[]={
        {"два плюс три даёт целое 5","вернуть два плюс три.",
         ОЖИДАЕТ_ЧИСЛО,"5",NULL},
        {"один разделить на два даёт 0,5","вернуть один разделить на два.",
         ОЖИДАЕТ_ЧИСЛО,"0,5",NULL},
        {"деление 1 на 3 округляется до 34 знаков",
         "вернуть один разделить на три.",ОЖИДАЕТ_ЧИСЛО,
         "0,3333333333333333333333333333333333",NULL},
        {"логика не равна числу один","вернуть да равно один.",
         ОЖИДАЕТ_ЛОГИКУ,"нет",NULL},
        {"деление на ноль возвращает ошибку",
         "вернуть один разделить на ноль.",ОЖИДАЕТ_ЧИСЛО,NULL,"ноль"},
        {"необъявленное имя не создаётся автоматически",
         "вернуть отсутствующее.",ОЖИДАЕТ_ЧИСЛО,NULL,"объявления"}
    };
    for(size_t i=0;i<sizeof(таблица)/sizeof(таблица[0]);++i){
        const ПроверкаКонтракта *т=&таблица[i];
        ЛексусЗначение факт=лексус_ничто();
        char ошибка[512]={0};
        int ok=выполнить(т->исходник,&факт,ошибка,sizeof(ошибка));
        if(т->ошибка)
            проверить(т->имя,!ok&&содержит(ошибка,т->ошибка));
        else
            проверить(т->имя,ok&&равно_ожиданию(факт,т));
        лексус_значение_освободить(&факт);
    }

    ЛексусЗначение речь=лексус_ничто();
    ЛексусОшибка e=лексус_речь_создать("ёж",strlen("ёж"),&речь);
    size_t длина=0;
    if(e.код==ЛЕКСУС_ОК) e=лексус_речь_длина(речь,&длина);
    проверить("длина речи считает кодовые точки Unicode, а не байты",
             e.код==ЛЕКСУС_ОК&&длина==2);
    лексус_значение_освободить(&речь);

    ЛексусЗначение перечень=лексус_ничто();
    e=лексус_перечень_создать(&перечень);
    ЛексусЗначение ноль=лексус_ничто(),элемент=лексус_ничто();
    if(e.код==ЛЕКСУС_ОК) e=лексус_число_создать("0",&ноль);
    if(e.код==ЛЕКСУС_ОК) e=лексус_перечень_получить(перечень,0,&элемент);
    проверить("индекс за границей перечня — управляемая ошибка",
             e.код==ЛЕКСУС_НЕТ_ЭЛЕМЕНТА);
    лексус_значение_освободить(&элемент);
    лексус_значение_освободить(&ноль);
    лексус_значение_освободить(&перечень);

    ЛексусЗначение пустая_речь=лексус_ничто();
    ЛексусОшибка речь_создана=лексус_речь_создать("",0,&пустая_речь);
    проверить("пустая речь ложна в условии",
             речь_создана.код==ЛЕКСУС_ОК&&!лексус_правда(пустая_речь));
    лексус_значение_освободить(&пустая_речь);

    printf("Итого: %u, провалено: %u\n",всего,провалено);
    return провалено?1:0;
}
