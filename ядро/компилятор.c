static int разобрать_аргументы_в_скобках(Компилятор *к,uint8_t *аргументы,uint8_t *число)
{
    *число=0;
    if(к->текущий.вид!=ТОК_ОТКРЫТЬ) return 1;
    if(!следующий(к)) return 0;
    if(к->текущий.вид==ТОК_ЗАКРЫТЬ) return следующий(к);
    for(;;) {
        if(*число>=254u) {
            ошибка_текста(к,"вызов правила не может принимать больше 254 аргументов");
            return 0;
        }
        uint8_t аргумент;
        if(!выражение(к,&аргумент)) return 0;
        аргументы[(*число)++]=аргумент;
        if(к->текущий.вид==ТОК_ЗАПЯТАЯ) {
            if(!следующий(к)) return 0;
            continue;
        }
        if(к->текущий.вид!=ТОК_ЗАКРЫТЬ) {
            ошибка_текста(к,"в аргументах правила ожидается запятая или закрывающая скобка");
            return 0;
        }
        return следующий(к);
    }
}
static int первичное(Компилятор *к,uint8_t *результат)
{
    if (к->текущий.вид==ТОК_РЕЧЬ) {
        ЛексусЗначение value=лексус_ничто();
        ЛексусОшибка e=лексус_речь_создать((const char*)к->текущий.данные_речи,
                                           к->текущий.длина_речи,&value);
        if(e.код!=ЛЕКСУС_ОК) {
            ошибка_текста(к,e.сообщение?e.сообщение:"не удалось создать речевое значение");
            return 0;
        }
        uint32_t ci; uint8_t r;
        if(!добавить_значение_константу(к,value,&ci)||!регистр_создать(к,&r)) return 0;
        if(!добавить_инструкцию(к,(ЛексусИнструкция){ЛЕКСУС_ОП_КОНСТАНТА,r,0,0,ci})) return 0;
        if(!следующий(к)) return 0;
        *результат=r; return 1;
    }
    if (к->текущий.вид==ТОК_ЧИСЛО) {
        char запись[РАЗМЕР_СЛОВА*2+2];
        uint32_t ci; uint8_t r;
        strcpy(запись,к->текущий.текст);
        if (!следующий(к)) return 0;
        if (слово(к,"запятая")||слово(к,"запятой")||слово(к,"запятую")) {
            size_t целая=strlen(запись);
            if (!следующий(к)) return 0;
            char дробь[РАЗМЕР_СЛОВА];
            if (к->текущий.вид==ТОК_ЧИСЛО) {
                strcpy(дробь,к->текущий.текст);
                if (!следующий(к)) return 0;
            } else {
                uint64_t дробное=0;
                int распознано=прочитать_числительное(к,&дробное);
                if (распознано<=0) {
                    ошибка_текста(к,"после слова «запятая» нужны цифры или числительное"); return 0;
                }
                int dn=snprintf(дробь,sizeof(дробь),"%llu",(unsigned long long)дробное);
                if(dn<0||(size_t)dn>=sizeof(дробь)) {
                    ошибка_текста(к,"слишком длинная дробная часть"); return 0;
                }
            }
            if (целая+strlen(дробь)+2>sizeof(запись)) {
                ошибка_текста(к,"слишком длинная запись дробного числа"); return 0;
            }
            запись[целая]=',';
            strcpy(запись+целая+1,дробь);
        }
        if (!добавить_константу(к,запись,&ci)||!регистр_создать(к,&r)) return 0;
        if (!добавить_инструкцию(к,(ЛексусИнструкция){ЛЕКСУС_ОП_КОНСТАНТА,r,0,0,ci})) return 0;
        *результат=r; return 1;
    }
    if (к->текущий.вид==ТОК_ОТКРЫТЬ) {
        if (!следующий(к)||!выражение(к,результат)) return 0;
        if (к->текущий.вид!=ТОК_ЗАКРЫТЬ) {
            ошибка_текста(к,"ожидается закрывающая скобка «)»"); return 0;
        }
        return следующий(к);
    }
    if (слово(к,"перечень")) {
        uint8_t list;
        if(!следующий(к)||к->текущий.вид!=ТОК_ОТКРЫТЬ) {
            ошибка_текста(к,"после «перечень» ожидается открывающая скобка"); return 0;
        }
        if(!регистр_создать(к,&list)||
           !добавить_инструкцию(к,(ЛексусИнструкция){ЛЕКСУС_ОП_ПЕРЕЧЕНЬ_СОЗДАТЬ,list,0,0,0})||
           !следующий(к)) return 0;
        if(к->текущий.вид==ТОК_ЗАКРЫТЬ) {
            if(!следующий(к)) return 0;
            *результат=list; return 1;
        }
        for(;;) {
            uint8_t item;
            if(!выражение(к,&item)) return 0;
            if(!добавить_инструкцию(к,(ЛексусИнструкция){ЛЕКСУС_ОП_ПЕРЕЧЕНЬ_ДОБАВИТЬ,0,list,item,0})) return 0;
            регистр_освободить(к,item);
            if(к->текущий.вид==ТОК_ЗАПЯТАЯ) {
                if(!следующий(к)) return 0;
                if(к->текущий.вид==ТОК_ЗАКРЫТЬ) {
                    ошибка_текста(к,"после запятой в перечне ожидается элемент"); return 0;
                }
                continue;
            }
            if(к->текущий.вид!=ТОК_ЗАКРЫТЬ) {
                ошибка_текста(к,"элементы перечня разделяются запятыми"); return 0;
            }
            if(!следующий(к)) return 0;
            break;
        }
        *результат=list; return 1;
    }
    if (к->текущий.вид==ТОК_СЛОВО) {
        uint64_t целое=0;
        int числовое=прочитать_числительное(к,&целое);
        if (числовое<0) return 0;
        if (числовое>0) {
            char запись[РАЗМЕР_СЛОВА*2+2],дробь[РАЗМЕР_СЛОВА];
            int n=snprintf(запись,sizeof(запись),"%llu",(unsigned long long)целое);
            if(n<0||(size_t)n>=sizeof(запись)) {
                ошибка_текста(к,"не удалось записать числительное"); return 0;
            }
            if (слово(к,"запятая")||слово(к,"запятой")||слово(к,"запятую")) {
                if(!следующий(к)) return 0;
                if(к->текущий.вид==ТОК_ЧИСЛО) {
                    strcpy(дробь,к->текущий.текст);
                    if(!следующий(к)) return 0;
                } else {
                    uint64_t дробное=0;
                    int распознано=прочитать_числительное(к,&дробное);
                    if(распознано<=0) {
                        ошибка_текста(к,"после слова «запятая» нужны цифры или числительное"); return 0;
                    }
                    int dn=snprintf(дробь,sizeof(дробь),"%llu",(unsigned long long)дробное);
                    if(dn<0||(size_t)dn>=sizeof(дробь)) {
                        ошибка_текста(к,"слишком длинная дробная часть"); return 0;
                    }
                }
                size_t whole=strlen(запись),fraction=strlen(дробь);
                if(whole+fraction+2>sizeof(запись)) {
                    ошибка_текста(к,"слишком длинное дробное числительное"); return 0;
                }
                запись[whole]=',';
                memcpy(запись+whole+1,дробь,fraction+1);
            }
            uint32_t ci; uint8_t r;
            if(!добавить_константу(к,запись,&ci)||!регистр_создать(к,&r)) return 0;
            if(!добавить_инструкцию(к,(ЛексусИнструкция){ЛЕКСУС_ОП_КОНСТАНТА,r,0,0,ci})) return 0;
            *результат=r; return 1;
        }
    }
    if (слово(к,"да")||слово(к,"истина")||слово(к,"нет")||слово(к,"ложь")||слово(к,"ничто")) {
        int truth=слово(к,"да")||слово(к,"истина");
        int nothing=слово(к,"ничто");
        ЛексусЗначение value=nothing?лексус_ничто():лексус_логическое(truth);
        uint32_t ci; uint8_t r;
        if (!добавить_значение_константу(к,value,&ci)||!регистр_создать(к,&r)) return 0;
        if (!добавить_инструкцию(к,(ЛексусИнструкция){ЛЕКСУС_ОП_КОНСТАНТА,r,0,0,ci})) return 0;
        if (!следующий(к)) return 0;
        *результат=r; return 1;
    }
    if (слово(к,"не")) {
        uint8_t value;
        if (!следующий(к)||!первичное(к,&value)) return 0;
        if (!добавить_инструкцию(к,(ЛексусИнструкция){ЛЕКСУС_ОП_НЕ,value,value,0,0})) return 0;
        *результат=value; return 1;
    }
    if (слово(к,"минус")) {
        uint8_t value,zero; uint32_t ci;
        if (!следующий(к)||!первичное(к,&value)) return 0;
        if (!добавить_константу(к,"0",&ci)||!регистр_создать(к,&zero)) return 0;
        if (!добавить_инструкцию(к,(ЛексусИнструкция){ЛЕКСУС_ОП_КОНСТАНТА,zero,0,0,ci})) return 0;
        if (!добавить_инструкцию(к,(ЛексусИнструкция){ЛЕКСУС_ОП_ВЫЧЕСТЬ,value,zero,value,0})) return 0;
        регистр_освободить(к,zero);
        *результат=value; return 1;
    }
    if (к->текущий.вид==ТОК_СЛОВО) {
        char имя[РАЗМЕР_СЛОВА];
        strcpy(имя,к->текущий.текст);
        if(!следующий(к)) return 0;
        if(к->текущий.вид==ТОК_ОТКРЫТЬ) {
            uint8_t аргументы[254],число_аргументов=0,dest;
            if(!разобрать_аргументы_в_скобках(к,аргументы,&число_аргументов)||
               !регистр_создать(к,&dest)||
               !добавить_вызов(к,имя,dest,аргументы,число_аргументов)) return 0;
            *результат=dest;
            return 1;
        }
        uint8_t source,dest;
        if (!найти_переменную(к,имя,&source)) { ошибка_текста(к,"переменная используется до объявления"); return 0; }
        if (!регистр_создать(к,&dest)) return 0;
        if (!добавить_инструкцию(к,(ЛексусИнструкция){ЛЕКСУС_ОП_КОПИЯ,dest,source,0,0})) return 0;
        *результат=dest; return 1;
    }
    ошибка_текста(к,"ожидается число или ранее объявленная переменная"); return 0;
}
static int произведение(Компилятор *к,uint8_t *результат)
{
    uint8_t left;
    if (!первичное(к,&left)) return 0;
    while (слово(к,"умножить")||слово(к,"разделить")) {
        int multiply=слово(к,"умножить");
        if (!следующий(к)||!требовать_слово(к,"на","после операции требуется предлог «на»")) return 0;
        uint8_t right;
        if (!первичное(к,&right)) return 0;
        uint8_t op=multiply?ЛЕКСУС_ОП_УМНОЖИТЬ:ЛЕКСУС_ОП_РАЗДЕЛИТЬ;
        /* Все первичные выражения лежат во временных регистрах: результат
           можно записать поверх левого операнда после чтения обоих аргументов. */
        if (!добавить_инструкцию(к,(ЛексусИнструкция){op,left,left,right,0})) return 0;
        регистр_освободить(к,right);
    }
    *результат=left; return 1;
}
static int сумма(Компилятор *к,uint8_t *результат)
{
    uint8_t left;
    if (!произведение(к,&left)) return 0;
    while (слово(к,"плюс")||слово(к,"минус")) {
        int add=слово(к,"плюс");
        if (!следующий(к)) return 0;
        uint8_t right;
        if (!произведение(к,&right)) return 0;
        uint8_t op=add?ЛЕКСУС_ОП_СЛОЖИТЬ:ЛЕКСУС_ОП_ВЫЧЕСТЬ;
        if (!добавить_инструкцию(к,(ЛексусИнструкция){op,left,left,right,0})) return 0;
        регистр_освободить(к,right);
    }
    *результат=left; return 1;
}
static int сравнение(Компилятор *к,uint8_t *результат)
{
    uint8_t left;
    if (!сумма(к,&left)) return 0;
    for (;;) {
        uint8_t op=0; int invert=0;
        if (слово(к,"равно")) {
            op=ЛЕКСУС_ОП_РАВНО;
            if (!следующий(к)) return 0;
        } else if (слово(к,"не")) {
            if (!следующий(к)) return 0;
            if (слово(к,"равно")) { op=ЛЕКСУС_ОП_РАВНО; invert=1; }
            else if (слово(к,"больше")) op=ЛЕКСУС_ОП_НЕБОЛЬШЕ;
            else if (слово(к,"меньше")) op=ЛЕКСУС_ОП_НЕМЕНЬШЕ;
            else { ошибка_текста(к,"после «не» в сравнении ожидается «равно», «больше» или «меньше»"); return 0; }
            if (!следующий(к)) return 0;
        } else if (слово(к,"больше")||слово(к,"меньше")) {
            int greater=слово(к,"больше");
            if (!следующий(к)) return 0;
            if (слово(к,"или")||слово(к,"либо")) {
                if (!следующий(к)||!требовать_слово(к,"равно","после «или» в сравнении ожидается «равно»")) return 0;
                op=greater?ЛЕКСУС_ОП_НЕМЕНЬШЕ:ЛЕКСУС_ОП_НЕБОЛЬШЕ;
            } else {
                op=greater?ЛЕКСУС_ОП_БОЛЬШЕ:ЛЕКСУС_ОП_МЕНЬШЕ;
            }
        } else break;
        uint8_t right;
        if (!сумма(к,&right)) return 0;
        if (!добавить_инструкцию(к,(ЛексусИнструкция){op,left,left,right,0})) return 0;
        регистр_освободить(к,right);
        if (invert && !добавить_инструкцию(к,(ЛексусИнструкция){ЛЕКСУС_ОП_НЕ,left,left,0,0})) return 0;
    }
    *результат=left; return 1;
}
static int логическое_и(Компилятор *к,uint8_t *результат)
{
    uint8_t left;
    if (!сравнение(к,&left)) return 0;
    while (слово(к,"и")) {
        if (!следующий(к)) return 0;
        uint8_t right;
        if (!сравнение(к,&right)) return 0;
        if (!добавить_инструкцию(к,(ЛексусИнструкция){ЛЕКСУС_ОП_И,left,left,right,0})) return 0;
        регистр_освободить(к,right);
    }
    *результат=left; return 1;
}
static int выражение(Компилятор *к,uint8_t *результат)
{
    uint8_t left;
    if (!логическое_и(к,&left)) return 0;
    while (слово(к,"или")) {
        if (!следующий(к)) return 0;
        uint8_t right;
        if (!логическое_и(к,&right)) return 0;
        if (!добавить_инструкцию(к,(ЛексусИнструкция){ЛЕКСУС_ОП_ИЛИ,left,left,right,0})) return 0;
        регистр_освободить(к,right);
    }
    *результат=left; return 1;
}
static void освободить_временные(Компилятор *к)
{
    к->следующий_регистр=(uint16_t)к->число_переменных;
}
static int объявить(Компилятор *к)
{
    char name[РАЗМЕР_СЛОВА]; uint8_t variable,value;
    if (!следующий(к)||!принять_имя(к,name)||!имя_доступно(к,name)) return 0;
    if (!регистр_создать(к,&variable)) return 0;
    if (слово(к,"это")) {
        if (!следующий(к)) return 0;
    } else if (!требовать_слово(к,"равно","после имени ожидается слово «равно» или «это»")) return 0;
    if (!выражение(к,&value)||!требовать_точку(к)) return 0;
    if (!добавить_инструкцию(к,(ЛексусИнструкция){ЛЕКСУС_ОП_КОПИЯ,variable,value,0,0})) return 0;
    strcpy(к->переменные[к->число_переменных].имя,name);
    к->переменные[к->число_переменных].регистр=variable;
    ++к->число_переменных; освободить_временные(к); return 1;
}
static int почему(Компилятор *к)
{
    uint8_t condition,reason;
    if(!следующий(к)||!выражение(к,&condition)||
       !требовать_слово(к,"то","после условия «почему» требуется маркер «то»")||
       !выражение(к,&reason)||!требовать_точку(к)) return 0;
    if(!добавить_инструкцию(к,(ЛексусИнструкция){ЛЕКСУС_ОП_ПРОВЕРИТЬ,0,condition,reason,0})) return 0;
    освободить_временные(к); return 1;
}
static int спросить(Компилятор *к)
{
    char name[РАЗМЕР_СЛОВА]; uint8_t variable;
    if(!следующий(к)||!принять_имя(к,name)) return 0;
    if(!найти_переменную(к,name,&variable)) {
        ошибка_текста(к,"ввод записывает значение только в заранее объявленное имя"); return 0;
    }
    if(!требовать_точку(к)) return 0;
    if(!добавить_инструкцию(к,(ЛексусИнструкция){ЛЕКСУС_ОП_ВВОД,variable,0,0,0})) return 0;
    освободить_временные(к); return 1;
}
static int сказать(Компилятор *к)
{
    uint8_t value;
    if (!следующий(к)||!выражение(к,&value)||!требовать_точку(к)) return 0;
    if (!добавить_инструкцию(к,(ЛексусИнструкция){ЛЕКСУС_ОП_ПОКАЗАТЬ,value,0,0,0})) return 0;
    освободить_временные(к); return 1;
}
static int вернуть(Компилятор *к)
{
    uint8_t value;
    if (!следующий(к)||!выражение(к,&value)||!требовать_точку(к)) return 0;
    if (!добавить_инструкцию(к,(ЛексусИнструкция){ЛЕКСУС_ОП_ВОЗВРАТ,0,value,0,0})) return 0;
    if(к->глубина_управления==0) к->возврат_встретился=1;
    освободить_временные(к); return 1;
}
static int изменить(Компилятор *к)
{
    char name[РАЗМЕР_СЛОВА]; uint8_t variable,right; int op;
    if (слово(к,"увеличить")) op=ЛЕКСУС_ОП_СЛОЖИТЬ;
    else if (слово(к,"уменьшить")) op=ЛЕКСУС_ОП_ВЫЧЕСТЬ;
    else if (слово(к,"умножить")) op=ЛЕКСУС_ОП_УМНОЖИТЬ;
    else op=ЛЕКСУС_ОП_РАЗДЕЛИТЬ;
    if (!следующий(к)||!принять_имя(к,name)) return 0;
    if (!найти_переменную(к,name,&variable)) { ошибка_текста(к,"изменяется необъявленная переменная"); return 0; }
    if (!требовать_слово(к,"на","после имени ожидается предлог «на»")) return 0;
    if (!выражение(к,&right)||!требовать_точку(к)) return 0;
    if (!добавить_инструкцию(к,(ЛексусИнструкция){(uint8_t)op,variable,variable,right,0})) return 0;
    освободить_временные(к); return 1;
}
static int разобрать_действие(Компилятор *к);
static int patch_target(Компилятор *к,size_t место,size_t цель)
{
    if(место>=к->число_инструкций||цель>UINT32_MAX) {
        ошибка_текста(к,"не удалось сформировать адрес перехода"); return 0;
    }
    к->код[место].операнд=(uint32_t)цель;
    return 1;
}
static int отложить_переход(Компилятор *к,size_t **адреса,size_t *число,
                            size_t *ёмкость,size_t адрес)
{
    if(*число==*ёмкость) {
        size_t новая=*ёмкость?*ёмкость*2:8;
        if(новая<*ёмкость || новая>SIZE_MAX/sizeof(**адреса)) {
            ошибка_текста(к,"слишком много переходов управления циклами"); return 0;
        }
        size_t *память=(size_t*)realloc(*адреса,новая*sizeof(**адреса));
        if(!память) { ошибка_текста(к,"не хватает памяти для переходов циклов"); return 0; }
        *адреса=память; *ёмкость=новая;
    }
    (*адреса)[(*число)++]=адрес;
    return 1;
}
static int начать_цикл(Компилятор *к,int тип)
{
    if(к->глубина_циклов>=sizeof(к->циклы)/sizeof(к->циклы[0])) {
        ошибка_текста(к,"превышена максимальная глубина вложенности циклов (128)"); return 0;
    }
    КонтекстЦикла *цикл=&к->циклы[к->глубина_циклов++];
    цикл->счётный=тип;
    цикл->начало_прерываний=к->число_прерываний;
    цикл->начало_продолжений=к->число_продолжений;
    return 1;
}
static int закрыть_цикл(Компилятор *к,size_t выход,size_t продолжение)
{
    if(!к->глубина_циклов) { ошибка_текста(к,"нарушен стек циклов компилятора"); return 0; }
    КонтекстЦикла цикл=к->циклы[к->глубина_циклов-1];
    for(size_t i=цикл.начало_прерываний;i<к->число_прерываний;++i)
        if(!patch_target(к,к->прерывания[i],выход)) return 0;
    for(size_t i=цикл.начало_продолжений;i<к->число_продолжений;++i)
        if(!patch_target(к,к->продолжения[i],продолжение)) return 0;
    к->число_прерываний=цикл.начало_прерываний;
    к->число_продолжений=цикл.начало_продолжений;
    --к->глубина_циклов;
    return 1;
}
static int разобрать_управление_циклом(Компилятор *к,int продолжить)
{
    if(!к->глубина_циклов) {
        ошибка_текста(к,продолжить?"«продолжить» допустимо только внутри цикла":"«прервать» допустимо только внутри цикла");
        return 0;
    }
    КонтекстЦикла *цикл=&к->циклы[к->глубина_циклов-1];
    if(!следующий(к)||!требовать_точку(к)) return 0;
    size_t адрес=к->число_инструкций;
    uint8_t операция=продолжить?ЛЕКСУС_ОП_ПЕРЕХОД:
        (цикл->счётный==1?ЛЕКСУС_ОП_ПОВТОРИТЬ_ПРЕРВАТЬ:
         цикл->счётный==2?ЛЕКСУС_ОП_ИТЕРАЦИЯ_ПРЕРВАТЬ:ЛЕКСУС_ОП_ПЕРЕХОД);
    if(!добавить_инструкцию(к,(ЛексусИнструкция){операция,0,0,0,0})) return 0;
    return продолжить?
        отложить_переход(к,&к->продолжения,&к->число_продолжений,&к->ёмкость_продолжений,адрес):
        отложить_переход(к,&к->прерывания,&к->число_прерываний,&к->ёмкость_прерываний,адрес);
}
static int тело_до(Компилятор *к,const char *стоп1,const char *стоп2)
{
    while(к->текущий.вид!=ТОК_КОНЕЦ &&
          !слово(к,стоп1) && (!стоп2||!слово(к,стоп2))) {
        if(к->текущий.вид==ТОК_ТОЧКА) {
            if(!следующий(к)) return 0;
            continue;
        }
        if(!разобрать_действие(к)) return 0;
    }
    if(к->текущий.вид==ТОК_КОНЕЦ) {
        ошибка_текста(к,"не закрыт блок управления; ожидается «конец»"); return 0;
    }
    return 1;
}
static int разобрать_правило(Компилятор *к)
{
    if(к->глубина_правила||к->глубина_управления||к->глубина_циклов) {
        ошибка_текста(к,"объявлять правила можно только на верхнем уровне программы");
        return 0;
    }
    char имя[РАЗМЕР_СЛОВА];
    if(!следующий(к)||!принять_имя(к,имя)) return 0;

    Переменная *старые_переменные=(Переменная*)malloc(sizeof(к->переменные));
    if(!старые_переменные) {
        ошибка_текста(к,"не хватает памяти для локальной области правила");
        return 0;
    }
#define ОШИБКА_ПРАВИЛА() do { free(старые_переменные); return 0; } while(0)
    memcpy(старые_переменные,к->переменные,sizeof(к->переменные));
    size_t старое_число_переменных=к->число_переменных;
    uint16_t старый_следующий_регистр=к->следующий_регистр;
    int старый_возврат=к->возврат_встретился;
    unsigned старая_глубина_управления=к->глубина_управления;
    size_t старая_глубина_циклов=к->глубина_циклов;
    size_t старые_прерывания=к->число_прерываний;
    size_t старые_продолжения=к->число_продолжений;

    memset(к->переменные,0,sizeof(к->переменные));
    к->число_переменных=0;
    к->следующий_регистр=0;
    к->возврат_встретился=0;
    к->глубина_управления=0;
    к->глубина_циклов=0;
    к->число_прерываний=0;
    к->число_продолжений=0;
    if(!имя_доступно(к,имя)) ОШИБКА_ПРАВИЛА();

    ОписаниеПравила правило;
    memset(&правило,0,sizeof(правило));
    strcpy(правило.имя,имя);
    if(слово(к,"принимает")) {
        if(!следующий(к)) ОШИБКА_ПРАВИЛА();
        for(;;) {
            if(правило.число_параметров>=254u) {
                ошибка_текста(к,"нативное правило не может принимать больше 254 параметров");
                ОШИБКА_ПРАВИЛА();
            }
            if(к->текущий.вид!=ТОК_СЛОВО) {
                ошибка_текста(к,"после «принимает» ожидается имя параметра");
                ОШИБКА_ПРАВИЛА();
            }
            char параметр[РАЗМЕР_СЛОВА];
            strcpy(параметр,к->текущий.текст);
            if(!имя_доступно(к,параметр)||!принять_имя(к,параметр)) ОШИБКА_ПРАВИЛА();
            uint8_t регистр;
            if(!регистр_создать(к,&регистр)) ОШИБКА_ПРАВИЛА();
            strcpy(к->переменные[к->число_переменных].имя,параметр);
            к->переменные[к->число_переменных].регистр=регистр;
            ++к->число_переменных;
            правило.параметры[правило.число_параметров++]=регистр;
            if(к->текущий.вид==ТОК_ЗАПЯТАЯ||слово(к,"и")) {
                if(!следующий(к)) ОШИБКА_ПРАВИЛА();
                continue;
            }
            break;
        }
    }
    if(слово(к,"повторять")||слово(к,"то")||слово(к,"делать"))
        if(!следующий(к)) ОШИБКА_ПРАВИЛА();

    size_t переход=к->число_инструкций;
    if(!добавить_инструкцию(к,(ЛексусИнструкция){ЛЕКСУС_ОП_ПЕРЕХОД,0,0,0,0})) ОШИБКА_ПРАВИЛА();
    if(к->число_инструкций>UINT32_MAX) {
        ошибка_текста(к,"адрес правила выходит за пределы байткода"); ОШИБКА_ПРАВИЛА();
    }
    правило.вход=(uint32_t)к->число_инструкций;
    if(!добавить_описание_правила(к,&правило)) ОШИБКА_ПРАВИЛА();
    ++к->глубина_правила;

    int ok=тело_до(к,"конец",NULL);
    if(!ok||!требовать_слово(к,"конец","правило закрывается словом «конец»")) ОШИБКА_ПРАВИЛА();
    if(слово(к,"правило")||слово(к,"правила")) {
        if(!следующий(к)) ОШИБКА_ПРАВИЛА();
    } else if(к->текущий.вид==ТОК_СЛОВО) {
        ошибка_текста(к,"после «конец» ожидается слово «правило»");
        ОШИБКА_ПРАВИЛА();
    }
    if(!требовать_точку(к)) ОШИБКА_ПРАВИЛА();

    uint32_t nothing_index;
    uint8_t nothing_register;
    if(!добавить_значение_константу(к,лексус_ничто(),&nothing_index)||
       !регистр_создать(к,&nothing_register)||
       !добавить_инструкцию(к,(ЛексусИнструкция){ЛЕКСУС_ОП_КОНСТАНТА,nothing_register,0,0,nothing_index})||
       !добавить_инструкцию(к,(ЛексусИнструкция){ЛЕКСУС_ОП_ВОЗВРАТ,0,nothing_register,0,0})) ОШИБКА_ПРАВИЛА();

    --к->глубина_правила;
    if(!patch_target(к,переход,к->число_инструкций)) ОШИБКА_ПРАВИЛА();
    memcpy(к->переменные,старые_переменные,sizeof(старые_переменные));
    к->число_переменных=старое_число_переменных;
    к->следующий_регистр=старый_следующий_регистр;
    к->возврат_встретился=старый_возврат;
    к->глубина_управления=старая_глубина_управления;
    к->глубина_циклов=старая_глубина_циклов;
    к->число_прерываний=старые_прерывания;
    к->число_продолжений=старые_продолжения;
    free(старые_переменные);
#undef ОШИБКА_ПРАВИЛА
    return 1;
}
static int разобрать_вызов_правила(Компилятор *к)
{
    char имя[РАЗМЕР_СЛОВА];
    if(!следующий(к)||!принять_имя(к,имя)) return 0;
    uint8_t аргументы[254],число_аргументов=0;
    if(к->текущий.вид==ТОК_ОТКРЫТЬ) {
        if(!разобрать_аргументы_в_скобках(к,аргументы,&число_аргументов)) return 0;
    } else if(слово(к,"с")) {
        if(!следующий(к)) return 0;
        for(;;) {
            if(число_аргументов>=254u) {
                ошибка_текста(к,"вызов правила не может передавать больше 254 аргументов");
                return 0;
            }
            if(!выражение(к,&аргументы[число_аргументов])) return 0;
            ++число_аргументов;
            if(к->текущий.вид==ТОК_ЗАПЯТАЯ) {
                if(!следующий(к)) return 0;
                continue;
            }
            break;
        }
    }
    if(!требовать_точку(к)) return 0;
    uint8_t назначение;
    if(!регистр_создать(к,&назначение)||
       !добавить_вызов(к,имя,назначение,аргументы,число_аргументов)) return 0;
    освободить_временные(к);
    return 1;
}
static int войти_в_управляющий_блок(Компилятор *к)
{
    /* Защита от переполнения C-стека на патологически вложенном исходнике. */
    if(к->глубина_управления>=128u) {
        ошибка_текста(к,"превышена максимальная глубина вложенности управляющих блоков (128)");
        return 0;
    }
    ++к->глубина_управления;
    return 1;
}
static int разобрать_если(Компилятор *к)
{
    size_t выходы[128],число_выходов=0;
    int временная_форма=strcmp(к->текущий.текст,"когда")==0;
    uint8_t условие;
    if(!следующий(к)||!выражение(к,&условие)) return 0;
    if(временная_форма&&слово(к,"наступит")) {
        ошибка_текста(к,"временная форма «когда ... наступит» требует интерфейса событий; эта сборка умеет только условное «когда ... то»");
        return 0;
    }
    if(!требовать_слово(к,"то","после условия «если» требуется слово «то»")) return 0;
    for(;;) {
        size_t ложный=к->число_инструкций;
        if(!добавить_инструкцию(к,(ЛексусИнструкция){
            ЛЕКСУС_ОП_ПЕРЕХОД_ЕСЛИ_ЛОЖЬ,0,условие,0,0})) return 0;
        освободить_временные(к);
        if(!войти_в_управляющий_блок(к)) return 0;
        int ok=тело_до(к,"иначе","конец");
        --к->глубина_управления;
        if(!ok) return 0;
        if(!слово(к,"иначе")) {
            if(!patch_target(к,ложный,к->число_инструкций)) return 0;
            break;
        }
        if(число_выходов>=sizeof(выходы)/sizeof(выходы[0])) {
            ошибка_текста(к,"в одном условии допускается не более 128 ветвей «иначе если»");
            return 0;
        }
        выходы[число_выходов++]=к->число_инструкций;
        if(!добавить_инструкцию(к,(ЛексусИнструкция){
            ЛЕКСУС_ОП_ПЕРЕХОД,0,0,0,0}) ||
           !patch_target(к,ложный,к->число_инструкций) || !следующий(к)) return 0;
        if(слово(к,"если")) {
            if(!следующий(к)||!выражение(к,&условие)||
               !требовать_слово(к,"то","после условия «иначе если» требуется слово «то»")) return 0;
            continue;
        }
        if(!войти_в_управляющий_блок(к)) return 0;
        ok=тело_до(к,"конец",NULL);
        --к->глубина_управления;
        if(!ok) return 0;
        break;
    }
    for(size_t i=0;i<число_выходов;++i)
        if(!patch_target(к,выходы[i],к->число_инструкций)) return 0;
    if(!требовать_слово(к,"конец","замысел «если» закрывается словом «конец»")) return 0;
    if(слово(к,"если") && !следующий(к)) return 0;
    if(!требовать_точку(к)) return 0;
    освободить_временные(к);
    return 1;
}
static int разобрать_пока(Компилятор *к)
{
    size_t начало=к->число_инструкций;
    uint8_t условие;
    if(!следующий(к)||!выражение(к,&условие)||
       !требовать_слово(к,"повторять","после условия «пока» требуется слово «повторять»")) return 0;
    size_t выход=к->число_инструкций;
    if(!добавить_инструкцию(к,(ЛексусИнструкция){
        ЛЕКСУС_ОП_ПЕРЕХОД_ЕСЛИ_ЛОЖЬ,0,условие,0,0})) return 0;
    освободить_временные(к);
    if(!войти_в_управляющий_блок(к)||!начать_цикл(к,0)) return 0;
    int ok=тело_до(к,"конец",NULL);
    --к->глубина_управления;
    if(!ok || !требовать_слово(к,"конец","замысел «пока» закрывается словом «конец»")) return 0;
    if(слово(к,"пока") && !следующий(к)) return 0;
    if(!требовать_точку(к)) return 0;
    if(!добавить_инструкцию(к,(ЛексусИнструкция){
        ЛЕКСУС_ОП_ПЕРЕХОД,0,0,0,(uint32_t)начало})) return 0;
    if(!patch_target(к,выход,к->число_инструкций)||
       !закрыть_цикл(к,к->число_инструкций,начало)) return 0;
    освободить_временные(к);
    return 1;
}
static int разобрать_повторить(Компилятор *к)
{
    uint8_t количество;
    if(!следующий(к)||!выражение(к,&количество)||
       !требовать_слово(к,"раз","после количества требуется слово «раз»")) return 0;
    /* Совместимая семантика языка: дробное количество усекается к нулю. */
    if(!добавить_инструкцию(к,(ЛексусИнструкция){
        ЛЕКСУС_ОП_ЦЕЛОЕ,количество,количество,0,0})) return 0;
    size_t начало=к->число_инструкций;
    if(!добавить_инструкцию(к,(ЛексусИнструкция){
        ЛЕКСУС_ОП_ПОВТОРИТЬ_НАЧАЛО,0,количество,0,0})) return 0;
    size_t тело=к->число_инструкций;
    освободить_временные(к);
    if(!войти_в_управляющий_блок(к)||!начать_цикл(к,1)) return 0;
    int ok=тело_до(к,"конец",NULL);
    --к->глубина_управления;
    if(!ok || !требовать_слово(к,"конец","замысел «повторить» закрывается словом «конец»")) return 0;
    if(слово(к,"повторить") && !следующий(к)) return 0;
    if(!требовать_точку(к)) return 0;
    size_t шаг=к->число_инструкций;
    if(!добавить_инструкцию(к,(ЛексусИнструкция){
        ЛЕКСУС_ОП_ПОВТОРИТЬ_ШАГ,0,0,0,(uint32_t)тело})) return 0;
    if(!patch_target(к,начало,к->число_инструкций)||
       !закрыть_цикл(к,к->число_инструкций,шаг)) return 0;
    освободить_временные(к);
    return 1;
}
static int разобрать_где(Компилятор *к)
{
    char name[РАЗМЕР_СЛОВА]; uint8_t collection,item;
    if (слово(к,"для")) {
        if (!следующий(к)||
            !требовать_слово(к,"каждый","после «для» требуется «каждого»")) return 0;
    } else if (!следующий(к)) return 0;
    if(!принять_имя(к,name)||!имя_доступно(к,name)||
       !требовать_слово(к,"из","после имени элемента требуется предлог «из»")||
       !выражение(к,&collection)||
       !требовать_слово(к,"повторять","после перечня требуется слово «повторять»")) return 0;
    size_t scope_variables=к->число_переменных;
    if(scope_variables>252u) {
        ошибка_текста(к,"для локального обхода нужны два свободных регистра; сократите число внешних переменных");
        return 0;
    }
    uint8_t collection_slot;
    if(!регистр_создать(к,&collection_slot)||
       !добавить_инструкцию(к,(ЛексусИнструкция){ЛЕКСУС_ОП_КОПИЯ,collection_slot,collection,0,0})) return 0;
    item=collection;
    strcpy(к->переменные[к->число_переменных].имя,name);
    к->переменные[к->число_переменных].регистр=item;
    ++к->число_переменных;
    к->переменные[к->число_переменных].имя[0]='\0';
    к->переменные[к->число_переменных].регистр=collection_slot;
    ++к->число_переменных;
    освободить_временные(к);
    size_t begin=к->число_инструкций;
    if(!добавить_инструкцию(к,(ЛексусИнструкция){ЛЕКСУС_ОП_ИТЕРАЦИЯ_НАЧАТЬ,0,collection_slot,0,0})) return 0;
    size_t step=к->число_инструкций;
    if(!добавить_инструкцию(к,(ЛексусИнструкция){ЛЕКСУС_ОП_ИТЕРАЦИЯ_ШАГ,item,collection_slot,0,0})) return 0;
    size_t body=к->число_инструкций;
    if(!войти_в_управляющий_блок(к)||!начать_цикл(к,2)) return 0;
    int ok=тело_до(к,"конец",NULL);
    --к->глубина_управления;
    if(!ok||!требовать_слово(к,"конец","обход перечня закрывается словом «конец»")) return 0;
    if((слово(к,"где")||слово(к,"для"))&&!следующий(к)) return 0;
    if(!требовать_точку(к)||
       !добавить_инструкцию(к,(ЛексусИнструкция){ЛЕКСУС_ОП_ПЕРЕХОД,0,0,0,(uint32_t)step})) return 0;
    size_t end=к->число_инструкций;
    if(!patch_target(к,begin,end)||!patch_target(к,step,body)||
       !закрыть_цикл(к,end,step)) return 0;
    к->число_переменных=scope_variables;
    освободить_временные(к);
    return 1;
}
static int разобрать_действие(Компилятор *к)
{
    if (к->возврат_встретился) { ошибка_текста(к,"после «вернуть» другие действия недопустимы"); return 0; }
    if (слово(к,"правило")) return разобрать_правило(к);
    if (слово(к,"как")||слово(к,"позвать")) return разобрать_вызов_правила(к);
    if (слово(к,"пусть")) return объявить(к);
    if (слово(к,"сказать")) return сказать(к);
    if (слово(к,"спросить")) return спросить(к);
    if (слово(к,"вернуть")) return вернуть(к);
    if (слово(к,"почему")) return почему(к);
    if (слово(к,"где")||слово(к,"для")) return разобрать_где(к);
    if (слово(к,"прервать")) return разобрать_управление_циклом(к,0);
    if (слово(к,"продолжить")) return разобрать_управление_циклом(к,1);
    if (слово(к,"если")) return разобрать_если(к);
    if (слово(к,"пока")) return разобрать_пока(к);
    if (слово(к,"повторить")) return разобрать_повторить(к);
    if (слово(к,"увеличить")||слово(к,"уменьшить")||слово(к,"умножить")||слово(к,"разделить"))
        return изменить(к);
    ошибка_текста(к,"эта конструкция пока не поддерживается нативным компилятором");
    return 0;
}
static int собрать_таблицы_вызовов(Компилятор *к,ЛексусСкомпилированнаяПрограмма *out)
{
    ЛексусФункция *функции=NULL;
    ЛексусВызов *вызовы=NULL;
    uint8_t *ссылки=NULL;
    size_t всего_ссылок=0;
    if(к->число_правил) {
        функции=(ЛексусФункция*)calloc(к->число_правил,sizeof(*функции));
        if(!функции) { ошибка_текста(к,"не хватает памяти для таблицы функций"); return 0; }
    }
    if(к->число_вызовов) {
        вызовы=(ЛексусВызов*)calloc(к->число_вызовов,sizeof(*вызовы));
        if(!вызовы) {
            free(функции);
            ошибка_текста(к,"не хватает памяти для таблицы вызовов");
            return 0;
        }
    }
    for(size_t i=0;i<к->число_правил;++i) {
        if(всего_ссылок>SIZE_MAX-к->правила[i].число_параметров) goto переполнение;
        всего_ссылок+=к->правила[i].число_параметров;
    }
    for(size_t i=0;i<к->число_вызовов;++i) {
        if(всего_ссылок>SIZE_MAX-к->вызовы[i].число_аргументов) goto переполнение;
        всего_ссылок+=к->вызовы[i].число_аргументов;
    }
    if(всего_ссылок) {
        ссылки=(uint8_t*)malloc(всего_ссылок);
        if(!ссылки) {
            free(функции); free(вызовы);
            ошибка_текста(к,"не хватает памяти для параметров и аргументов");
            return 0;
        }
    }
    size_t смещение=0;
    for(size_t i=0;i<к->число_правил;++i) {
        функции[i].вход=к->правила[i].вход;
        функции[i].число_параметров=к->правила[i].число_параметров;
        if(функции[i].число_параметров) {
            memcpy(ссылки+смещение,к->правила[i].параметры,функции[i].число_параметров);
            функции[i].параметры=ссылки+смещение;
            смещение+=функции[i].число_параметров;
        }
    }
    for(size_t i=0;i<к->число_вызовов;++i) {
        size_t индекс_функции=0;
        while(индекс_функции<к->число_правил&&
              strcmp(к->вызовы[i].имя,к->правила[индекс_функции].имя)!=0)
            ++индекс_функции;
        if(индекс_функции==к->число_правил) {
            free(ссылки); free(функции); free(вызовы);
            ошибка_текста(к,"вызванное правило не объявлено в этой программе");
            return 0;
        }
        if(к->вызовы[i].число_аргументов!=к->правила[индекс_функции].число_параметров) {
            free(ссылки); free(функции); free(вызовы);
            ошибка_текста(к,"число аргументов вызова не совпадает с числом параметров правила");
            return 0;
        }
        if(индекс_функции>UINT32_MAX||i>UINT32_MAX) {
            free(ссылки); free(функции); free(вызовы);
            ошибка_текста(к,"таблица вызовов превышает адресуемый размер");
            return 0;
        }
        вызовы[i].функция=(uint32_t)индекс_функции;
        вызовы[i].назначение=к->вызовы[i].назначение;
        вызовы[i].число_аргументов=к->вызовы[i].число_аргументов;
        if(вызовы[i].число_аргументов) {
            memcpy(ссылки+смещение,к->вызовы[i].аргументы,вызовы[i].число_аргументов);
            вызовы[i].аргументы=ссылки+смещение;
            смещение+=вызовы[i].число_аргументов;
        }
        к->код[к->вызовы[i].инструкция].операнд=(uint32_t)i;
    }
    out->функции=функции;
    out->число_функций=к->число_правил;
    out->вызовы=вызовы;
    out->число_вызовов=к->число_вызовов;
    out->память_ссылок=ссылки;
    return 1;
переполнение:
    free(функции); free(вызовы);
    ошибка_текста(к,"слишком много ссылок на параметры и аргументы");
    return 0;
}

void лексус_скомпиляцию_освободить(ЛексусСкомпилированнаяПрограмма *p)
{
    if (!p) return;
    for (size_t i=0;i<p->число_констант;++i) лексус_значение_освободить(&p->константы[i]);
    free(p->константы); free(p->код);
    free(p->функции); free(p->вызовы); free(p->память_ссылок);
    memset(p,0,sizeof(*p));
}
int лексус_скомпилировать_с_профилями(const char *source,size_t length,unsigned profiles,
                                      ЛексусСкомпилированнаяПрограмма *out,char *err,size_t errn)
{
    if (!out||(!source&&length)) return 0;
    if (profiles&~(ЛЕКСУС_ПРОФИЛЬ_18_ПЛЮС|ЛЕКСУС_ПРОФИЛЬ_ЗУМЕР)) {
        if(err&&errn) snprintf(err,errn,"неизвестный языковой профиль");
        return 0;
    }
    memset(out,0,sizeof(*out));
    if (err&&errn) err[0]=0;
    Компилятор к; memset(&к,0,sizeof(к));
    к.источник=(const unsigned char*)source; к.длина=length; к.строка=1; к.столбец=1;
    к.профили=profiles;
    if (length>=3 && (unsigned char)source[0]==0xEF && (unsigned char)source[1]==0xBB && (unsigned char)source[2]==0xBF)
        к.позиция=3;
    к.ошибка=err; к.размер_ошибки=errn;
    if (!следующий(&к)) goto fail;
    while (к.текущий.вид!=ТОК_КОНЕЦ) {
        if (к.текущий.вид==ТОК_ТОЧКА) { if (!следующий(&к)) goto fail; continue; }
        if (!разобрать_действие(&к)) goto fail;
    }
    if (!к.число_инструкций) { ошибка_текста(&к,"пустая программа"); goto fail; }
    if (!к.возврат_встретился &&
        !добавить_инструкцию(&к,(ЛексусИнструкция){ЛЕКСУС_ОП_СТОП,0,0,0,0})) goto fail;
    if(!собрать_таблицы_вызовов(&к,out)) goto fail;
    out->код=к.код; out->число_инструкций=к.число_инструкций;
    out->константы=к.константы; out->число_констант=к.число_констант;
    out->регистры=к.максимум_регистров?к.максимум_регистров:1;
    free(к.правила); free(к.вызовы);
    free(к.прерывания); free(к.продолжения);
    return 1;
fail:
    if (err&&errn&&!err[0]) ошибка_текста(&к,"не удалось скомпилировать программу");
    for (size_t i=0;i<к.число_констант;++i) лексус_значение_освободить(&к.константы[i]);
    free(к.константы); free(к.код); free(к.правила); free(к.вызовы);
    free(к.прерывания); free(к.продолжения);
    лексус_скомпиляцию_освободить(out);
    return 0;
}

int лексус_скомпилировать(const char *source,size_t length,ЛексусСкомпилированнаяПрограмма *out,char *err,size_t errn)
{
    return лексус_скомпилировать_с_профилями(source,length,
        ЛЕКСУС_ПРОФИЛЬ_БЕЗ_ИЗМЕНЕНИЙ,out,err,errn);
}
