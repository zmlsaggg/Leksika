static int слово(Компилятор *к,const char *ожидание)
{
    return к->текущий.вид==ТОК_СЛОВО &&
           strcmp(каноническое_слово(к,к->текущий.текст),ожидание)==0;
}
static int требовать_слово(Компилятор *к,const char *ожидание,const char *сообщение)
{
    if (!слово(к,ожидание)) { ошибка_текста(к,сообщение); return 0; }
    return следующий(к);
}
static int требовать_точку(Компилятор *к)
{
    if (к->текущий.вид==ТОК_КОНЕЦ) return 1;
    if (к->текущий.вид!=ТОК_ТОЧКА) { ошибка_текста(к,"ожидается точка в конце действия"); return 0; }
    return следующий(к);
}
static int добавить_инструкцию(Компилятор *к, ЛексусИнструкция x)
{
    if (к->число_инструкций>=ЛИМИТ_ИНСТРУКЦИЙ) { ошибка_текста(к,"превышен предел размера программы"); return 0; }
    if (к->число_инструкций==к->ёмкость_инструкций) {
        size_t cap=к->ёмкость_инструкций?к->ёмкость_инструкций*2:64;
        ЛексусИнструкция *p=(ЛексусИнструкция*)realloc(к->код,cap*sizeof(*p));
        if (!p) { ошибка_текста(к,"не хватает памяти для байткода"); return 0; }
        к->код=p; к->ёмкость_инструкций=cap;
    }
    к->код[к->число_инструкций++]=x; return 1;
}
static int регистр_создать(Компилятор *к,uint8_t *r)
{
    if (к->следующий_регистр>=256) { ошибка_текста(к,"в этой версии программы допускается не более 256 одновременно используемых регистров"); return 0; }
    *r=(uint8_t)к->следующий_регистр++;
    if (к->следующий_регистр>к->максимум_регистров) к->максимум_регистров=к->следующий_регистр;
    return 1;
}

static int добавить_описание_правила(Компилятор *к,const ОписаниеПравила *правило)
{
    for(size_t i=0;i<к->число_правил;++i)
        if(strcmp(к->правила[i].имя,правило->имя)==0) {
            ошибка_текста(к,"правило с таким именем уже объявлено"); return 0;
        }
    if(к->число_правил==к->ёмкость_правил) {
        size_t новая=к->ёмкость_правил?к->ёмкость_правил*2:8;
        if(новая<к->ёмкость_правил||новая>SIZE_MAX/sizeof(*к->правила)) {
            ошибка_текста(к,"слишком много правил в программе"); return 0;
        }
        ОписаниеПравила *память=(ОписаниеПравила*)realloc(к->правила,новая*sizeof(*память));
        if(!память) { ошибка_текста(к,"не хватает памяти для таблицы правил"); return 0; }
        к->правила=память; к->ёмкость_правил=новая;
    }
    к->правила[к->число_правил++]=*правило;
    return 1;
}
static int добавить_вызов(Компилятор *к,const char *имя,uint8_t назначение,
                          const uint8_t *аргументы,uint8_t число_аргументов)
{
    if(к->число_вызовов==к->ёмкость_вызовов) {
        size_t новая=к->ёмкость_вызовов?к->ёмкость_вызовов*2:16;
        if(новая<к->ёмкость_вызовов||новая>SIZE_MAX/sizeof(*к->вызовы)) {
            ошибка_текста(к,"слишком много вызовов правил"); return 0;
        }
        ОтложенныйВызов *память=(ОтложенныйВызов*)realloc(к->вызовы,новая*sizeof(*память));
        if(!память) { ошибка_текста(к,"не хватает памяти для таблицы вызовов"); return 0; }
        к->вызовы=память; к->ёмкость_вызовов=новая;
    }
    size_t инструкция=к->число_инструкций;
    if(!добавить_инструкцию(к,(ЛексусИнструкция){ЛЕКСУС_ОП_ВЫЗОВ,0,0,0,0})) return 0;
    ОтложенныйВызов *вызов=&к->вызовы[к->число_вызовов++];
    memset(вызов,0,sizeof(*вызов));
    вызов->инструкция=инструкция;
    strcpy(вызов->имя,имя);
    вызов->назначение=назначение;
    вызов->число_аргументов=число_аргументов;
    if(число_аргументов) memcpy(вызов->аргументы,аргументы,число_аргументов);
    return 1;
}
static int добавить_значение_константу(Компилятор *к,ЛексусЗначение value,uint32_t *index)
{
    size_t начало=к->число_констант>64?к->число_констант-64:0;
    for (size_t i=начало;i<к->число_констант;++i) {
        int equal=0;
        ЛексусОшибка compare=лексус_равно(к->константы[i],value,&equal);
        if (compare.код==ЛЕКСУС_ОК && equal) {
            лексус_значение_освободить(&value);
            *index=(uint32_t)i;
            return 1;
        }
    }
    if (к->число_констант>=ЛИМИТ_КОНСТАНТ) {
        лексус_значение_освободить(&value);
        ошибка_текста(к,"превышено число констант"); return 0;
    }
    ЛексусЗначение *p=(ЛексусЗначение*)realloc(к->константы,(к->число_констант+1)*sizeof(*p));
    if (!p) {
        лексус_значение_освободить(&value);
        ошибка_текста(к,"не хватает памяти для таблицы констант"); return 0;
    }
    к->константы=p; к->константы[к->число_констант]=value;
    *index=(uint32_t)к->число_констант++; return 1;
}
static int добавить_константу(Компилятор *к,const char *text,uint32_t *index)
{
    ЛексусЗначение value=лексус_ничто();
    ЛексусОшибка e=лексус_число_создать(text,&value);
    if (e.код!=ЛЕКСУС_ОК) {
        ошибка_текста(к,e.сообщение?e.сообщение:"не удалось создать числовую константу");
        return 0;
    }
    return добавить_значение_константу(к,value,index);
}
static void регистр_освободить(Компилятор *к,uint8_t r)
{
    /* Временные регистры выделяются последовательно; освобождаем вершину.
       Регистры имён находятся ниже числа объявленных переменных. */
    if ((size_t)r>=к->число_переменных && (uint16_t)(r+1)==к->следующий_регистр)
        --к->следующий_регистр;
}

