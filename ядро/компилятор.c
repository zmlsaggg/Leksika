/* Падежный поиск имени.

   Устройство повторяет эталонный найти_имя из лексика/исполнитель.lek, но без
   областей видимости и модели: у нативного компилятора плоский список имён до
   254 записей, поэтому спорные случаи разрешаются порядком объявления.

   Порядок поиска:
     1. точное совпадение с объявленным именем (быстрый путь, без морфологии);
     2. формы склонения объявленных имён — от последнего объявленного к первому;
     3. если нужного падежа нет, но имя всё равно узнано, берём его: падеж это
        предпочтение шаблона команды, а не запрет (как в эталоне при падеж=None);
     4. если ничего не нашли — лемма из разбора и повторный поиск;
     5. иначе ошибка с подсказкой «заведённые имена: …». */

static const ЛексикаСловоформа *формы_имени(Компилятор *к,size_t индекс,size_t *число)
{
    ЛексикаСловоформа *место;
    if(!к->кэш_форм||индекс>=ЛИМИТ_ИМЁН||индекс>=к->число_переменных) { *число=0; return NULL; }
    место=к->кэш_форм+индекс*ЛЕКСИКА_ФОРМ_ПРЕДЕЛ;
    if(!к->кэш_готов[индекс]) {
        к->кэш_число[индекс]=лексика_склонить(к->переменные[индекс].имя,NULL,0,
                                              место,ЛЕКСИКА_ФОРМ_ПРЕДЕЛ);
        к->кэш_готов[индекс]=1;
    }
    *число=к->кэш_число[индекс];
    return место;
}

/* Совпадает ли поверхность со словом имени в нужной форме. падеж == 0 — любой. */
static int форма_подходит(Компилятор *к,size_t индекс,const char *поверхность,unsigned падеж)
{
    size_t число=0;
    const ЛексикаСловоформа *формы=формы_имени(к,индекс,&число);
    for(size_t i=0;i<число;++i)
        if(strcmp(формы[i].форма,поверхность)==0&&
           лексика_форма_подходит(&формы[i],падеж,0)) return 1;
    return 0;
}

/* Отказ, если регистр принадлежит постоянной. Ищем по регистру, а не по
   написанию: падежные формы одного имени должны вести к одной переменной. */
static int проверить_можно_менять(Компилятор *к,uint8_t регистр)
{
    for(size_t i=0;i<к->число_переменных;++i)
        if(к->переменные[i].регистр==регистр && к->переменные[i].неизменяемая) {
            char сообщение[512];
            snprintf(сообщение,sizeof(сообщение),
                     "«%s» объявлено постоянной и не меняется; замените объявление словом «пусть», если значение должно меняться",
                     к->переменные[i].имя[0] ? к->переменные[i].имя : "имя");
            ошибка_текста(к,сообщение);
            return 0;
        }
    return 1;
}
static int найти_переменную_в_падеже(Компилятор *к,const char *name,unsigned падеж,uint8_t *r)
{
    char поверхность[РАЗМЕР_СЛОВА];
    ЛексикаСловоформа разбор[32];
    size_t число;
    if(!лексика_нижнее(name,поверхность,sizeof(поверхность))) return 0;

    for(size_t i=0;i<к->число_переменных;++i)
        if(strcmp(к->переменные[i].имя,поверхность)==0) { *r=к->переменные[i].регистр; return 1; }

    /* Ближние объявления важнее: свежая переменная перекрывает старую омонимию. */
    for(size_t сколько=0;сколько<к->число_переменных;++сколько)
        if(форма_подходит(к,к->число_переменных-1-сколько,поверхность,падеж)) {
            *r=к->переменные[к->число_переменных-1-сколько].регистр; return 1;
        }
    if(падеж)
        for(size_t сколько=0;сколько<к->число_переменных;++сколько)
            if(форма_подходит(к,к->число_переменных-1-сколько,поверхность,0)) {
                *r=к->переменные[к->число_переменных-1-сколько].регистр; return 1;
            }

    /* Последняя попытка: лемма из разбора — там основа может отличаться от
       основы склонения («элементу» → «элемент», а не «элемента»). */
    число=лексика_разобрать(поверхность,разбор,32);
    for(size_t j=0;j<число;++j)
        for(size_t i=0;i<к->число_переменных;++i)
            if(strcmp(к->переменные[i].имя,разбор[j].форма)==0) {
                *r=к->переменные[i].регистр; return 1;
            }
    return 0;
}

/* Падеж 0 означает «любая форма»: так работает поиск в выражении. Отдельного
 * вызова без падежа не нужно, поэтому голый «найти_переменную» не заводится:
 * неиспользуемая функция давала предупреждение в сборке C++-обёртки. */

/* Точное совпадение с записью в таблице имён — без морфологии. Нужно там, где
 * падежная вольность была бы ошибкой: «где элемент из элементы» заводит
 * переменную цикла, и «элемент» не должен считаться повторным объявлением. */
static int имя_занято_точно(Компилятор *к,const char *name)
{
    char поверхность[РАЗМЕР_СЛОВА];
    if(!лексика_нижнее(name,поверхность,sizeof(поверхность))) return 0;
    for(size_t i=0;i<к->число_переменных;++i)
        if(strcmp(к->переменные[i].имя,поверхность)==0) return 1;
    return 0;
}

/* Диагностика вместо тупика: подсказываем похожее имя или перечисляем
 * заведённые. Никакой модели для этого не нужно — только морфология. */
static void ошибка_неизвестного_имени(Компилятор *к,const char *name,const char *где)
{
    char поверхность[РАЗМЕР_СЛОВА],сообщение[512],заведённые[256]="";
    size_t занято=0;
    if(!лексика_нижнее(name,поверхность,sizeof(поверхность)))
        snprintf(поверхность,sizeof(поверхность),"%s",name);
    for(size_t сколько=0;сколько<к->число_переменных;++сколько) {
        size_t i=к->число_переменных-1-сколько;
        if(форма_подходит(к,i,поверхность,0)) {
            snprintf(сообщение,sizeof(сообщение),
                     "%s: имя «%s» не объявлено, но похоже на «%s» — объявленное имя узнаётся в любой падежной форме",
                     где,name,к->переменные[i].имя);
            ошибка_текста(к,сообщение);
            return;
        }
    }
    for(size_t i=0;i<к->число_переменных;++i) {
        int n=snprintf(заведённые+занято,sizeof(заведённые)-занято,"%s%s",
                       i?", ":"",к->переменные[i].имя);
        if(n<0||(size_t)n>=sizeof(заведённые)-занято) { заведённые[занято]=0; break; }
        занято+=(size_t)n;
    }
    if(к->число_переменных)
        snprintf(сообщение,sizeof(сообщение),
                 "%s: имя «%s» не объявлено; заведённые имена: %s",где,name,заведённые);
    else
        snprintf(сообщение,sizeof(сообщение),
                 "%s: имя «%s» не объявлено; заведите имя словом «пусть»: пусть счёт равно нулю",
                 где,name);
    ошибка_текста(к,сообщение);
}
