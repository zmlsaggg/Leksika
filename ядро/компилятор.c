#define ЛИМИТ_ИНСТРУКЦИЙ 1000000u
#define ЛИМИТ_КОНСТАНТ 100000u
#define ЛИМИТ_ИМЁН 256u
#define РАЗМЕР_СЛОВА 256u

typedef enum { ТОК_КОНЕЦ, ТОК_СЛОВО, ТОК_ЧИСЛО, ТОК_ТОЧКА, ТОК_ЗАПЯТАЯ, ТОК_ОТКРЫТЬ, ТОК_ЗАКРЫТЬ, ТОК_РЕЧЬ } ВидТокена;
typedef struct {
    ВидТокена вид;
    char текст[РАЗМЕР_СЛОВА];
    const unsigned char *данные_речи;
    size_t длина_речи;
    size_t строка, столбец;
} Токен;
typedef struct {
    char имя[РАЗМЕР_СЛОВА];
    uint8_t регистр;
} Переменная;
typedef struct {
    int счётный;
    size_t начало_прерываний, начало_продолжений;
} КонтекстЦикла;
typedef struct {
    char имя[РАЗМЕР_СЛОВА];
    uint32_t вход;
    uint8_t число_параметров;
    uint8_t параметры[254];
} ОписаниеПравила;
typedef struct {
    size_t инструкция;
    char имя[РАЗМЕР_СЛОВА];
    uint8_t назначение;
    uint8_t число_аргументов;
    uint8_t аргументы[254];
} ОтложенныйВызов;
typedef struct {
    const unsigned char *источник;
    size_t длина, позиция, строка, столбец;
    unsigned профили;
    Токен текущий;
    ЛексусИнструкция *код;
    size_t число_инструкций, ёмкость_инструкций;
    ЛексусЗначение *константы;
    size_t число_констант;
    Переменная переменные[ЛИМИТ_ИМЁН];
    size_t число_переменных;
    uint16_t следующий_регистр, максимум_регистров;
    int возврат_встретился;
    unsigned глубина_управления;
    КонтекстЦикла циклы[128];
    size_t глубина_циклов;
    size_t *прерывания, число_прерываний, ёмкость_прерываний;
    size_t *продолжения, число_продолжений, ёмкость_продолжений;
    ОписаниеПравила *правила; size_t число_правил, ёмкость_правил;
    ОтложенныйВызов *вызовы; size_t число_вызовов, ёмкость_вызовов;
    unsigned глубина_правила;
    char *ошибка;
    size_t размер_ошибки;
} Компилятор;

static void ошибка_текста(Компилятор *к, const char *текст)
{
    if (!к->ошибка || !к->размер_ошибки || к->ошибка[0]) return;
    snprintf(к->ошибка, к->размер_ошибки, "строка %zu, столбец %zu: %s",
             к->текущий.строка, к->текущий.столбец, текст);
}
static int utf8_символ(const unsigned char *s, size_t n, size_t *ширина, uint32_t *код)
{
    if (!n) return 0;
    unsigned char a=s[0]; unsigned k; uint32_t c;
    if (a<0x80) { k=1; c=a; }
    else if (a>=0xC2 && a<=0xDF) { k=2; c=a&0x1F; }
    else if (a>=0xE0 && a<=0xEF) { k=3; c=a&0x0F; }
    else if (a>=0xF0 && a<=0xF4) { k=4; c=a&0x07; }
    else return 0;
    if (k>n) return 0;
    for (unsigned i=1;i<k;++i) {
        unsigned char b=s[i];
        if ((b&0xC0)!=0x80) return 0;
        if (i==1 && ((a==0xE0&&b<0xA0)||(a==0xED&&b>=0xA0)||
                     (a==0xF0&&b<0x90)||(a==0xF4&&b>=0x90))) return 0;
        c=(c<<6)|(b&0x3F);
    }
    if (c>0x10FFFF || (c>=0xD800&&c<=0xDFFF)) return 0;
    *ширина=k; *код=c; return 1;
}
static size_t записать_utf8(uint32_t c, char *out)
{
    if (c<0x80) { out[0]=(char)c; return 1; }
    if (c<0x800) { out[0]=(char)(0xC0|(c>>6)); out[1]=(char)(0x80|(c&63)); return 2; }
    if (c<0x10000) {
        out[0]=(char)(0xE0|(c>>12)); out[1]=(char)(0x80|((c>>6)&63));
        out[2]=(char)(0x80|(c&63)); return 3;
    }
    out[0]=(char)(0xF0|(c>>18)); out[1]=(char)(0x80|((c>>12)&63));
    out[2]=(char)(0x80|((c>>6)&63)); out[3]=(char)(0x80|(c&63)); return 4;
}
static int русская_буква(uint32_t c)
{
    return (c>=0x0400&&c<=0x052F)||(c>=0x2DE0&&c<=0x2DFF)||(c>=0xA640&&c<=0xA69F);
}
static int латинская_буква(uint32_t c)
{
    return (c>='A'&&c<='Z')||(c>='a'&&c<='z');
}
static int граница_исходного_слова(Компилятор *к,size_t позиция)
{
    if(позиция>=к->длина) return 1;
    size_t ширина=0; uint32_t код=0;
    if(!utf8_символ(к->источник+позиция,к->длина-позиция,&ширина,&код)) return 0;
    return !(русская_буква(код)||латинская_буква(код)||(код>='0'&&код<='9')||код=='-');
}
static int исходник_совпадает(Компилятор *к,size_t позиция,const char *слово)
{
    size_t длина=strlen(слово), i=0;
    if(позиция>к->длина || длина>к->длина-позиция) return 0;
    while(i<длина) {
        size_t a=0,b=0; uint32_t x=0,y=0;
        if(!utf8_символ(к->источник+позиция+i,к->длина-позиция-i,&a,&x) ||
           !utf8_символ((const unsigned char *)слово+i,длина-i,&b,&y) || a!=b) return 0;
        if(x>=0x0410 && x<=0x042F) x+=0x20;
        else if(x==0x0401) x=0x0451;
        if(x!=y) return 0;
        i+=a;
    }
    return 1;
}
static void шаг_исходника(Компилятор *к,size_t ширина,uint32_t код)
{
    к->позиция+=ширина;
    if(код==10) { ++к->строка; к->столбец=1; }
    else ++к->столбец;
}
/* Речь — один токен с указателем и длиной; содержимое не копируется в буфер слова. */
static int получить_токен_речи(Компилятор *к,Токен *t)
{
    static const char начало[]="речь";
    static const char конец[]="конец";
    static const char речи[]="речи";
    size_t старт=к->позиция;
    if(!исходник_совпадает(к,старт,начало) ||
       !граница_исходного_слова(к,старт+sizeof(начало)-1)) return 0;
    for(size_t i=0;i<sizeof(начало)-1;++i) { ++к->позиция; ++к->столбец; }
    size_t тело=к->позиция;
    unsigned глубина=0;
    while(к->позиция<к->длина) {
        if(глубина==0 && исходник_совпадает(к,к->позиция,конец) &&
           граница_исходного_слова(к,к->позиция+sizeof(конец)-1)) {
            size_t after=к->позиция+sizeof(конец)-1;
            while(after<к->длина &&
                  (к->источник[after]==' '||к->источник[after]=='\t')) ++after;
            if(исходник_совпадает(к,after,речи) &&
               граница_исходного_слова(к,after+sizeof(речи)-1)) {
                size_t конец_тела=к->позиция;
                if(тело<конец_тела &&
                   (к->источник[тело]==' '||к->источник[тело]=='\t')) ++тело;
                if(тело<конец_тела &&
                   (к->источник[конец_тела-1]==' '||к->источник[конец_тела-1]=='\t')) --конец_тела;
                t->вид=ТОК_РЕЧЬ;
                t->данные_речи=к->источник+тело;
                t->длина_речи=конец_тела-тело;
                while(к->позиция<after+sizeof(речи)-1) {
                    size_t ширина=0; uint32_t код=0;
                    if(!utf8_символ(к->источник+к->позиция,к->длина-к->позиция,&ширина,&код)) {
                        ошибка_текста(к,"некорректная UTF-8-последовательность в конце блока речи");
                        return -1;
                    }
                    шаг_исходника(к,ширина,код);
                }
                return 1;
            }
        }
        size_t ширина=0; uint32_t код=0;
        if(!utf8_символ(к->источник+к->позиция,к->длина-к->позиция,&ширина,&код)) {
            ошибка_текста(к,"некорректная UTF-8-последовательность внутри блока речи");
            return -1;
        }
        if(код=='(') ++глубина;
        else if(код==')'&&глубина) --глубина;
        шаг_исходника(к,ширина,код);
    }
    ошибка_текста(к,"блок речи не закрыт: ожидается «конец речи»");
    return -1;
}
static int получить_токен(Компилятор *к, Токен *t)
{
    memset(t,0,sizeof(*t));
    while (к->позиция<к->длина) {
        unsigned char c=к->источник[к->позиция];
        if (c==' '||c=='\t'||c=='\r'||c=='\n') {
            if (c=='\n') { ++к->строка; к->столбец=1; }
            else ++к->столбец;
            ++к->позиция;
        } else break;
    }
    t->строка=к->строка; t->столбец=к->столбец;
    if (к->позиция>=к->длина) { t->вид=ТОК_КОНЕЦ; return 1; }
    unsigned char first=к->источник[к->позиция];
    к->текущий=*t;
    int речь=получить_токен_речи(к,t);
    if(речь<0) return 0;
    if(речь>0) return 1;
    if (first=='.') {
        t->вид=ТОК_ТОЧКА; t->текст[0]='.'; t->текст[1]=0;
        ++к->позиция; ++к->столбец; return 1;
    }
    if (first==',') {
        t->вид=ТОК_ЗАПЯТАЯ; t->текст[0]=','; t->текст[1]=0;
        ++к->позиция; ++к->столбец; return 1;
    }
    if (first=='(') {
        t->вид=ТОК_ОТКРЫТЬ; t->текст[0]='('; t->текст[1]=0;
        ++к->позиция; ++к->столбец; return 1;
    }
    if (first==')') {
        t->вид=ТОК_ЗАКРЫТЬ; t->текст[0]=')'; t->текст[1]=0;
        ++к->позиция; ++к->столбец; return 1;
    }
    if (first>='0'&&first<='9') {
        size_t n=0;
        while (к->позиция<к->длина) {
            unsigned char c=к->источник[к->позиция];
            if (c<'0'||c>'9') break;
            if (n+1>=sizeof(t->текст)) { к->текущий=*t; ошибка_текста(к,"слишком длинная запись числа"); return 0; }
            t->текст[n++]=(char)c; ++к->позиция; ++к->столбец;
        }
        t->текст[n]=0; t->вид=ТОК_ЧИСЛО; return 1;
    }
    size_t width=0; uint32_t cp=0;
    if (!utf8_символ(к->источник+к->позиция,к->длина-к->позиция,&width,&cp)) {
        к->текущий=*t; ошибка_текста(к,"некорректная последовательность UTF-8"); return 0;
    }
    if (русская_буква(cp)||латинская_буква(cp)) {
        size_t n=0; int латиница=0;
        while (к->позиция<к->длина) {
            if (!utf8_символ(к->источник+к->позиция,к->длина-к->позиция,&width,&cp)) {
                к->текущий=*t; ошибка_текста(к,"некорректная последовательность UTF-8"); return 0;
            }
            if (!(русская_буква(cp)||латинская_буква(cp))) break;
            if (латинская_буква(cp)) латиница=1;
            if (cp>=0x0410&&cp<=0x042F) cp+=0x20;
            else if (cp==0x0401) cp=0x0451;
            char encoded[4]; size_t count=записать_utf8(cp,encoded);
            if (n+count>=sizeof(t->текст)) { к->текущий=*t; ошибка_текста(к,"слишком длинное имя или слово"); return 0; }
            memcpy(t->текст+n,encoded,count); n+=count;
            к->позиция+=width; ++к->столбец;
        }
        t->текст[n]=0; t->вид=ТОК_СЛОВО;
        if (латиница) { к->текущий=*t; ошибка_текста(к,"латинские слова пока не поддерживаются нативным компилятором"); return 0; }
        return 1;
    }
    к->текущий=*t;
    char сообщение[160];
    snprintf(сообщение,sizeof(сообщение),
             "недопустимый символ U+%04X; в этом этапе используются русские слова, числа цифрами и точка",
             (unsigned)cp);
    ошибка_текста(к,сообщение);
    return 0;
}
static int следующий(Компилятор *к)
{
    if (!получить_токен(к,&к->текущий)) return 0;
    return 1;
}
