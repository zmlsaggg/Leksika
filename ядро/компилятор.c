static int прочитать_числительное(Компилятор *к,uint64_t *результат)
{
    uint64_t всего=0,часть=0,значение=0;
    int найдено=0,группа_начата=0;
    while(к->текущий.вид==ТОК_СЛОВО) {
        if(найти_числовое_слово(ЧИСЛИТЕЛЬНЫЕ_СЛОВА,
           sizeof(ЧИСЛИТЕЛЬНЫЕ_СЛОВА)/sizeof(ЧИСЛИТЕЛЬНЫЕ_СЛОВА[0]),
           к->текущий.текст,&значение)) {
            if(часть>UINT64_MAX-значение) {
                ошибка_текста(к,"числительное слишком велико для текущей версии компилятора");
                return -1;
            }
            часть+=значение;
            группа_начата=1;
        } else if(найти_числовое_слово(ЧИСЛИТЕЛЬНЫЕ_МНОЖИТЕЛИ,
           sizeof(ЧИСЛИТЕЛЬНЫЕ_МНОЖИТЕЛИ)/sizeof(ЧИСЛИТЕЛЬНЫЕ_МНОЖИТЕЛИ[0]),
           к->текущий.текст,&значение)) {
            if(!группа_начата) часть=1;
            if(значение && часть>UINT64_MAX/значение) {
                ошибка_текста(к,"числительное слишком велико для текущей версии компилятора");
                return -1;
            }
            uint64_t произведение=часть*значение;
            if(всего>UINT64_MAX-произведение) {
                ошибка_текста(к,"числительное слишком велико для текущей версии компилятора");
                return -1;
            }
            всего+=произведение;
            часть=0;
            группа_начата=0;
        } else break;
        найдено=1;
        if(!следующий(к)) return -1;
    }
    if(!найдено) return 0;
    if(всего>UINT64_MAX-часть) {
        ошибка_текста(к,"числительное слишком велико для текущей версии компилятора");
        return -1;
    }
    *результат=всего+часть;
    return 1;
}

