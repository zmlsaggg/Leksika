#include "компилятор.h"
#include "морфология.h"
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#define ЛИМИТ_ИНСТРУКЦИЙ 1000000u
#define ЛИМИТ_КОНСТАНТ 100000u
#define ЛИМИТ_ИМЁН 256u
/* Глубина вложенности выражений и блоков: рекурсивный разбор без предела
   роняет процесс на «((((…» и «не не не…». 128 уровней — это всё ещё
   недостижимо для осмысленного кода, но влезает в стек главного потока
   Windows, который по умолчанию всего 1 МБ (Linux даёт 8 МБ, и прежние
   256 уровней на Windows роняли тесты переполнением стека). */
#define ЛИМИТ_ВЛОЖЕННОСТИ 128u
#define РАЗМЕР_СЛОВА 256u

typedef enum { ТОК_КОНЕЦ, ТОК_СЛОВО, ТОК_ЧИСЛО, ТОК_ТОЧКА, ТОК_ЗАПЯТАЯ, ТОК_ОТКРЫТЬ, ТОК_ЗАКРЫТЬ, ТОК_РЕЧЬ } ВидТокена;

/* Часть блока речи: либо текст, либо выражение, которое надо вычислить и
 * вставить. Указатели смотрят в исходник — копировать текст не нужно.
 * «((» и «))» дают обычные скобки: так в речь попадает живая скобка. */
typedef struct {
    int выражение;
    const unsigned char *начало;
    size_t байты;
} ЧастьРечи;

#define ЛИМИТ_ЧАСТЕЙ_РЕЧИ 64u
typedef struct {
    ВидТокена вид;
    char текст[РАЗМЕР_СЛОВА];
    /* Блок речи приходит частями: текст и вложенные выражения. Тело целиком
       больше не хранится — интерполяция встраивается при компиляции. */
    ЧастьРечи части_речи[ЛИМИТ_ЧАСТЕЙ_РЕЧИ];
    size_t число_частей_речи;
    size_t строка, столбец;
} Токен;
typedef struct {
    char имя[РАЗМЕР_СЛОВА];
    uint8_t регистр;
    /* Объявлена словом «постоянная»: присваивать и менять нельзя.
       Это const из C#, а не совет: попытка изменения — ошибка компиляции. */
    unsigned неизменяемая;
} Переменная;
typedef struct {
    int счётный;
    size_t начало_прерываний, начало_продолжений;
} КонтекстЦикла;
typedef struct {
    char имя[РАЗМЕР_СЛОВА];
    uint32_t вход;
    uint8_t число_параметров;
    uint8_t параметры[254];
} ОписаниеПравила;
typedef struct {
    size_t инструкция;
    char имя[РАЗМЕР_СЛОВА];
    uint8_t назначение;
    uint8_t число_аргументов;
    uint8_t аргументы[254];
} ОтложенныйВызов;
typedef struct {
    const unsigned char *источник;
    size_t длина, позиция, строка, столбец;
    size_t строка_последнего_токена;
    unsigned профили;
    Токен текущий;
    ЛексусИнструкция *код;
    size_t число_инструкций, ёмкость_инструкций;
    ЛексусПозицияИсходника *позиции;
    ЛексусЗначение *константы;
    size_t число_констант;
    Переменная переменные[ЛИМИТ_ИМЁН];
    size_t число_переменных;
    uint16_t следующий_регистр, максимум_регистров;
    int возврат_встретился;
    unsigned глубина_управления;
    КонтекстЦикла циклы[128];
    size_t глубина_циклов;
    size_t *прерывания, число_прерываний, ёмкость_прерываний;
    size_t *продолжения, число_продолжений, ёмкость_продолжений;
    ОписаниеПравила *правила; size_t число_правил, ёмкость_правил;
    ОтложенныйВызов *вызовы; size_t число_вызовов, ёмкость_вызовов;
    unsigned глубина_правила;
    /* Лексер речи: сколько частей текущего блока уже скомпилировано. */
    size_t позиция_части_речи;
    /* Текущая глубина рекурсии разбора. Общая на все уровни выражения и на
       тело блока: иначе обход одной ветви ограничен, а сумма всех — нет. */
    unsigned глубина_разбора;
    /* Граница «до» в цикле «для»: allow-флаг на один разбор выражения.
       Иначе «до 10» разбиралось бы как начало конструкции «до тех пор,
       пока». Та же роль, что «стоп-слова» у тела блока, только для
       выражения, которое иначе съело бы разделитель. */
    unsigned ждать_число;
    /* Склонение объявленных имён: считается по требованию и живёт до
       следующего объявления (тогда кэш сбрасывается). Без кэша поиск по
       250 именам на 1200 косвенных обращений занимал секунды.
       Сами словоформы лежат в куче: 256 × 24 × 168 байт — это почти
       мегабайт, а стандартный стек Windows меньше. Метки готовности
       остаются рядом с компилятором, они маленькие. */
    ЛексикаСловоформа *кэш_форм;
    size_t кэш_число[ЛИМИТ_ИМЁН];
    unsigned char кэш_готов[ЛИМИТ_ИМЁН];
    char *ошибка;
    size_t размер_ошибки;
} Компилятор;

static void ошибка_текста(Компилятор *к, const char *текст)
{
    if (!к->ошибка || !к->размер_ошибки || к->ошибка[0]) return;
    snprintf(к->ошибка, к->размер_ошибки, "строка %zu, столбец %zu: %s",
             к->текущий.строка, к->текущий.столбец, текст);
}

/* Общий вход в рекурсивную часть разбора. Отказ вместо падения: глубина
   свыше предела — ошибка компиляции с понятным текстом, а не SIGSEGV. */
static int войти_в_разбор(Компилятор *к)
{
    if (к->глубина_разбора >= ЛИМИТ_ВЛОЖЕННОСТИ) {
        ошибка_текста(к, "слишком глубокая вложенность: предел 128 уровней");
        return 0;
    }
    ++к->глубина_разбора;
    return 1;
}

static void выйти_из_разбора(Компилятор *к)
{
    if (к->глубина_разбора) --к->глубина_разбора;
}

static int utf8_символ(const unsigned char *s, size_t n, size_t *ширина, uint32_t *код)
{
    if (!n) return 0;
    unsigned char a=s[0]; unsigned k; uint32_t c;
    if (a<0x80) { k=1; c=a; }
    else if (a>=0xC2 && a<=0xDF) { k=2; c=a&0x1F; }
    else if (a>=0xE0 && a<=0xEF) { k=3; c=a&0x0F; }
    else if (a>=0xF0 && a<=0xF4) { k=4; c=a&0x07; }
    else return 0;
    if (k>n) return 0;
    for (unsigned i=1;i<k;++i) {
        unsigned char b=s[i];
        if ((b&0xC0)!=0x80) return 0;
        if (i==1 && ((a==0xE0&&b<0xA0)||(a==0xED&&b>=0xA0)||
                     (a==0xF0&&b<0x90)||(a==0xF4&&b>=0x90))) return 0;
        c=(c<<6)|(b&0x3F);
    }
    if (c>0x10FFFF || (c>=0xD800&&c<=0xDFFF)) return 0;
    *ширина=k; *код=c; return 1;
}
static size_t записать_utf8(uint32_t c, char *out)
{
    if (c<0x80) { out[0]=(char)c; return 1; }
    if (c<0x800) { out[0]=(char)(0xC0|(c>>6)); out[1]=(char)(0x80|(c&63)); return 2; }
    if (c<0x10000) {
        out[0]=(char)(0xE0|(c>>12)); out[1]=(char)(0x80|((c>>6)&63));
        out[2]=(char)(0x80|(c&63)); return 3;
    }
    out[0]=(char)(0xF0|(c>>18)); out[1]=(char)(0x80|((c>>12)&63));
    out[2]=(char)(0x80|((c>>6)&63)); out[3]=(char)(0x80|(c&63)); return 4;
}
static int русская_буква(uint32_t c)
{
    return (c>=0x0400&&c<=0x052F)||(c>=0x2DE0&&c<=0x2DFF)||(c>=0xA640&&c<=0xA69F);
}
static int латинская_буква(uint32_t c)
{
    return (c>='A'&&c<='Z')||(c>='a'&&c<='z');
}
static int граница_исходного_слова(Компилятор *к,size_t позиция)
{
    if(позиция>=к->длина) return 1;
    size_t ширина=0; uint32_t код=0;
    if(!utf8_символ(к->источник+позиция,к->длина-позиция,&ширина,&код)) return 0;
    return !(русская_буква(код)||латинская_буква(код)||(код>='0'&&код<='9')||код=='-');
}
static int исходник_совпадает(Компилятор *к,size_t позиция,const char *слово)
{
    size_t длина=strlen(слово), i=0;
    if(позиция>к->длина || длина>к->длина-позиция) return 0;
    while(i<длина) {
        size_t a=0,b=0; uint32_t x=0,y=0;
        if(!utf8_символ(к->источник+позиция+i,к->длина-позиция-i,&a,&x) ||
           !utf8_символ((const unsigned char *)слово+i,длина-i,&b,&y) || a!=b) return 0;
        if(x>=0x0410 && x<=0x042F) x+=0x20;
        else if(x==0x0401) x=0x0451;
        if(x!=y) return 0;
        i+=a;
    }
    return 1;
}
static void шаг_исходника(Компилятор *к,size_t ширина,uint32_t код)
{
    к->позиция+=ширина;
    if(код==10) { ++к->строка; к->столбец=1; }
    else ++к->столбец;
}
/* Читает блок «речь … конец речи» и разбирает его на части.
 * Возвращает 0 — это не блок речи, 1 — блок прочитан, -1 — ошибка. */
static int прочитать_части_речи(Компилятор *к, ЧастьРечи *части, size_t *число_частей)
{
    static const char начало[]="речь";
    static const char конец[]="конец";
    static const char речи[]="речи";
    size_t старт=к->позиция;
    if(!исходник_совпадает(к,старт,начало) ||
       !граница_исходного_слова(к,старт+sizeof(начало)-1)) return 0;
    for(size_t i=0;i<sizeof(начало)-1;++i) { ++к->позиция; ++к->столбец; }

    size_t начало_куска=к->позиция;
    unsigned глубина=0;
    size_t кусок_выражения=0;
    *число_частей=0;

    #define ДОБАВИТЬ_ЧАСТЬ(вид,с,дл) do { \
        if((дл)&&(*число_частей)<ЛИМИТ_ЧАСТЕЙ_РЕЧИ){ \
            части[*число_частей].выражение=(вид); \
            части[*число_частей].начало=(с); части[*число_частей].байты=(дл); \
            ++*число_частей; \
        } } while(0)

    while(к->позиция<к->длина) {
        if(глубина==0 && исходник_совпадает(к,к->позиция,конец) &&
           граница_исходного_слова(к,к->позиция+sizeof(конец)-1)) {
            size_t after=к->позиция+sizeof(конец)-1;
            while(after<к->длина &&
                  (к->источник[after]==' '||к->источник[after]=='\t')) ++after;
            if(исходник_совпадает(к,after,речи) &&
               граница_исходного_слова(к,after+sizeof(речи)-1)) {
                /* Хвост текста перед «конец речи» закрывает последнюю часть. */
                ДОБАВИТЬ_ЧАСТЬ(0,к->источник+начало_куска,к->позиция-начало_куска);
                while(к->позиция<after+sizeof(речи)-1) {
                    size_t ширина=0; uint32_t код=0;
                    if(!utf8_символ(к->источник+к->позиция,к->длина-к->позиция,&ширина,&код)) {
                        ошибка_текста(к,"некорректная UTF-8-последовательность в конце блока речи");
                        return -1;
                    }
                    шаг_исходника(к,ширина,код);
                }
                return 1;
            }
        }
        size_t ширина=0; uint32_t код=0;
        if(!utf8_символ(к->источник+к->позиция,к->длина-к->позиция,&ширина,&код)) {
            ошибка_текста(к,"некорректная UTF-8-последовательность внутри блока речи");
            return -1;
        }
        if(глубина==0 && (код=='('||код==')') && к->позиция+1<к->длина &&
           к->источник[к->позиция+1]==(unsigned char)код) {
            /* «((» в тексте речи — одна настоящая скобка, «))» — одна
               закрывающая. Так в речь попадают живые скобки, а не выражения.
               Обе скобки исходника съедаются, в текст идёт только первая. */
            ДОБАВИТЬ_ЧАСТЬ(0,к->источник+начало_куска,к->позиция-начало_куска);
            ДОБАВИТЬ_ЧАСТЬ(0,к->источник+к->позиция,1);
            шаг_исходника(к,ширина,код);
            шаг_исходника(к,1,(uint32_t)код);
            начало_куска=к->позиция;
            continue;
        }
        if(глубина==0 && код=='(') {
            ДОБАВИТЬ_ЧАСТЬ(0,к->источник+начало_куска,к->позиция-начало_куска);
            глубина=1;
            кусок_выражения=к->позиция+1;
            шаг_исходника(к,ширина,код);
            continue;
        }
        if(глубина>0) {
            if(код=='(') ++глубина;
            else if(код==')') {
                --глубина;
                if(глубина==0) {
                    ДОБАВИТЬ_ЧАСТЬ(1,к->источник+кусок_выражения,к->позиция-кусок_выражения);
                    шаг_исходника(к,ширина,код);
                    начало_куска=к->позиция;
                    continue;
                }
            }
        }
        шаг_исходника(к,ширина,код);
    }
    #undef ДОБАВИТЬ_ЧАСТЬ
    ошибка_текста(к,"блок речи не закрыт: ожидается «конец речи»");
    return -1;
}

static int получить_токен(Компилятор *к, Токен *t)
{
    memset(t,0,sizeof(*t));
    while (к->позиция<к->длина) {
        unsigned char c=к->источник[к->позиция];
        if (c==' '||c=='\t'||c=='\r'||c=='\n') {
            if (c=='\n') { ++к->строка; к->столбец=1; }
            else ++к->столбец;
            ++к->позиция;
        } else break;
    }
    t->строка=к->строка; t->столбец=к->столбец;
    if (к->позиция>=к->длина) { t->вид=ТОК_КОНЕЦ; return 1; }
    unsigned char first=к->источник[к->позиция];
    к->текущий=*t;
    {
        int речь=прочитать_части_речи(к,t->части_речи,&t->число_частей_речи);
        if(речь<0) return 0;
        if(речь>0) { t->вид=ТОК_РЕЧЬ; return 1; }
    }
    if (first=='.') {
        t->вид=ТОК_ТОЧКА; t->текст[0]='.'; t->текст[1]=0;
        ++к->позиция; ++к->столбец; return 1;
    }
    if (first==',') {
        t->вид=ТОК_ЗАПЯТАЯ; t->текст[0]=','; t->текст[1]=0;
        ++к->позиция; ++к->столбец; return 1;
    }
    if (first=='(') {
        t->вид=ТОК_ОТКРЫТЬ; t->текст[0]='('; t->текст[1]=0;
        ++к->позиция; ++к->столбец; return 1;
    }
    if (first==')') {
        t->вид=ТОК_ЗАКРЫТЬ; t->текст[0]=')'; t->текст[1]=0;
        ++к->позиция; ++к->столбец; return 1;
    }
    if (first>='0'&&first<='9') {
        size_t n=0;
        while (к->позиция<к->длина) {
            unsigned char c=к->источник[к->позиция];
            if (c<'0'||c>'9') break;
            if (n+1>=sizeof(t->текст)) { к->текущий=*t; ошибка_текста(к,"слишком длинная запись числа"); return 0; }
            t->текст[n++]=(char)c; ++к->позиция; ++к->столбец;
        }
        t->текст[n]=0; t->вид=ТОК_ЧИСЛО; return 1;
    }
    size_t width=0; uint32_t cp=0;
    if (!utf8_символ(к->источник+к->позиция,к->длина-к->позиция,&width,&cp)) {
        к->текущий=*t; ошибка_текста(к,"некорректная последовательность UTF-8"); return 0;
    }
    if (русская_буква(cp)||латинская_буква(cp)) {
        size_t n=0; int латиница=0;
        while (к->позиция<к->длина) {
            if (!utf8_символ(к->источник+к->позиция,к->длина-к->позиция,&width,&cp)) {
                к->текущий=*t; ошибка_текста(к,"некорректная последовательность UTF-8"); return 0;
            }
            if (!(русская_буква(cp)||латинская_буква(cp))) {
                /* Дефис внутри составного имени: «что-то», «когда-то».
                   В начале/конце токена и перед пробелом он остаётся
                   недопустимым символом, а не оператором вычитания. */
                if (cp=='-' && n>0 && к->позиция+width<к->длина) {
                    size_t nw=0; uint32_t nc=0;
                    if (utf8_символ(к->источник+к->позиция+width,
                                    к->длина-к->позиция-width,&nw,&nc) &&
                        русская_буква(nc)) {
                        (void)nw;
                        if (n+1>=sizeof(t->текст)) {
                            к->текущий=*t; ошибка_текста(к,"слишком длинное имя или слово"); return 0;
                        }
                        t->текст[n++]='-';
                        к->позиция+=width; ++к->столбец;
                        continue;
                    }
                }
                break;
            }
            if (латинская_буква(cp)) латиница=1;
            if (cp>=0x0410&&cp<=0x042F) cp+=0x20;
            else if (cp==0x0401) cp=0x0451;
            char encoded[4]; size_t count=записать_utf8(cp,encoded);
            if (n+count>=sizeof(t->текст)) { к->текущий=*t; ошибка_текста(к,"слишком длинное имя или слово"); return 0; }
            memcpy(t->текст+n,encoded,count); n+=count;
            к->позиция+=width; ++к->столбец;
        }
        t->текст[n]=0; t->вид=ТОК_СЛОВО;
        if (латиница) { к->текущий=*t; ошибка_текста(к,"латинские слова пока не поддерживаются нативным компилятором"); return 0; }
        return 1;
    }
    к->текущий=*t;
    char сообщение[192];
    snprintf(сообщение,sizeof(сообщение),
             "недопустимый символ U+%04X; в этом этапе используются русские слова, числа цифрами и точка",
             (unsigned)cp);
    ошибка_текста(к,сообщение);
    return 0;
}
static const char *каноническое_слово(const Компилятор *к,const char *текст);

/* Ищет слово «среди» до конца текущей строки. Нужно контекстному «выбор»:
   между ним и «среди» может стоять целое выражение — «выбор длина п среди»,
   и заглядывания на фиксированное число токенов не хватает.
   Возвращает 1, если слово найдено, состояние разбора не меняется. */
static int найти_среди_в_строке(Компилятор *к)
{
    size_t позиция=к->позиция, строка=к->строка, столбец=к->столбец;
    Токен текущий=к->текущий;
    char прежняя_ошибка[512];
    size_t длина_ошибки=0;
    if (к->ошибка && к->размер_ошибки) {
        прежняя_ошибка[0]='\0';
        if (к->ошибка[0]) {
            snprintf(прежняя_ошибка,sizeof(прежняя_ошибка),"%s",к->ошибка);
            длина_ошибки=strlen(прежняя_ошибка);
        }
    }
    int найдено=0;
    size_t исходная_строка=к->строка;
    /* Ограничиваем перебор сотней токенов: этого хватает на любое реальное
       значение, а на мусорном входе мы не уходим в долгий обход. */
    for (size_t шаг=0; шаг<100; ++шаг) {
        if (!получить_токен(к,&к->текущий)) break;
        if (к->строка!=исходная_строка) break;
        if (к->текущий.вид==ТОК_ТОЧКА) break;
        if (к->текущий.вид==ТОК_СЛОВО &&
            strcmp(каноническое_слово(к,к->текущий.текст),"среди")==0) { найдено=1; break; }
    }
    к->позиция=позиция; к->строка=строка; к->столбец=столбец;
    к->текущий=текущий;
    if (к->ошибка && к->размер_ошибки)
        memcpy(к->ошибка,прежняя_ошибка,длина_ошибки+1);
    return найдено;
}

/* Заглядывание вперёд на несколько токенов без изменения состояния разбора.
   Нужно контекстным словам: «выбор» открывает конструкцию только в связке
   «выбор … среди», иначе это обычное имя переменной.
   После взгляда позиция, строка, столбец и текущий токен возвращаются на
   место, а ошибка, выставленная пробным чтением, снимается: заглядывание
   не должно менять исход разбора. */
static int заглянуть_слово(Компилятор *к,const char *ожидание,size_t сдвиг)
{
    size_t позиция=к->позиция, строка=к->строка, столбец=к->столбец;
    Токен текущий=к->текущий;
    char прежняя_ошибка[512];
    size_t длина_ошибки=0;
    if (к->ошибка && к->размер_ошибки) {
        прежняя_ошибка[0]='\0';
        if (к->ошибка[0]) {
            snprintf(прежняя_ошибка,sizeof(прежняя_ошибка),"%s",к->ошибка);
            длина_ошибки=strlen(прежняя_ошибка);
        }
    }
    int совпало=0, прочитано=1;
    for (size_t i=0;i<сдвиг;++i) {
        if (!получить_токен(к,&к->текущий)) { прочитано=0; break; }
    }
    if (прочитано)
        совпало=к->текущий.вид==ТОК_СЛОВО &&
                strcmp(каноническое_слово(к,к->текущий.текст),ожидание)==0;
    к->позиция=позиция; к->строка=строка; к->столбец=столбец;
    к->текущий=текущий;
    /* Восстанавливаем ровно то, что было: либо прежний текст ошибки,
       либо её отсутствие. */
    if (к->ошибка && к->размер_ошибки)
        memcpy(к->ошибка,прежняя_ошибка,длина_ошибки+1);
    return совпало;
}
static int следующий(Компилятор *к)
{
    if (к->текущий.вид!=ТОК_КОНЕЦ)
        к->строка_последнего_токена=к->текущий.строка;
    if (!получить_токен(к,&к->текущий)) return 0;
    return 1;
}
