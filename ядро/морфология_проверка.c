/*
 * Проверки падежной морфологии нативного ядра.
 *
 * Каждая строка — обещание языка, а не деталь реализации: если здесь что-то
 * падает, значит «длина перечня» перестанет работать у пользователя.
 */
#include "морфология.h"
#include <stdio.h>
#include <string.h>

static const char *const ПАДЕЖИ_КОДЫ[ЛЕКСИКА_ПАДЕЖЕЙ] = {"им", "рд", "дт", "вн", "тв", "пр"};

static int проверить(const char *имя, int условие)
{
    printf("%s: %s\n", условие ? "OK" : "FAIL", имя);
    return условие ? 0 : 1;
}

/* Есть ли в склонении указанная форма с нужным падежом. */
/* Падеж и число задаются битовой маской; в проверках они складываются
 * оператором |, поэтому здесь unsigned, а не enum — MSVC иначе ругается C5287. */
static int есть_форма(const char *лемма, const char *род, int одушевлённое,
                      const char *форма, unsigned падеж)
{
    ЛексикаСловоформа формы[ЛЕКСИКА_ФОРМ_ПРЕДЕЛ];
    size_t n = лексика_склонить(лемма, род, одушевлённое, формы, ЛЕКСИКА_ФОРМ_ПРЕДЕЛ);
    for (size_t i = 0; i < n; ++i)
        if (strcmp(формы[i].форма, форма) == 0 && (формы[i].падеж & падеж)) return 1;
    return 0;
}

/* Полное совпадение набора словоформ в эталонном порядке. */
static int формы_совпали(const char *лемма, const char *род,
                         const char *const *ожидание, size_t ожидаемых)
{
    ЛексикаСловоформа формы[ЛЕКСИКА_ФОРМ_ПРЕДЕЛ];
    size_t n = лексика_склонить(лемма, род, 0, формы, ЛЕКСИКА_ФОРМ_ПРЕДЕЛ);
    if (n != ожидаемых) return 0;
    for (size_t i = 0; i < n; ++i)
        if (strcmp(формы[i].форма, ожидание[i]) != 0) return 0;
    return 1;
}

/* Знает ли разбор пару «основа + падеж». */
static int разбор_знает(const char *слово, const char *основа, unsigned падеж, unsigned число)
{
    ЛексикаСловоформа разбор[32];
    size_t n = лексика_разобрать(слово, разбор, 32);
    for (size_t i = 0; i < n; ++i)
        if (strcmp(разбор[i].форма, основа) == 0 && (разбор[i].падеж & падеж) &&
            (!число || (разбор[i].число & число))) return 1;
    return 0;
}

int main(void)
{
    int провалов = 0;
    puts("Падежная морфология нативного ядра");

    провалов += проверить("«сумма» даёт творительный «суммой»",
                          есть_форма("сумма", "ж", 0, "суммой", ЛЕКСИКА_ТВ));
    провалов += проверить("«сумма» даёт дательный «сумме»",
                          есть_форма("сумма", "ж", 0, "сумме", ЛЕКСИКА_ДТ));
    провалов += проверить("родительный множественного «сумм» без двойной «м»",
                          есть_форма("сумма", "ж", 0, "сумм", ЛЕКСИКА_МН_РД));
    провалов += проверить("«ручка» даёт «ручек», а не «ручок»",
                          есть_форма("ручка", "ж", 0, "ручек", ЛЕКСИКА_РД));
    провалов += проверить("«книга» даёт «книг» с беглой гласной",
                          есть_форма("книга", "ж", 0, "книг", ЛЕКСИКА_РД));
    провалов += проверить("«покупка» даёт «покупок»",
                          есть_форма("покупка", "ж", 0, "покупок", ЛЕКСИКА_РД));
    провалов += проверить("«станция» склоняется как «станцией», а не «станцей»",
                          есть_форма("станция", "ж", 0, "станцией", ЛЕКСИКА_ТВ) &&
                          !есть_форма("станция", "ж", 0, "станцей", ЛЕКСИКА_ТВ));
    провалов += проверить("«перечень» даёт мягкий творительный «перечнем»",
                          есть_форма("перечень", "м", 0, "перечнем", ЛЕКСИКА_ТВ));
    провалов += проверить("одушевлённое «студент» получает винительный «студента»",
                          есть_форма("студент", "м", 1, "студента", ЛЕКСИКА_ВН) &&
                          есть_форма("студент", "м", 0, "студент", ЛЕКСИКА_ВН));
    провалов += проверить("несклоняемое «пальто» остаётся одной формой",
                          есть_форма("пальто", "с", 0, "пальто", (unsigned)ЛЕКСИКА_РД | (unsigned)ЛЕКСИКА_ПР | (unsigned)ЛЕКСИКА_ТВ));
    провалов += проверить("«покупки» узнаётся и в единственном («покупку»)",
                          есть_форма("покупки", NULL, 0, "покупка", ЛЕКСИКА_ИМ) &&
                          есть_форма("покупки", NULL, 0, "покупку", ЛЕКСИКА_ВН));
    провалов += проверить("«число» получает отдельную парадигму «чисел/числам»",
                          есть_форма("число", "с", 0, "чисел", ЛЕКСИКА_МН_РД));
    провалов += проверить("«элемент» даёт родительный «элемента»",
                          есть_форма("элемент", "м", 0, "элемента", ЛЕКСИКА_РД));

    {
        /* Эталонный порядок: сначала единственное, потом множественное. */
        static const char *const станция[] = {
            "станция", "станции", "станцию", "станцией", "станций",
            "станциям", "станциями", "станциях"
        };
        static const char *const сумма[] = {
            "сумма", "суммы", "сумме", "сумму", "суммой", "сумм",
            "суммам", "суммами", "суммах"
        };
        static const char *const элемент[] = {
            "элемент", "элемента", "элементу", "элементом", "элементе",
            "элементы", "элементов", "элементам", "элементами", "элементах"
        };
        провалов += проверить("словоформы «станция» совпадают с эталоном",
                              формы_совпали("станция", "ж", станция, 8));
        провалов += проверить("словоформы «сумма» совпадают с эталоном",
                              формы_совпали("сумма", "ж", сумма, 9));
        провалов += проверить("словоформы «элемент» совпадают с эталоном",
                              формы_совпали("элемент", "м", элемент, 10));
    }

    провалов += проверить("разбор «счётчику» даёт дательный единственного",
                          разбор_знает("счётчику", "счётчик", ЛЕКСИКА_ДТ, ЛЕКСИКА_ЕД));
    провалов += проверить("разбор не зависит от регистра: «СУММУ»",
                          разбор_знает("СУММУ", "сумм", ЛЕКСИКА_ДТ, ЛЕКСИКА_ЕД));
    провалов += проверить("разбор «перечня» даёт родительный единственного",
                          разбор_знает("перечня", "перечн", ЛЕКСИКА_РД, ЛЕКСИКА_ЕД));
    провалов += проверить("разбор «покупками» даёт творительный множественного",
                          разбор_знает("покупками", "покупк", ЛЕКСИКА_ТВ, ЛЕКСИКА_МН));
    провалов += проверить("разбор держит тождественную форму «им/ед»",
                          разбор_знает("перечень", "перечень", ЛЕКСИКА_ИМ, ЛЕКСИКА_ЕД));
    провалов += проверить("разбор не выдумывает основ короче двух знаков",
                          !разбор_знает("я", "", ЛЕКСИКА_РД, ЛЕКСИКА_ЕД));

    {
        char нижнее[64];
        провалов += проверить("нижний регистр переводит «ЁЖ» в «ёж»",
                              лексика_нижнее("ЁЖ", нижнее, sizeof(нижнее)) &&
                              strcmp(нижнее, "ёж") == 0);
        провалов += проверить("нижний регистр не трогает знаки: «Счёт-2» → «счёт-2»",
                              лексика_нижнее("Счёт-2", нижнее, sizeof(нижнее)) &&
                              strcmp(нижнее, "счёт-2") == 0);
        провалов += проверить("нижний регистр отвергает обрезанный UTF-8",
                              !лексика_нижнее("\xd0", нижнее, sizeof(нижнее)));
        провалов += проверить("нижний регистр не переполняет буфер",
                              !лексика_нижнее("сумма", нижнее, 4));
    }

    {
        ЛексикаСловоформа форма;
        форма.падеж = ЛЕКСИКА_ВН;
        форма.число = ЛЕКСИКА_ЕД;
        strcpy(форма.форма, "сумму");
        провалов += проверить("форма подходит под требуемый падеж",
                              лексика_форма_подходит(&форма, ЛЕКСИКА_ВН, 0));
        провалов += проверить("форма не подходит под чужой падеж",
                              !лексика_форма_подходит(&форма, ЛЕКСИКА_РД, 0));
        провалов += проверить("нулевой падеж означает «любой»",
                              лексика_форма_подходит(&форма, 0, 0));
        провалов += проверить("число проверяется отдельно",
                              лексика_форма_подходит(&форма, 0, ЛЕКСИКА_ЕД) &&
                              !лексика_форма_подходит(&форма, 0, ЛЕКСИКА_МН));
    }

    for (unsigned i = 0; i < ЛЕКСИКА_ПАДЕЖЕЙ; ++i) {
        char имя[64];
        snprintf(имя, sizeof(имя), "падеж «%s» называется по-русски", ПАДЕЖИ_КОДЫ[i]);
        провалов += проверить(имя, strlen(лексика_название_падежа(ПАДЕЖИ_КОДЫ[i])) > 3);
    }

    printf("Итого: %s\n", провалов ? "есть ошибки" : "все проверки пройдены");
    return провалов ? 1 : 0;
}
