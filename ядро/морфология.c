/* Сборщик словоформ: одинаковые формы складываются в одну запись с
 * объединёнными метками. Омонимия («суммы» = рд ед и им мн) — норма языка. */
typedef struct {
    ЛексикаСловоформа *формы;
    size_t число;
    size_t предел;
} Сборщик;

static void доб(Сборщик *к, const char *слово, unsigned падеж, unsigned число)
{
    if (!слово || !*слово || !к->предел) return;
    char нижнее[160];
    if (!лексика_нижнее(слово, нижнее, sizeof(нижнее)))
        копировать(нижнее, sizeof(нижнее), слово);
    for (size_t i = 0; i < к->число; ++i) {
        if (strcmp(к->формы[i].форма, нижнее) == 0) {
            к->формы[i].падеж |= падеж;
            к->формы[i].число |= число;
            return;
        }
    }
    if (к->число >= к->предел) return;
    копировать(к->формы[к->число].форма, sizeof(к->формы[0].форма), нижнее);
    к->формы[к->число].падеж = падеж;
    к->формы[к->число].число = число;
    ++к->число;
}

/* родительный_множественного() из эталона. */
static void родительный_множественного(const char *слово, char *выход, size_t размер)
{
    char основа[160], перед[16], хвост[160];

    if (оканчивается(слово, "ка")) {
        без_последнего(слово, основа, sizeof(основа));
        предпоследний_знак(основа, перед, sizeof(перед));
        if (!*перед || гласный(перед)) { копировать(выход, размер, основа); return; }
        без_последнего(основа, хвост, sizeof(хвост));
        склеить(выход, размер, хвост,
                (оканчивается(перед, "ж") || оканчивается(перед, "ч") ||
                 оканчивается(перед, "ш") || оканчивается(перед, "щ")) ? "ек" : "ок");
        return;
    }
    if (оканчивается(слово, "га") || оканчивается(слово, "ха") ||
        оканчивается(слово, "жа") || оканчивается(слово, "ша") ||
        оканчивается(слово, "ча") || оканчивается(слово, "ща")) {
        без_последнего(слово, основа, sizeof(основа));
        предпоследний_знак(основа, перед, sizeof(перед));
        if (!*перед || гласный(перед)) { копировать(выход, размер, основа); return; }
        без_последнего(основа, хвост, sizeof(хвост));
        склеить(выход, размер, хвост, "ек");
        return;
    }
    if (оканчивается(слово, "а") || оканчивается(слово, "я") ||
        оканчивается(слово, "о") || оканчивается(слово, "е")) {
        без_последнего(слово, выход, размер);
        return;
    }
    if (оканчивается(слово, "ь"))  { без_последнего(слово, основа, sizeof(основа)); склеить(выход, размер, основа, "ей"); return; }
    if (оканчивается(слово, "й"))  { без_последнего(слово, основа, sizeof(основа)); склеить(выход, размер, основа, "ев"); return; }
    if (оканчивается(слово, "ец")) { без_последних(слово, 2, основа, sizeof(основа)); склеить(выход, размер, основа, "цев"); return; }
    if (шипящее(слово))            { склеить(выход, размер, слово, "ей"); return; }
    склеить(выход, размер, слово, "ов");
}

/* _единица() из эталона. */
static void единица(const char *слово, const char *род, int одушевлённое, Сборщик *к)
{
    char основа[160], форма[160];
    int женский;
    if (!слово || !*слово) return;
    женский = род && strcmp(род, "ж") == 0;

    if ((оканчивается(слово, "а") || оканчивается(слово, "я")) && знаков(слово) > 2) {
        if (оканчивается(слово, "ия")) {
            /* Эталонная ветка «ия» даёт «станцией» из основы «станции» —
             * лишняя «и» давала бы «станциией», поэтому творительный
             * строится как основа + «ей». */
            без_последнего(слово, основа, sizeof(основа));
            доб(к, слово, ЛЕКСИКА_ИМ, ЛЕКСИКА_ЕД);
            склеить(форма, sizeof(форма), основа, "и");  доб(к, форма, ЛЕКСИКА_РД, ЛЕКСИКА_ЕД);
            доб(к, форма, ЛЕКСИКА_ДТ, ЛЕКСИКА_ЕД);
            склеить(форма, sizeof(форма), основа, "ю");  доб(к, форма, ЛЕКСИКА_ВН, ЛЕКСИКА_ЕД);
            склеить(форма, sizeof(форма), основа, "ей"); доб(к, форма, ЛЕКСИКА_ТВ, ЛЕКСИКА_ЕД);
            доб(к, форма, ЛЕКСИКА_ПР, ЛЕКСИКА_ЕД);
            return;
        }
        без_последнего(слово, основа, sizeof(основа));
        if (оканчивается(слово, "я")) {
            доб(к, слово, ЛЕКСИКА_ИМ, ЛЕКСИКА_ЕД);
            склеить(форма, sizeof(форма), основа, "и");  доб(к, форма, ЛЕКСИКА_РД, ЛЕКСИКА_ЕД);
            склеить(форма, sizeof(форма), основа, "е");  доб(к, форма, ЛЕКСИКА_ДТ, ЛЕКСИКА_ЕД);
            склеить(форма, sizeof(форма), основа, "ю");  доб(к, форма, ЛЕКСИКА_ВН, ЛЕКСИКА_ЕД);
            склеить(форма, sizeof(форма), основа, "ей"); доб(к, форма, ЛЕКСИКА_ТВ, ЛЕКСИКА_ЕД);
            склеить(форма, sizeof(форма), основа, "е");  доб(к, форма, ЛЕКСИКА_ПР, ЛЕКСИКА_ЕД);
            return;
        }
        доб(к, слово, ЛЕКСИКА_ИМ, ЛЕКСИКА_ЕД);
        склеить(форма, sizeof(форма), основа, губное_ка(основа) ? "и" : "ы");
        доб(к, форма, ЛЕКСИКА_РД, ЛЕКСИКА_ЕД);
        склеить(форма, sizeof(форма), основа, "е");  доб(к, форма, ЛЕКСИКА_ДТ, ЛЕКСИКА_ЕД);
        склеить(форма, sizeof(форма), основа, "у");  доб(к, форма, ЛЕКСИКА_ВН, ЛЕКСИКА_ЕД);
        склеить(форма, sizeof(форма), основа, "ой"); доб(к, форма, ЛЕКСИКА_ТВ, ЛЕКСИКА_ЕД);
        склеить(форма, sizeof(форма), основа, "е");  доб(к, форма, ЛЕКСИКА_ПР, ЛЕКСИКА_ЕД);
        return;
    }

    if (оканчивается(слово, "о") || оканчивается(слово, "е") || оканчивается(слово, "ё")) {
        int мягкое = !оканчивается(слово, "о");
        без_последнего(слово, основа, sizeof(основа));
        доб(к, слово, ЛЕКСИКА_ИМ, ЛЕКСИКА_ЕД);
        доб(к, слово, ЛЕКСИКА_РД, ЛЕКСИКА_ЕД);
        доб(к, слово, ЛЕКСИКА_ДТ, ЛЕКСИКА_ЕД);
        доб(к, слово, ЛЕКСИКА_ВН, ЛЕКСИКА_ЕД);
        склеить(форма, sizeof(форма), основа, мягкое ? "ем" : "ом");
        доб(к, форма, ЛЕКСИКА_ТВ, ЛЕКСИКА_ЕД);
        склеить(форма, sizeof(форма), основа, "е");
        доб(к, форма, ЛЕКСИКА_ПР, ЛЕКСИКА_ЕД);
        return;
    }

    if (оканчивается(слово, "ь")) {
        без_последнего(слово, основа, sizeof(основа));
        if (женский) {
            доб(к, слово, ЛЕКСИКА_ИМ, ЛЕКСИКА_ЕД);
            склеить(форма, sizeof(форма), основа, "и");  доб(к, форма, ЛЕКСИКА_РД, ЛЕКСИКА_ЕД);
            доб(к, форма, ЛЕКСИКА_ДТ, ЛЕКСИКА_ЕД);
            доб(к, слово, ЛЕКСИКА_ВН, ЛЕКСИКА_ЕД);
            склеить(форма, sizeof(форма), основа, "ью"); доб(к, форма, ЛЕКСИКА_ТВ, ЛЕКСИКА_ЕД);
            доб(к, форма, ЛЕКСИКА_ПР, ЛЕКСИКА_ЕД);
            return;
        }
        {
            char твердая[160], творительная[160];
            копировать(твердая, sizeof(твердая), основа);
            if (оканчивается(слово, "ень") && знаков(слово) >= 4) {
                без_последних(слово, 3, твердая, sizeof(твердая));
                склеить(твердая, sizeof(твердая), твердая, "н");
                склеить(творительная, sizeof(творительная), твердая, "ем");
            } else if (оканчивается(слово, "ец") && знаков(слово) > 3) {
                без_последних(слово, 2, твердая, sizeof(твердая));
                склеить(твердая, sizeof(твердая), твердая, "ц");
                склеить(творительная, sizeof(творительная), твердая, "ем");
            } else {
                склеить(творительная, sizeof(творительная), основа, "ём");
            }
            доб(к, слово, ЛЕКСИКА_ИМ, ЛЕКСИКА_ЕД);
            склеить(форма, sizeof(форма), твердая, "я"); доб(к, форма, ЛЕКСИКА_РД, ЛЕКСИКА_ЕД);
            склеить(форма, sizeof(форма), твердая, "ю"); доб(к, форма, ЛЕКСИКА_ДТ, ЛЕКСИКА_ЕД);
            доб(к, слово, ЛЕКСИКА_ВН, ЛЕКСИКА_ЕД);
            доб(к, творительная, ЛЕКСИКА_ТВ, ЛЕКСИКА_ЕД);
            склеить(форма, sizeof(форма), твердая, "е"); доб(к, форма, ЛЕКСИКА_ПР, ЛЕКСИКА_ЕД);
        }
        return;
    }

    if (оканчивается(слово, "й")) {
        без_последнего(слово, основа, sizeof(основа));
        доб(к, слово, ЛЕКСИКА_ИМ, ЛЕКСИКА_ЕД);
        склеить(форма, sizeof(форма), основа, "я");  доб(к, форма, ЛЕКСИКА_РД, ЛЕКСИКА_ЕД);
        склеить(форма, sizeof(форма), основа, "ю");  доб(к, форма, ЛЕКСИКА_ДТ, ЛЕКСИКА_ЕД);
        доб(к, слово, ЛЕКСИКА_ВН, ЛЕКСИКА_ЕД);
        склеить(форма, sizeof(форма), основа, "ем"); доб(к, форма, ЛЕКСИКА_ТВ, ЛЕКСИКА_ЕД);
        склеить(форма, sizeof(форма), основа, "е");  доб(к, форма, ЛЕКСИКА_ПР, ЛЕКСИКА_ЕД);
        return;
    }

    /* Регулярное существительное на согласную. */
    копировать(основа, sizeof(основа), слово);
    if (оканчивается(слово, "ень") && знаков(слово) > 4) {
        без_последних(слово, 3, основа, sizeof(основа));
        склеить(основа, sizeof(основа), основа, "н");
    } else if (оканчивается(слово, "ец") && знаков(слово) > 3) {
        без_последних(слово, 2, основа, sizeof(основа));
        склеить(основа, sizeof(основа), основа, "ц");
    }
    доб(к, слово, ЛЕКСИКА_ИМ, ЛЕКСИКА_ЕД);
    склеить(форма, sizeof(форма), основа, "а"); доб(к, форма, ЛЕКСИКА_РД, ЛЕКСИКА_ЕД);
    склеить(форма, sizeof(форма), основа, "у"); доб(к, форма, ЛЕКСИКА_ДТ, ЛЕКСИКА_ЕД);
    if (одушевлённое) {
        склеить(форма, sizeof(форма), основа, "а");
        доб(к, форма, ЛЕКСИКА_ВН, ЛЕКСИКА_ЕД);
    } else {
        доб(к, слово, ЛЕКСИКА_ВН, ЛЕКСИКА_ЕД);
    }
    склеить(форма, sizeof(форма), основа, "ом"); доб(к, форма, ЛЕКСИКА_ТВ, ЛЕКСИКА_ЕД);
    склеить(форма, sizeof(форма), основа, "е");  доб(к, форма, ЛЕКСИКА_ПР, ЛЕКСИКА_ЕД);
}

/* _множество() из эталона. */
static void множество(const char *слово, Сборщик *к)
{
    char основа[160], именительный[160], родительный[160], форма[160];
    if (!слово || !*слово) return;

    if (оканчивается(слово, "ия")) {
        без_последних(слово, 2, основа, sizeof(основа));
        склеить(форма, sizeof(форма), основа, "ии");   доб(к, форма, ЛЕКСИКА_ИМ, ЛЕКСИКА_МН);
        склеить(форма, sizeof(форма), основа, "ий");   доб(к, форма, ЛЕКСИКА_РД, ЛЕКСИКА_МН);
        склеить(форма, sizeof(форма), основа, "иям");  доб(к, форма, ЛЕКСИКА_ДТ, ЛЕКСИКА_МН);
        склеить(форма, sizeof(форма), основа, "ии");   доб(к, форма, ЛЕКСИКА_ВН, ЛЕКСИКА_МН);
        склеить(форма, sizeof(форма), основа, "иями"); доб(к, форма, ЛЕКСИКА_ТВ, ЛЕКСИКА_МН);
        склеить(форма, sizeof(форма), основа, "иях");  доб(к, форма, ЛЕКСИКА_ПР, ЛЕКСИКА_МН);
        return;
    }

    if (оканчивается(слово, "а") || оканчивается(слово, "я")) {
        int мягкое = оканчивается(слово, "я") || оканчивается(слово, "ья");
        без_последнего(слово, основа, sizeof(основа));
        склеить(именительный, sizeof(именительный), основа,
                (мягкое || губное_ка(основа)) ? "и" : "ы");
        родительный_множественного(слово, родительный, sizeof(родительный));
        доб(к, именительный, ЛЕКСИКА_ИМ, ЛЕКСИКА_МН);
        доб(к, родительный, ЛЕКСИКА_РД, ЛЕКСИКА_МН);
        склеить(форма, sizeof(форма), основа, мягкое ? "ям" : "ам");
        доб(к, форма, ЛЕКСИКА_ДТ, ЛЕКСИКА_МН);
        доб(к, именительный, ЛЕКСИКА_ВН, ЛЕКСИКА_МН);
        склеить(форма, sizeof(форма), основа, мягкое ? "ями" : "ами");
        доб(к, форма, ЛЕКСИКА_ТВ, ЛЕКСИКА_МН);
        склеить(форма, sizeof(форма), основа, мягкое ? "ях" : "ах");
        доб(к, форма, ЛЕКСИКА_ПР, ЛЕКСИКА_МН);
        return;
    }

    if (оканчивается(слово, "о") || оканчивается(слово, "е") || оканчивается(слово, "ё")) {
        int мягкое = !оканчивается(слово, "о");
        без_последнего(слово, основа, sizeof(основа));
        склеить(именительный, sizeof(именительный), основа, мягкое ? "я" : "а");
        родительный_множественного(слово, родительный, sizeof(родительный));
        доб(к, именительный, ЛЕКСИКА_ИМ, ЛЕКСИКА_МН);
        доб(к, родительный, ЛЕКСИКА_РД, ЛЕКСИКА_МН);
        склеить(форма, sizeof(форма), основа, мягкое ? "ям" : "ам");
        доб(к, форма, ЛЕКСИКА_ДТ, ЛЕКСИКА_МН);
        доб(к, именительный, ЛЕКСИКА_ВН, ЛЕКСИКА_МН);
        склеить(форма, sizeof(форма), основа, мягкое ? "ями" : "ами");
        доб(к, форма, ЛЕКСИКА_ТВ, ЛЕКСИКА_МН);
        склеить(форма, sizeof(форма), основа, мягкое ? "ях" : "ах");
        доб(к, форма, ЛЕКСИКА_ПР, ЛЕКСИКА_МН);
        return;
    }

    if (оканчивается(слово, "ь")) {
        без_последнего(слово, основа, sizeof(основа));
        склеить(форма, sizeof(форма), основа, "и");   доб(к, форма, ЛЕКСИКА_ИМ, ЛЕКСИКА_МН);
        склеить(форма, sizeof(форма), основа, "ей");  доб(к, форма, ЛЕКСИКА_РД, ЛЕКСИКА_МН);
        склеить(форма, sizeof(форма), основа, "ям");  доб(к, форма, ЛЕКСИКА_ДТ, ЛЕКСИКА_МН);
        склеить(форма, sizeof(форма), основа, "и");   доб(к, форма, ЛЕКСИКА_ВН, ЛЕКСИКА_МН);
        склеить(форма, sizeof(форма), основа, "ями"); доб(к, форма, ЛЕКСИКА_ТВ, ЛЕКСИКА_МН);
        склеить(форма, sizeof(форма), основа, "ях");  доб(к, форма, ЛЕКСИКА_ПР, ЛЕКСИКА_МН);
        return;
    }

    if (оканчивается(слово, "й")) {
        без_последнего(слово, основа, sizeof(основа));
        склеить(форма, sizeof(форма), основа, "и");   доб(к, форма, ЛЕКСИКА_ИМ, ЛЕКСИКА_МН);
        склеить(форма, sizeof(форма), основа, "ев");  доб(к, форма, ЛЕКСИКА_РД, ЛЕКСИКА_МН);
        склеить(форма, sizeof(форма), основа, "ям");  доб(к, форма, ЛЕКСИКА_ДТ, ЛЕКСИКА_МН);
        склеить(форма, sizeof(форма), основа, "и");   доб(к, форма, ЛЕКСИКА_ВН, ЛЕКСИКА_МН);
        склеить(форма, sizeof(форма), основа, "ями"); доб(к, форма, ЛЕКСИКА_ТВ, ЛЕКСИКА_МН);
        склеить(форма, sizeof(форма), основа, "ях");  доб(к, форма, ЛЕКСИКА_ПР, ЛЕКСИКА_МН);
        return;
    }

    копировать(основа, sizeof(основа), слово);
    склеить(именительный, sizeof(именительный), основа, губное_ка(основа) ? "и" : "ы");
    родительный_множественного(слово, родительный, sizeof(родительный));
    доб(к, именительный, ЛЕКСИКА_ИМ, ЛЕКСИКА_МН);
    доб(к, родительный, ЛЕКСИКА_РД, ЛЕКСИКА_МН);
    склеить(форма, sizeof(форма), основа, "ам");  доб(к, форма, ЛЕКСИКА_ДТ, ЛЕКСИКА_МН);
    доб(к, именительный, ЛЕКСИКА_ВН, ЛЕКСИКА_МН);
    склеить(форма, sizeof(форма), основа, "ами"); доб(к, форма, ЛЕКСИКА_ТВ, ЛЕКСИКА_МН);
    склеить(форма, sizeof(форма), основа, "ах");  доб(к, форма, ЛЕКСИКА_ПР, ЛЕКСИКА_МН);
}

int лексика_нижнее(const char *вход, char *выход, size_t размер)
{
    size_t о = 0;
    const unsigned char *с;
    if (!вход || !выход || !размер) return 0;
    с = (const unsigned char *)вход;
    while (*с) {
        uint32_t код;
        size_t ширина;
        unsigned char первый = *с;
        if (первый < 0x80) { код = первый; ширина = 1; }
        else if (первый >= 0xC2 && первый <= 0xDF) { код = первый & 0x1F; ширина = 2; }
        else if (первый >= 0xE0 && первый <= 0xEF) { код = первый & 0x0F; ширина = 3; }
        else if (первый >= 0xF0 && первый <= 0xF4) { код = первый & 0x07; ширина = 4; }
        else return 0;
        for (size_t i = 1; i < ширина; ++i) {
            if ((с[i] & 0xC0) != 0x80) return 0;
            код = (код << 6) | (с[i] & 0x3F);
        }
        if (код >= 0x0410 && код <= 0x042F) код += 0x20;
        else if (код == 0x0401) код = 0x0451;
        else if (код >= 'A' && код <= 'Z') код += 0x20;
        unsigned char байты[4];
        size_t длина;
        if (код < 0x80) { байты[0] = (unsigned char)код; длина = 1; }
        else if (код < 0x800) {
            байты[0] = (unsigned char)(0xC0 | (код >> 6));
            байты[1] = (unsigned char)(0x80 | (код & 0x3F));
            длина = 2;
        } else if (код < 0x10000) {
            байты[0] = (unsigned char)(0xE0 | (код >> 12));
            байты[1] = (unsigned char)(0x80 | ((код >> 6) & 0x3F));
            байты[2] = (unsigned char)(0x80 | (код & 0x3F));
            длина = 3;
        } else {
            байты[0] = (unsigned char)(0xF0 | (код >> 18));
            байты[1] = (unsigned char)(0x80 | ((код >> 12) & 0x3F));
            байты[2] = (unsigned char)(0x80 | ((код >> 6) & 0x3F));
            байты[3] = (unsigned char)(0x80 | (код & 0x3F));
            длина = 4;
        }
        if (о + длина >= размер) return 0;
        memcpy(выход + о, байты, длина);
        о += длина;
        с += ширина;
    }
    выход[о] = 0;
    return 1;
}

size_t лексика_склонить(const char *лемма, const char *род, int одушевлённое,
                        ЛексикаСловоформа *формы, size_t предел)
{
    char слово[160], основа[160], второй[160];
    const char *кандидаты[2];
    size_t число_кандидатов = 1;
    int множественное_имя = 0;
    Сборщик к;
    const char *р;

    if (!лемма || !*лемма || !формы || !предел) return 0;
    if (!лексика_нижнее(лемма, слово, sizeof(слово))) return 0;
    if (предел > ЛЕКСИКА_ФОРМ_ПРЕДЕЛ) предел = ЛЕКСИКА_ФОРМ_ПРЕДЕЛ;
    к.формы = формы; к.число = 0; к.предел = предел;
    р = род && *род ? род : "м";

    if (strcmp(слово, "число") == 0 || strcmp(слово, "числа") == 0) {
        static const char *const ед[] = {"число", "числа", "числу", "число", "числом", "числе"};
        static const char *const мн[] = {"числа", "чисел", "числам", "числа", "числами", "числах"};
        for (unsigned i = 0; i < ЛЕКСИКА_ПАДЕЖЕЙ; ++i) доб(&к, ед[i], ПАДЕЖ_БИТ[i], ЛЕКСИКА_ЕД);
        for (unsigned i = 0; i < ЛЕКСИКА_ПАДЕЖЕЙ; ++i) доб(&к, мн[i], ПАДЕЖ_БИТ[i], ЛЕКСИКА_МН);
        return к.число;
    }
    for (size_t i = 0; i < РАЗМЕР(НЕСКЛОНЯЕМЫЕ); ++i) {
        if (strcmp(слово, НЕСКЛОНЯЕМЫЕ[i]) == 0) {
            доб(&к, слово, ЛЕКСИКА_ИМ | ЛЕКСИКА_РД | ЛЕКСИКА_ДТ | ЛЕКСИКА_ВН | ЛЕКСИКА_ТВ | ЛЕКСИКА_ПР,
                ЛЕКСИКА_ЕД | ЛЕКСИКА_МН);
            return к.число;
        }
    }

    /* Как в эталоне: имя, заведённое во множественном числе, узнаётся и в
     * единственном — кандидаты «основа» и «основа + а». */
    кандидаты[0] = слово;
    if (знаков(слово) > 3 && (оканчивается(слово, "ы") || оканчивается(слово, "и")) &&
        !оканчивается(слово, "ий") && !оканчивается(слово, "ия") &&
        !оканчивается(слово, "ие") && !оканчивается(слово, "ье") &&
        !оканчивается(слово, "ья") && !оканчивается(слово, "ии") &&
        !оканчивается(слово, "ые")) {
        множественное_имя = 1;
        без_последнего(слово, основа, sizeof(основа));
        склеить(второй, sizeof(второй), основа, "а");
        кандидаты[0] = основа;
        кандидаты[1] = второй;
        число_кандидатов = 2;
    }
    for (size_t i = 0; i < число_кандидатов; ++i) {
        единица(кандидаты[i], р, одушевлённое, &к);
        множество(кандидаты[i], &к);
    }
    if (множественное_имя) {
        доб(&к, слово, ЛЕКСИКА_ИМ, ЛЕКСИКА_МН);
        доб(&к, слово, ЛЕКСИКА_ВН, ЛЕКСИКА_МН);
    }
    return к.число;
}

/* ОКОНЧАНИЯ_РАЗБОРА из эталона, в том же порядке. */
static const struct { const char *окончание; unsigned падеж; unsigned число; } ОКОНЧАНИЯ_РАЗБОРА[] = {
    {"ами", ЛЕКСИКА_ТВ, ЛЕКСИКА_МН}, {"ями", ЛЕКСИКА_ТВ, ЛЕКСИКА_МН},
    {"ах", ЛЕКСИКА_ПР, ЛЕКСИКА_МН}, {"ях", ЛЕКСИКА_ПР, ЛЕКСИКА_МН},
    {"ам", ЛЕКСИКА_ДТ, ЛЕКСИКА_МН}, {"ям", ЛЕКСИКА_ДТ, ЛЕКСИКА_МН},
    {"ов", ЛЕКСИКА_РД, ЛЕКСИКА_МН}, {"ев", ЛЕКСИКА_РД, ЛЕКСИКА_МН},
    {"ей", ЛЕКСИКА_РД, ЛЕКСИКА_МН}, {"ой", ЛЕКСИКА_ТВ, ЛЕКСИКА_ЕД},
    {"ей", ЛЕКСИКА_ТВ, ЛЕКСИКА_ЕД}, {"ом", ЛЕКСИКА_ТВ, ЛЕКСИКА_ЕД},
    {"ем", ЛЕКСИКА_ТВ, ЛЕКСИКА_ЕД}, {"ём", ЛЕКСИКА_ТВ, ЛЕКСИКА_ЕД},
    {"ью", ЛЕКСИКА_ТВ, ЛЕКСИКА_ЕД},
    {"а", ЛЕКСИКА_РД, ЛЕКСИКА_ЕД}, {"я", ЛЕКСИКА_РД, ЛЕКСИКА_ЕД},
    {"у", ЛЕКСИКА_ДТ, ЛЕКСИКА_ЕД}, {"ю", ЛЕКСИКА_ДТ, ЛЕКСИКА_ЕД},
    {"е", ЛЕКСИКА_ПР, ЛЕКСИКА_ЕД}, {"и", ЛЕКСИКА_ПР, ЛЕКСИКА_ЕД},
    {"ы", ЛЕКСИКА_ИМ, ЛЕКСИКА_МН}, {"и", ЛЕКСИКА_ИМ, ЛЕКСИКА_МН},
    {"ь", ЛЕКСИКА_ИМ, ЛЕКСИКА_ЕД}
};

size_t лексика_разобрать(const char *слово, ЛексикаСловоформа *варианты, size_t предел)
{
    char нижнее[160];
    size_t число = 0;
    int уже;
    if (!слово || !варианты || !предел) return 0;
    if (!лексика_нижнее(слово, нижнее, sizeof(нижнее))) return 0;
    for (size_t i = 0; i < РАЗМЕР(ОКОНЧАНИЯ_РАЗБОРА); ++i) {
        char основа[160];
        if (!оканчивается(нижнее, ОКОНЧАНИЯ_РАЗБОРА[i].окончание)) continue;
        без_последних(нижнее, знаков(ОКОНЧАНИЯ_РАЗБОРА[i].окончание), основа, sizeof(основа));
        if (знаков(основа) < 2) continue;
        уже = 0;
        for (size_t j = 0; j < число; ++j)
            if (strcmp(варианты[j].форма, основа) == 0 &&
                варианты[j].падеж == ОКОНЧАНИЯ_РАЗБОРА[i].падеж &&
                варианты[j].число == ОКОНЧАНИЯ_РАЗБОРА[i].число) { уже = 1; break; }
        if (уже || число >= предел) continue;
        копировать(варианты[число].форма, sizeof(варианты[0].форма), основа);
        варианты[число].падеж = ОКОНЧАНИЯ_РАЗБОРА[i].падеж;
        варианты[число].число = ОКОНЧАНИЯ_РАЗБОРА[i].число;
        ++число;
    }
    /* Тождественная форма: слово как есть — именительный единственного. */
    уже = 0;
    for (size_t j = 0; j < число; ++j)
        if (strcmp(варианты[j].форма, нижнее) == 0 &&
            варианты[j].падеж == ЛЕКСИКА_ИМ && варианты[j].число == ЛЕКСИКА_ЕД) уже = 1;
    if (!уже && число < предел) {
        копировать(варианты[число].форма, sizeof(варианты[0].форма), нижнее);
        варианты[число].падеж = ЛЕКСИКА_ИМ;
        варианты[число].число = ЛЕКСИКА_ЕД;
        ++число;
    }
    return число;
}

int лексика_форма_подходит(const ЛексикаСловоформа *форма, unsigned падеж, unsigned число)
{
    if (!форма) return 0;
    if (падеж && !(форма->падеж & падеж)) return 0;
    if (число && !(форма->число & число)) return 0;
    return 1;
}

const char *лексика_название_падежа(const char *код)
{
    if (!код) return "";
    if (strcmp(код, "им") == 0) return "именительный";
    if (strcmp(код, "рд") == 0) return "родительный";
    if (strcmp(код, "дт") == 0) return "дательный";
    if (strcmp(код, "вн") == 0) return "винительный";
    if (strcmp(код, "тв") == 0) return "творительный";
    if (strcmp(код, "пр") == 0) return "предложный";
    return код;
}
