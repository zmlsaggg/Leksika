/*
 * Перенос падежной морфологии лексика/морфология.lek на C11.
 *
 * Повторены ГУБНЫЕ_КА, ШИПЯЩИЕ, родительный_множественного(), _единица(),
 * _множество() и ОКОНЧАНИЯ_РАЗБОРА — с той же очерёдностью проверок, чтобы
 * словоформы совпадали с эталоном один в один (это проверяет морфология-тест).
 */
#include "морфология.h"
#include <stdio.h>
#include <string.h>

const char *const ЛЕКСИКА_ПАДЕЖИ[ЛЕКСИКА_ПАДЕЖЕЙ] = {"им", "рд", "дт", "вн", "тв", "пр"};

static const unsigned ПАДЕЖ_БИТ[ЛЕКСИКА_ПАДЕЖЕЙ] = {
    ЛЕКСИКА_ИМ, ЛЕКСИКА_РД, ЛЕКСИКА_ДТ, ЛЕКСИКА_ВН, ЛЕКСИКА_ТВ, ЛЕКСИКА_ПР
};

static const char *const ГЛАСНЫЕ[] = {"а", "е", "ё", "и", "о", "у", "ы", "э", "ю", "я"};
static const char *const НЕСКЛОНЯЕМЫЕ[] = {
    "метро", "пальто", "кофе", "такси", "кино", "радио", "шоссе", "депо",
    "жюри", "интервью", "меню", "резюме", "кенгуру", "ателье", "драже",
    "желе", "пианино", "домино", "салями", "бордо", "танго", "манго"
};
static const char *const ГУБНЫЕ_КА[] = {"г", "к", "х", "ж", "ч", "ш", "щ"};
static const char *const ШИПЯЩИЕ[] = {"ж", "ч", "ш", "щ", "ц"};

#define РАЗМЕР(имя) (sizeof(имя) / sizeof((имя)[0]))

static int оканчивается(const char *слово, const char *хвост)
{
    if (!слово || !хвост) return 0;
    size_t а = strlen(слово), б = strlen(хвост);
    return а >= б && memcmp(слово + а - б, хвост, б) == 0;
}

static int оканчивается_на(const char *слово, const char *const *хвосты, size_t число)
{
    for (size_t i = 0; i < число; ++i)
        if (оканчивается(слово, хвосты[i])) return 1;
    return 0;
}

static int губное_ка(const char *слово) { return оканчивается_на(слово, ГУБНЫЕ_КА, РАЗМЕР(ГУБНЫЕ_КА)); }
static int шипящее(const char *слово) { return оканчивается_на(слово, ШИПЯЩИЕ, РАЗМЕР(ШИПЯЩИЕ)); }
static int гласный(const char *знак) { return оканчивается_на(знак, ГЛАСНЫЕ, РАЗМЕР(ГЛАСНЫЕ)); }

/* Число знаков UTF-8 (в эталоне — длина строки Python). */
static size_t знаков(const char *строка)
{
    size_t n = 0;
    if (!строка) return 0;
    for (const unsigned char *с = (const unsigned char *)строка; *с; ++с)
        if ((*с & 0xC0) != 0x80) ++n;
    return n;
}

/* Начало последнего знака UTF-8 в строке длиной длина. */
static size_t начало_последнего(const char *строка, size_t длина)
{
    size_t i = длина;
    while (i > 0 && ((unsigned char)строка[i - 1] & 0xC0) == 0x80) --i;
    return i > 0 ? i - 1 : 0;
}

static void копировать(char *куда, size_t размер, const char *откуда)
{
    if (!размер) return;
    size_t n = strlen(откуда);
    if (n >= размер) n = размер - 1;
    if (n) memcpy(куда, откуда, n);
    куда[n] = 0;
}

/* word[:-1] по знакам, а не по байтам. */
static void без_последнего(const char *слово, char *выход, size_t размер)
{
    size_t n = strlen(слово);
    копировать(выход, размер, слово);
    if (n) выход[начало_последнего(слово, n)] = 0;
}

/* word[:-k] по знакам. */
static void без_последних(const char *слово, size_t k, char *выход, size_t размер)
{
    size_t конец = strlen(слово);
    for (size_t i = 0; i < k && конец; ++i) конец = начало_последнего(слово, конец);
    копировать(выход, размер, слово);
    выход[конец] = 0;
}

/* Знак перед последним: основа[-2] в терминах Python. */
static void предпоследний_знак(const char *основа, char *выход, size_t размер)
{
    выход[0] = 0;
    size_t n = strlen(основа);
    if (n < 2 || !размер) return;
    size_t последний = начало_последнего(основа, n);
    if (!последний) return;
    size_t начало = начало_последнего(основа, последний);
    size_t длина = последний - начало;
    if (длина >= размер) return;
    memcpy(выход, основа + начало, длина);
    выход[длина] = 0;
}

/* f"{основа}{хвост}"; работает и когда куда совпадает с основа. */
static void склеить(char *куда, size_t размер, const char *основа, const char *хвост)
{
    char временная[512];
    size_t а = strlen(основа), б = strlen(хвост);
    if (а + б >= sizeof(временная)) { if (размер) куда[0] = 0; return; }
    if (а) memcpy(временная, основа, а);
    memcpy(временная + а, хвост, б + 1);
    копировать(куда, размер, временная);
}

