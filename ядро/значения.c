ЛексусЗначение лексус_значение_копия(ЛексусЗначение значение)
{
    switch (значение.вид) {
        case ЛЕКСУС_ЧИСЛО: if (значение.данные.число) ++значение.данные.число->ссылки; break;
        case ЛЕКСУС_РЕЧЬ: if (значение.данные.речь) ++значение.данные.речь->ссылки; break;
        case ЛЕКСУС_ПЕРЕЧЕНЬ: if (значение.данные.перечень) ++значение.данные.перечень->ссылки; break;
        case ЛЕКСУС_СЛОВАРЬ: if (значение.данные.словарь) ++значение.данные.словарь->ссылки; break;
        default: break;
    }
    return значение;
}

void лексус_значение_освободить(ЛексусЗначение *значение)
{
    if (!значение) return;
    switch (значение->вид) {
        case ЛЕКСУС_ЧИСЛО:
            if (значение->данные.число && --значение->данные.число->ссылки == 0) {
                free(значение->данные.число->цифры);
                free(значение->данные.число);
            }
            break;
        case ЛЕКСУС_РЕЧЬ:
            if (значение->данные.речь && --значение->данные.речь->ссылки == 0) {
                free(значение->данные.речь->текст);
                free(значение->данные.речь);
            }
            break;
        case ЛЕКСУС_ПЕРЕЧЕНЬ:
            if (значение->данные.перечень && --значение->данные.перечень->ссылки == 0) {
                ЛексусПеречень *перечень = значение->данные.перечень;
                for (size_t i = 0; i < перечень->длина; ++i) лексус_значение_освободить(&перечень->элементы[i]);
                free(перечень->элементы);
                free(перечень);
            }
            break;
        case ЛЕКСУС_СЛОВАРЬ:
            if (значение->данные.словарь && --значение->данные.словарь->ссылки == 0) {
                ЛексусСловарь *словарь = значение->данные.словарь;
                for (size_t i = 0; i < словарь->длина; ++i) {
                    лексус_значение_освободить(&словарь->пары[i].ключ);
                    лексус_значение_освободить(&словарь->пары[i].значение);
                }
                free(словарь->пары);
                free(словарь);
            }
            break;
        default: break;
    }
    *значение = лексус_ничто();
}

