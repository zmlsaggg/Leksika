/* Числа хранятся в канонической форме: хвостовые нули уже удалены. */
static int равно_числа(ЛексусЧисло *а, ЛексусЧисло *б)
{
    return а->знак == б->знак && а->масштаб == б->масштаб &&
           а->длина == б->длина && memcmp(а->цифры, б->цифры, а->длина) == 0;
}

static int равно_ключи(ЛексусЗначение а, ЛексусЗначение б)
{
    if (а.вид != б.вид) return 0;
    if (а.вид == ЛЕКСУС_ЛОГИКА) return а.данные.логика == б.данные.логика;
    if (а.вид == ЛЕКСУС_РЕЧЬ)
        return а.данные.речь->байты == б.данные.речь->байты &&
               memcmp(а.данные.речь->текст, б.данные.речь->текст, а.данные.речь->байты) == 0;
    if (а.вид == ЛЕКСУС_ЧИСЛО) return равно_числа(а.данные.число, б.данные.число);
    return 0;
}

/* Возвращает 1, если граф значения уже содержит искомый контейнер,
 * 0 если не содержит и -1 если достигнут защитный предел вложенности.
 */
static int содержит_контейнер(ЛексусЗначение значение, ЛексусЗначение искомый, size_t глубина)
{
    if (глубина > 1024) return -1;
    if (значение.вид == искомый.вид) {
        if (значение.вид == ЛЕКСУС_ПЕРЕЧЕНЬ && значение.данные.перечень == искомый.данные.перечень) return 1;
        if (значение.вид == ЛЕКСУС_СЛОВАРЬ && значение.данные.словарь == искомый.данные.словарь) return 1;
    }
    if (значение.вид == ЛЕКСУС_ПЕРЕЧЕНЬ) {
        for (size_t i = 0; i < значение.данные.перечень->длина; ++i) {
            int найдено = содержит_контейнер(значение.данные.перечень->элементы[i], искомый, глубина + 1);
            if (найдено) return найдено;
        }
    } else if (значение.вид == ЛЕКСУС_СЛОВАРЬ) {
        for (size_t i = 0; i < значение.данные.словарь->длина; ++i) {
            int найдено = содержит_контейнер(значение.данные.словарь->пары[i].значение, искомый, глубина + 1);
            if (найдено) return найдено;
        }
    }
    return 0;
}

static int вместить_словарь(ЛексусСловарь *словарь)
{
    if (словарь->длина < словарь->ёмкость) return 1;
    size_t новая = словарь->ёмкость ? словарь->ёмкость * 2 : 4;
    if (новая < словарь->ёмкость || новая > SIZE_MAX / sizeof(*словарь->пары)) return 0;
    ЛексусПара *пары = (ЛексусПара *)realloc(словарь->пары, новая * sizeof(*пары));
    if (!пары) return 0;
    словарь->пары = пары;
    словарь->ёмкость = новая;
    return 1;
}

ЛексусОшибка лексус_словарь_записать(ЛексусЗначение значение, ЛексусЗначение ключ, ЛексусЗначение элемент)
{
    if (значение.вид != ЛЕКСУС_СЛОВАРЬ || !значение.данные.словарь)
        return ошибка(ЛЕКСУС_НЕВЕРНЫЙ_ВИД, "запись требует значение вида «словарь»");
    if (!допустимый_ключ(ключ))
        return ошибка(ЛЕКСУС_НЕВЕРНЫЙ_КЛЮЧ, "ключом словаря могут быть только речь, число или логика");
    int цикл = содержит_контейнер(элемент, значение, 0);
    if (цикл > 0) return ошибка(ЛЕКСУС_ЦИКЛ_КОЛЛЕКЦИИ, "циклическое вложение коллекций запрещено");
    if (цикл < 0) return ошибка(ЛЕКСУС_СЛИШКОМ_ГЛУБОКАЯ_КОЛЛЕКЦИЯ, "слишком глубокая вложенность коллекций");
    ЛексусСловарь *словарь = значение.данные.словарь;
    for (size_t i = 0; i < словарь->длина; ++i) {
        if (равно_ключи(словарь->пары[i].ключ, ключ)) {
            ЛексусЗначение новое = лексус_значение_копия(элемент);
            лексус_значение_освободить(&словарь->пары[i].значение);
            словарь->пары[i].значение = новое;
            return без_ошибки();
        }
    }
    if (!вместить_словарь(словарь))
        return ошибка(ЛЕКСУС_НЕТ_ПАМЯТИ, "не хватило памяти для словаря");
    словарь->пары[словарь->длина].ключ = лексус_значение_копия(ключ);
    словарь->пары[словарь->длина].значение = лексус_значение_копия(элемент);
    ++словарь->длина;
    return без_ошибки();
}

ЛексусОшибка лексус_словарь_прочитать(ЛексусЗначение значение, ЛексусЗначение ключ, ЛексусЗначение *результат)
{
    if (!результат) return ошибка(ЛЕКСУС_НЕВЕРНЫЙ_ВИД, "не задано место для значения словаря");
    if (значение.вид != ЛЕКСУС_СЛОВАРЬ || !значение.данные.словарь)
        return ошибка(ЛЕКСУС_НЕВЕРНЫЙ_ВИД, "чтение требует значение вида «словарь»");
    if (!допустимый_ключ(ключ))
        return ошибка(ЛЕКСУС_НЕВЕРНЫЙ_КЛЮЧ, "ключом словаря могут быть только речь, число или логика");
    for (size_t i = 0; i < значение.данные.словарь->длина; ++i) {
        if (равно_ключи(значение.данные.словарь->пары[i].ключ, ключ)) {
            *результат = лексус_значение_копия(значение.данные.словарь->пары[i].значение);
            return без_ошибки();
        }
    }
    return ошибка(ЛЕКСУС_КЛЮЧ_НЕ_НАЙДЕН, "в словаре нет такого ключа");
}

ЛексусОшибка лексус_словарь_длина(ЛексусЗначение значение, size_t *длина)
{
    if (значение.вид != ЛЕКСУС_СЛОВАРЬ || !длина)
        return ошибка(ЛЕКСУС_НЕВЕРНЫЙ_ВИД, "длина требует значение вида «словарь»");
    *длина = значение.данные.словарь->длина;
    return без_ошибки();
}

ЛексусОшибка лексус_словарь_убрать(ЛексусЗначение значение, ЛексусЗначение ключ)
{
    if (значение.вид != ЛЕКСУС_СЛОВАРЬ || !значение.данные.словарь)
        return ошибка(ЛЕКСУС_НЕВЕРНЫЙ_ВИД, "удаление требует значение вида «словарь»");
    if (!допустимый_ключ(ключ))
        return ошибка(ЛЕКСУС_НЕВЕРНЫЙ_КЛЮЧ, "ключом словаря могут быть только речь, число или логика");
    ЛексусСловарь *словарь = значение.данные.словарь;
    for (size_t i = 0; i < словарь->длина; ++i) {
        if (равно_ключи(словарь->пары[i].ключ, ключ)) {
            лексус_значение_освободить(&словарь->пары[i].ключ);
            лексус_значение_освободить(&словарь->пары[i].значение);
            if (i + 1 < словарь->длина)
                memmove(&словарь->пары[i], &словарь->пары[i + 1],
                        (словарь->длина - i - 1) * sizeof(*словарь->пары));
            --словарь->длина;
            словарь->пары[словарь->длина].ключ = лексус_ничто();
            словарь->пары[словарь->длина].значение = лексус_ничто();
            return без_ошибки();
        }
    }
    return ошибка(ЛЕКСУС_КЛЮЧ_НЕ_НАЙДЕН, "в словаре нет такого ключа");
}

ЛексусОшибка лексус_сложить(ЛексусЗначение а, ЛексусЗначение б, ЛексусЗначение *результат)
{
    if (!результат) return ошибка(ЛЕКСУС_НЕВЕРНЫЙ_ВИД, "не задано место для результата сложения");
    if (а.вид != б.вид)
        return ошибка(ЛЕКСУС_НЕВЕРНЫЙ_ВИД, "сложение разных видов значений запрещено без явного преобразования");
    if (а.вид == ЛЕКСУС_ЧИСЛО) return лексус_число_сложить(а, б, результат);
    if (а.вид == ЛЕКСУС_РЕЧЬ) return лексус_речь_соединить(а, б, результат);
    if (а.вид == ЛЕКСУС_ПЕРЕЧЕНЬ) {
        ЛексусЗначение новый = лексус_ничто();
        ЛексусОшибка создание = лексус_перечень_создать(&новый);
        if (создание.код != ЛЕКСУС_ОК) return создание;
        for (size_t i = 0; i < а.данные.перечень->длина; ++i) {
            ЛексусОшибка e = лексус_перечень_добавить(новый, а.данные.перечень->элементы[i]);
            if (e.код != ЛЕКСУС_ОК) { лексус_значение_освободить(&новый); return e; }
        }
        for (size_t i = 0; i < б.данные.перечень->длина; ++i) {
            ЛексусОшибка e = лексус_перечень_добавить(новый, б.данные.перечень->элементы[i]);
            if (e.код != ЛЕКСУС_ОК) { лексус_значение_освободить(&новый); return e; }
        }
        *результат = новый;
        return без_ошибки();
    }
    return ошибка(ЛЕКСУС_НЕВЕРНЫЙ_ВИД, "плюс поддерживает только два числа, две речи или два перечня");
}

static ЛексусОшибка сравнить_значения(ЛексусЗначение а, ЛексусЗначение б,
                                      int *равны, size_t глубина)
{
    if (глубина > 1024) return ошибка(ЛЕКСУС_СЛИШКОМ_ГЛУБОКАЯ_КОЛЛЕКЦИЯ, "слишком глубокое сравнение коллекций");
    if (а.вид != б.вид) { *равны = 0; return без_ошибки(); }
    switch (а.вид) {
        case ЛЕКСУС_НИЧТО: *равны = 1; return без_ошибки();
        case ЛЕКСУС_ЛОГИКА: *равны = а.данные.логика == б.данные.логика; return без_ошибки();
        case ЛЕКСУС_ЧИСЛО: *равны = равно_числа(а.данные.число, б.данные.число); return без_ошибки();
        case ЛЕКСУС_РЕЧЬ:
            *равны = а.данные.речь->байты == б.данные.речь->байты &&
                     memcmp(а.данные.речь->текст, б.данные.речь->текст, а.данные.речь->байты) == 0;
            return без_ошибки();
        case ЛЕКСУС_ПРАВИЛО: case ЛЕКСУС_СРЕДА:
            *равны = а.данные.ссылка == б.данные.ссылка; return без_ошибки();
        case ЛЕКСУС_ПЕРЕЧЕНЬ: {
            ЛексусПеречень *x = а.данные.перечень, *y = б.данные.перечень;
            if (x->длина != y->длина) { *равны = 0; return без_ошибки(); }
            for (size_t i = 0; i < x->длина; ++i) {
                int одинаковы = 0;
                ЛексусОшибка e = сравнить_значения(x->элементы[i], y->элементы[i], &одинаковы, глубина + 1);
                if (e.код != ЛЕКСУС_ОК) return e;
                if (!одинаковы) { *равны = 0; return без_ошибки(); }
            }
            *равны = 1;
            return без_ошибки();
        }
        case ЛЕКСУС_СЛОВАРЬ: {
            ЛексусСловарь *x = а.данные.словарь, *y = б.данные.словарь;
            if (x->длина != y->длина) { *равны = 0; return без_ошибки(); }
            for (size_t i = 0; i < x->длина; ++i) {
                int найден = 0;
                for (size_t j = 0; j < y->длина; ++j) {
                    if (равно_ключи(x->пары[i].ключ, y->пары[j].ключ)) {
                        int одинаковы = 0;
                        ЛексусОшибка e = сравнить_значения(x->пары[i].значение, y->пары[j].значение,
                                                           &одинаковы, глубина + 1);
                        if (e.код != ЛЕКСУС_ОК) return e;
                        if (!одинаковы) { *равны = 0; return без_ошибки(); }
                        найден = 1;
                        break;
                    }
                }
                if (!найден) { *равны = 0; return без_ошибки(); }
            }
            *равны = 1;
            return без_ошибки();
        }
        default: *равны = 0; return без_ошибки();
    }
}

ЛексусОшибка лексус_равно(ЛексусЗначение а, ЛексусЗначение б, int *равны)
{
    if (!равны) return ошибка(ЛЕКСУС_НЕВЕРНЫЙ_ВИД, "не задан результат сравнения");
    return сравнить_значения(а, б, равны, 0);
}

int лексус_правда(ЛексусЗначение значение)
{
    switch (значение.вид) {
        case ЛЕКСУС_НИЧТО: return 0;
        case ЛЕКСУС_ЛОГИКА: return значение.данные.логика != 0;
        case ЛЕКСУС_ЧИСЛО: return значение.данные.число->знак != 0;
        case ЛЕКСУС_РЕЧЬ: return значение.данные.речь->символы != 0;
        case ЛЕКСУС_ПЕРЕЧЕНЬ: return значение.данные.перечень->длина != 0;
        case ЛЕКСУС_СЛОВАРЬ: return значение.данные.словарь->длина != 0;
        case ЛЕКСУС_ПРАВИЛО: case ЛЕКСУС_СРЕДА: return 1;
        default: return 0;
    }
}
