static int вместить_перечень(ЛексусПеречень *перечень)
{
    if (перечень->длина < перечень->ёмкость) return 1;
    size_t новая = перечень->ёмкость ? перечень->ёмкость * 2 : 4;
    if (новая < перечень->ёмкость || новая > SIZE_MAX / sizeof(*перечень->элементы)) return 0;
    ЛексусЗначение *элементы = (ЛексусЗначение *)realloc(перечень->элементы, новая * sizeof(*элементы));
    if (!элементы) return 0;
    перечень->элементы = элементы;
    перечень->ёмкость = новая;
    return 1;
}

