#include "байткод.h"
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#define ЛЕКСУС_МОДУЛЬ_ЗАГОЛОВОК 48u
#define ЛЕКСУС_МОДУЛЬ_ПРЕДЕЛ (128u * 1024u * 1024u)
#define ЛЕКСУС_МОДУЛЬ_ИНСТРУКЦИЙ 1000000u
#define ЛЕКСУС_МОДУЛЬ_КОНСТАНТ 100000u
#define ЛЕКСУС_МОДУЛЬ_ВЫЗОВОВ 1000000u

static const unsigned char МАГИЯ[8] = {'L','E','K','S','B','C','0','1'};

enum {
    КОНСТАНТА_НИЧТО = 0,
    КОНСТАНТА_ЛОГИКА = 1,
    КОНСТАНТА_ЧИСЛО = 2,
    КОНСТАНТА_РЕЧЬ = 3
};

typedef struct {
    unsigned char *данные;
    size_t длина;
    size_t ёмкость;
} Буфер;

typedef struct {
    const unsigned char *данные;
    size_t длина;
    size_t позиция;
} Читатель;

static void ошибка(char *куда, size_t размер, const char *текст)
{
    if (куда && размер) snprintf(куда, размер, "%s", текст);
}

static uint32_t прочитать_u32(const unsigned char *p)
{
    return (uint32_t)p[0] |
           ((uint32_t)p[1] << 8) |
           ((uint32_t)p[2] << 16) |
           ((uint32_t)p[3] << 24);
}

static uint16_t прочитать_u16(const unsigned char *p)
{
    return (uint16_t)((uint16_t)p[0] | ((uint16_t)p[1] << 8));
}

static void записать_u16(unsigned char *p, uint16_t значение)
{
    p[0] = (unsigned char)значение;
    p[1] = (unsigned char)(значение >> 8);
}

static void записать_u32(unsigned char *p, uint32_t значение)
{
    p[0] = (unsigned char)значение;
    p[1] = (unsigned char)(значение >> 8);
    p[2] = (unsigned char)(значение >> 16);
    p[3] = (unsigned char)(значение >> 24);
}

static uint32_t crc32(const unsigned char *данные, size_t длина)
{
    uint32_t crc = UINT32_C(0xFFFFFFFF);
    for (size_t i = 0; i < длина; ++i) {
        crc ^= данные[i];
        for (unsigned bit = 0; bit < 8; ++bit) {
            uint32_t маска = (uint32_t)-(int32_t)(crc & 1u);
            crc = (crc >> 1) ^ (UINT32_C(0xEDB88320) & маска);
        }
    }
    return ~crc;
}

static int буфер_добавить(Буфер *буфер, const void *данные, size_t длина)
{
    if (длина > SIZE_MAX - буфер->длина) return 0;
    size_t нужно = буфер->длина + длина;
    if (нужно > ЛЕКСУС_МОДУЛЬ_ПРЕДЕЛ) return 0;
    if (нужно > буфер->ёмкость) {
        size_t новая = буфер->ёмкость ? буфер->ёмкость : 256;
        while (новая < нужно) {
            if (новая > ЛЕКСУС_МОДУЛЬ_ПРЕДЕЛ / 2) {
                новая = ЛЕКСУС_МОДУЛЬ_ПРЕДЕЛ;
                break;
            }
            новая *= 2;
        }
        if (новая < нужно) return 0;
        unsigned char *память = (unsigned char *)realloc(буфер->данные, новая);
        if (!память) return 0;
        буфер->данные = память;
        буфер->ёмкость = новая;
    }
    if (длина) memcpy(буфер->данные + буфер->длина, данные, длина);
    буфер->длина = нужно;
    return 1;
}

static int буфер_u8(Буфер *буфер, uint8_t значение)
{
    return буфер_добавить(буфер, &значение, 1);
}

static int буфер_u32(Буфер *буфер, uint32_t значение)
{
    unsigned char bytes[4];
    записать_u32(bytes, значение);
    return буфер_добавить(буфер, bytes, sizeof(bytes));
}

static int читать(Читатель *читатель, void *куда, size_t длина)
{
    if (длина > читатель->длина - читатель->позиция) return 0;
    if (длина) memcpy(куда, читатель->данные + читатель->позиция, длина);
    читатель->позиция += длина;
    return 1;
}

static int читать_u8(Читатель *читатель, uint8_t *значение)
{
    return читать(читатель, значение, 1);
}

static int читать_u32(Читатель *читатель, uint32_t *значение)
{
    unsigned char bytes[4];
    if (!читать(читатель, bytes, sizeof(bytes))) return 0;
    *значение = прочитать_u32(bytes);
    return 1;
}

static int добавить_константу(Буфер *буфер, ЛексусЗначение значение,
                              char *ошибка_текста, size_t размер_ошибки)
{
    unsigned char вид = 0;
    const void *данные = NULL;
    size_t длина = 0;
    char *число = NULL;
    const char *речь = NULL;
    unsigned char логическое = 0;

    switch (значение.вид) {
        case ЛЕКСУС_НИЧТО:
            вид = КОНСТАНТА_НИЧТО;
            break;
        case ЛЕКСУС_ЛОГИКА:
            логическое = (unsigned char)(значение.данные.логика ? 1 : 0);
            данные = &логическое;
            длина = 1;
            вид = КОНСТАНТА_ЛОГИКА;
            break;
        case ЛЕКСУС_ЧИСЛО: {
            ЛексусОшибка результат = лексус_число_запись(значение, &число);
            if (результат.код != ЛЕКСУС_ОК || !число) {
                ошибка(ошибка_текста, размер_ошибки,
                       результат.сообщение ? результат.сообщение :
                       "не удалось сериализовать числовую константу");
                free(число);
                return 0;
            }
            данные = число;
            длина = strlen(число);
            вид = КОНСТАНТА_ЧИСЛО;
            break;
        }
        case ЛЕКСУС_РЕЧЬ: {
            ЛексусОшибка результат = лексус_речь_текст(значение, &речь, &длина);
            if (результат.код != ЛЕКСУС_ОК || (!речь && длина)) {
                ошибка(ошибка_текста, размер_ошибки,
                       результат.сообщение ? результат.сообщение :
                       "не удалось сериализовать речевую константу");
                return 0;
            }
            данные = речь;
            вид = КОНСТАНТА_РЕЧЬ;
            break;
        }
        default:
            ошибка(ошибка_текста, размер_ошибки,
                   "формат .lekb не допускает ссылочные или исполняемые константы");
            return 0;
    }

    if (длина > UINT32_MAX ||
        !буфер_u8(буфер, вид) ||
        !буфер_u32(буфер, (uint32_t)длина) ||
        !буфер_добавить(буфер, данные, длина)) {
        free(число);
        ошибка(ошибка_текста, размер_ошибки,
               "не удалось записать константу в бинарный модуль");
        return 0;
    }
    free(число);
    return 1;
}

int лексус_байткод_сериализовать(const ЛексусПрограмма *программа,
                                  unsigned char **данные, size_t *длина,
                                  char *ошибка_текста, size_t размер_ошибки)
{
    if (данные) *данные = NULL;
    if (длина) *длина = 0;
    if (ошибка_текста && размер_ошибки) ошибка_текста[0] = '\0';
    if (!данные || !длина || !программа) {
        ошибка(ошибка_текста, размер_ошибки, "не задан входной байткод или место результата");
        return 0;
    }
    if (!лексус_байткод_проверить(программа, ошибка_текста, размер_ошибки))
        return 0;
    if (программа->число_инструкций > ЛЕКСУС_МОДУЛЬ_ИНСТРУКЦИЙ ||
        программа->число_констант > ЛЕКСУС_МОДУЛЬ_КОНСТАНТ ||
        программа->число_функций > UINT16_MAX ||
        программа->число_вызовов > ЛЕКСУС_МОДУЛЬ_ВЫЗОВОВ ||
        программа->число_инструкций > UINT32_MAX ||
        программа->число_констант > UINT32_MAX ||
        программа->число_вызовов > UINT32_MAX ||
        программа->число_позиций > UINT32_MAX) {
        ошибка(ошибка_текста, размер_ошибки, "размер таблиц не поддерживается форматом .lekb");
        return 0;
    }

    Буфер буфер = {0};
    unsigned char заголовок[ЛЕКСУС_МОДУЛЬ_ЗАГОЛОВОК] = {0};
    if (!буфер_добавить(&буфер, заголовок, sizeof(заголовок))) {
        ошибка(ошибка_текста, размер_ошибки, "не удалось выделить память для бинарного модуля");
        return 0;
    }

    for (size_t i = 0; i < программа->число_инструкций; ++i) {
        const ЛексусИнструкция *x = &программа->код[i];
        unsigned char bytes[8] = {
            x->операция, x->назначение, x->а, x->б,
            (unsigned char)x->операнд,
            (unsigned char)(x->операнд >> 8),
            (unsigned char)(x->операнд >> 16),
            (unsigned char)(x->операнд >> 24)
        };
        if (!буфер_добавить(&буфер, bytes, sizeof(bytes))) goto память;
    }

    for (size_t i = 0; i < программа->число_констант; ++i)
        if (!добавить_константу(&буфер, программа->константы[i],
                               ошибка_текста, размер_ошибки)) goto fail;

    for (size_t i = 0; i < программа->число_функций; ++i) {
        const ЛексусФункция *f = &программа->функции[i];
        if (!буфер_u32(&буфер, f->вход) ||
            !буфер_u8(&буфер, f->число_параметров) ||
            !буфер_добавить(&буфер, f->параметры, f->число_параметров)) goto память;
    }

    for (size_t i = 0; i < программа->число_вызовов; ++i) {
        const ЛексусВызов *c = &программа->вызовы[i];
        if (!буфер_u32(&буфер, c->функция) ||
            !буфер_u8(&буфер, c->назначение) ||
            !буфер_u8(&буфер, c->число_аргументов) ||
            !буфер_добавить(&буфер, c->аргументы, c->число_аргументов)) goto память;
    }

    for (size_t i = 0; i < программа->число_позиций; ++i) {
        if (!буфер_u32(&буфер, программа->позиции[i].строка) ||
            !буфер_u32(&буфер, программа->позиции[i].столбец)) goto память;
    }

    if (буфер.длина < ЛЕКСУС_МОДУЛЬ_ЗАГОЛОВОК ||
        буфер.длина - ЛЕКСУС_МОДУЛЬ_ЗАГОЛОВОК > UINT32_MAX) goto память;

    memcpy(буфер.данные, МАГИЯ, sizeof(МАГИЯ));
    записать_u16(буфер.данные + 8, ЛЕКСУС_БАЙТКОД_МАЖОР);
    записать_u16(буфер.данные + 10, ЛЕКСУС_БАЙТКОД_МИНОР);
    записать_u32(буфер.данные + 12, ЛЕКСУС_МОДУЛЬ_ЗАГОЛОВОК);
    записать_u32(буфер.данные + 16, 0);
    записать_u32(буфер.данные + 20, (uint32_t)программа->число_инструкций);
    записать_u32(буфер.данные + 24, (uint32_t)программа->число_констант);
    записать_u16(буфер.данные + 28, программа->регистры);
    записать_u16(буфер.данные + 30, (uint16_t)программа->число_функций);
    записать_u32(буфер.данные + 32, (uint32_t)программа->число_вызовов);
    записать_u32(буфер.данные + 36, (uint32_t)программа->число_позиций);
    записать_u32(буфер.данные + 40,
                 (uint32_t)(буфер.длина - ЛЕКСУС_МОДУЛЬ_ЗАГОЛОВОК));
    записать_u32(буфер.данные + 44,
                 crc32(буфер.данные + ЛЕКСУС_МОДУЛЬ_ЗАГОЛОВОК,
                       буфер.длина - ЛЕКСУС_МОДУЛЬ_ЗАГОЛОВОК));

    *данные = буфер.данные;
    *длина = буфер.длина;
    return 1;

память:
    ошибка(ошибка_текста, размер_ошибки, "превышен размер бинарного модуля или закончилась память");
fail:
    free(буфер.данные);
    return 0;
}

void лексус_байткод_модуль_очистить(ЛексусБинарныйМодуль *модуль)
{
    if (!модуль) return;
    for (size_t i = 0; i < модуль->число_констант; ++i)
        лексус_значение_освободить(&модуль->константы[i]);
    for (size_t i = 0; i < модуль->число_функций; ++i)
        free((void *)модуль->функции[i].параметры);
    for (size_t i = 0; i < модуль->число_вызовов; ++i)
        free((void *)модуль->вызовы[i].аргументы);
    free(модуль->код);
    free(модуль->константы);
    free(модуль->функции);
    free(модуль->вызовы);
    free(модуль->позиции);
    memset(модуль, 0, sizeof(*модуль));
}

void лексус_байткод_модуль_представить(const ЛексусБинарныйМодуль *модуль,
                                        ЛексусПрограмма *программа)
{
    if (!программа) return;
    memset(программа, 0, sizeof(*программа));
    if (!модуль) return;
    программа->код = модуль->код;
    программа->число_инструкций = модуль->число_инструкций;
    программа->константы = модуль->константы;
    программа->число_констант = модуль->число_констант;
    программа->регистры = модуль->регистры;
    программа->функции = модуль->функции;
    программа->число_функций = модуль->число_функций;
    программа->вызовы = модуль->вызовы;
    программа->число_вызовов = модуль->число_вызовов;
    программа->позиции = модуль->позиции;
    программа->число_позиций = модуль->число_позиций;
}

int лексус_байткод_загрузить(const void *сырые_данные, size_t длина,
                              ЛексусБинарныйМодуль *модуль,
                              char *ошибка_текста, size_t размер_ошибки)
{
    if (ошибка_текста && размер_ошибки) ошибка_текста[0] = '\0';
    if (!модуль) {
        ошибка(ошибка_текста, размер_ошибки, "не задано место для загруженного модуля");
        return 0;
    }
    memset(модуль, 0, sizeof(*модуль));
    if (!сырые_данные || длина < ЛЕКСУС_МОДУЛЬ_ЗАГОЛОВОК ||
        длина > ЛЕКСУС_МОДУЛЬ_ПРЕДЕЛ) {
        ошибка(ошибка_текста, размер_ошибки, "размер файла .lekb вне допустимых границ");
        return 0;
    }

    const unsigned char *данные = (const unsigned char *)сырые_данные;
    if (memcmp(данные, МАГИЯ, sizeof(МАГИЯ)) != 0) {
        ошибка(ошибка_текста, размер_ошибки, "неверная сигнатура файла .lekb");
        return 0;
    }
    uint16_t major = прочитать_u16(данные + 8);
    uint16_t minor = прочитать_u16(данные + 10);
    uint32_t размер_заголовка = прочитать_u32(данные + 12);
    uint32_t флаги = прочитать_u32(данные + 16);
    uint32_t число_инструкций = прочитать_u32(данные + 20);
    uint32_t число_констант = прочитать_u32(данные + 24);
    uint16_t регистры = прочитать_u16(данные + 28);
    uint16_t число_функций = прочитать_u16(данные + 30);
    uint32_t число_вызовов = прочитать_u32(данные + 32);
    uint32_t число_позиций = прочитать_u32(данные + 36);
    uint32_t размер_полезной_нагрузки = прочитать_u32(данные + 40);
    uint32_t ожидаемый_crc = прочитать_u32(данные + 44);

    if (major != ЛЕКСУС_БАЙТКОД_МАЖОР || minor > ЛЕКСУС_БАЙТКОД_МИНОР) {
        ошибка(ошибка_текста, размер_ошибки, "версия .lekb не поддерживается этим ядром");
        return 0;
    }
    if (размер_заголовка != ЛЕКСУС_МОДУЛЬ_ЗАГОЛОВОК || флаги != 0) {
        ошибка(ошибка_текста, размер_ошибки, "заголовок .lekb содержит неизвестные поля");
        return 0;
    }
    if (число_инструкций == 0 || число_инструкций > ЛЕКСУС_МОДУЛЬ_ИНСТРУКЦИЙ ||
        число_констант > ЛЕКСУС_МОДУЛЬ_КОНСТАНТ ||
        число_вызовов > ЛЕКСУС_МОДУЛЬ_ВЫЗОВОВ ||
        (число_позиций != 0 && число_позиций != число_инструкций) ||
        регистры == 0 || регистры > 256) {
        ошибка(ошибка_текста, размер_ошибки, "таблицы .lekb превышают допустимые размеры");
        return 0;
    }
    if ((size_t)размер_полезной_нагрузки != длина - ЛЕКСУС_МОДУЛЬ_ЗАГОЛОВОК) {
        ошибка(ошибка_текста, размер_ошибки, "размер полезной нагрузки .lekb не совпадает с файлом");
        return 0;
    }
    if (crc32(данные + ЛЕКСУС_МОДУЛЬ_ЗАГОЛОВОК,
              длина - ЛЕКСУС_МОДУЛЬ_ЗАГОЛОВОК) != ожидаемый_crc) {
        ошибка(ошибка_текста, размер_ошибки, "контрольная сумма .lekb не совпадает");
        return 0;
    }

    Читатель читатель = {данные, длина, ЛЕКСУС_МОДУЛЬ_ЗАГОЛОВОК};
    модуль->код = (ЛексусИнструкция *)calloc(число_инструкций, sizeof(*модуль->код));
    if (!модуль->код) goto память;
    модуль->число_инструкций = число_инструкций;
    модуль->регистры = регистры;

    if (число_констант) {
        модуль->константы = (ЛексусЗначение *)calloc(число_констант, sizeof(*модуль->константы));
        if (!модуль->константы) goto память;
        модуль->число_констант = число_констант;
        for (size_t i = 0; i < число_констант; ++i)
            модуль->константы[i] = лексус_ничто();
    }

    if (число_функций) {
        модуль->функции = (ЛексусФункция *)calloc(число_функций, sizeof(*модуль->функции));
        if (!модуль->функции) goto память;
        модуль->число_функций = число_функций;
    }
    if (число_вызовов) {
        модуль->вызовы = (ЛексусВызов *)calloc(число_вызовов, sizeof(*модуль->вызовы));
        if (!модуль->вызовы) goto память;
        модуль->число_вызовов = число_вызовов;
    }
    if (число_позиций) {
        модуль->позиции = (ЛексусПозицияИсходника *)calloc(число_позиций, sizeof(*модуль->позиции));
        if (!модуль->позиции) goto память;
        модуль->число_позиций = число_позиций;
    }

    for (size_t i = 0; i < число_инструкций; ++i) {
        unsigned char bytes[8];
        if (!читать(&читатель, bytes, sizeof(bytes))) goto повреждён;
        модуль->код[i].операция = bytes[0];
        модуль->код[i].назначение = bytes[1];
        модуль->код[i].а = bytes[2];
        модуль->код[i].б = bytes[3];
        модуль->код[i].операнд = прочитать_u32(bytes + 4);
    }

    for (size_t i = 0; i < число_констант; ++i) {
        uint8_t вид;
        uint32_t число_байтов;
        if (!читать_u8(&читатель, &вид) || !читать_u32(&читатель, &число_байтов) ||
            число_байтов > читатель.длина - читатель.позиция) goto повреждён;
        const unsigned char *начало = читатель.данные + читатель.позиция;
        ЛексусОшибка результат = {ЛЕКСУС_ОК, ""};

        if (вид == КОНСТАНТА_НИЧТО) {
            if (число_байтов != 0) goto повреждён;
            модуль->константы[i] = лексус_ничто();
        } else if (вид == КОНСТАНТА_ЛОГИКА) {
            if (число_байтов != 1 || начало[0] > 1) goto повреждён;
            модуль->константы[i] = лексус_логическое(начало[0] != 0);
        } else if (вид == КОНСТАНТА_ЧИСЛО) {
            if (число_байтов == 0 || memchr(начало, 0, число_байтов)) goto повреждён;
            char *запись = (char *)malloc((size_t)число_байтов + 1);
            if (!запись) goto память;
            memcpy(запись, начало, число_байтов);
            запись[число_байтов] = '\0';
            результат = лексус_число_создать(запись, &модуль->константы[i]);
            free(запись);
            if (результат.код != ЛЕКСУС_ОК) goto повреждён;
        } else if (вид == КОНСТАНТА_РЕЧЬ) {
            результат = лексус_речь_создать((const char *)начало, число_байтов,
                                             &модуль->константы[i]);
            if (результат.код != ЛЕКСУС_ОК) goto повреждён;
        } else {
            goto повреждён;
        }
        читатель.позиция += число_байтов;
    }

    for (size_t i = 0; i < число_функций; ++i) {
        uint32_t вход;
        uint8_t параметров;
        if (!читать_u32(&читатель, &вход) || !читать_u8(&читатель, &параметров))
            goto повреждён;
        модуль->функции[i].вход = вход;
        модуль->функции[i].число_параметров = параметров;
        if (параметров) {
            uint8_t *копия = (uint8_t *)malloc(параметров);
            if (!копия) goto память;
            if (!читать(&читатель, копия, параметров)) {
                free(копия);
                goto повреждён;
            }
            модуль->функции[i].параметры = копия;
        }
    }

    for (size_t i = 0; i < число_вызовов; ++i) {
        uint32_t функция;
        uint8_t назначение, аргументов;
        if (!читать_u32(&читатель, &функция) ||
            !читать_u8(&читатель, &назначение) ||
            !читать_u8(&читатель, &аргументов)) goto повреждён;
        модуль->вызовы[i].функция = функция;
        модуль->вызовы[i].назначение = назначение;
        модуль->вызовы[i].число_аргументов = аргументов;
        if (аргументов) {
            uint8_t *копия = (uint8_t *)malloc(аргументов);
            if (!копия) goto память;
            if (!читать(&читатель, копия, аргументов)) {
                free(копия);
                goto повреждён;
            }
            модуль->вызовы[i].аргументы = копия;
        }
    }

    for (size_t i = 0; i < число_позиций; ++i) {
        uint32_t строка, столбец;
        if (!читать_u32(&читатель, &строка) ||
            !читать_u32(&читатель, &столбец) || !строка || !столбец)
            goto повреждён;
        модуль->позиции[i].строка = строка;
        модуль->позиции[i].столбец = столбец;
    }

    if (читатель.позиция != читатель.длина) goto повреждён;

    ЛексусПрограмма программа;
    лексус_байткод_модуль_представить(модуль, &программа);
    if (!лексус_байткод_проверить(&программа, ошибка_текста, размер_ошибки)) {
        лексус_байткод_модуль_очистить(модуль);
        return 0;
    }
    return 1;

память:
    ошибка(ошибка_текста, размер_ошибки, "не хватает памяти для загрузки модуля .lekb");
    лексус_байткод_модуль_очистить(модуль);
    return 0;

повреждён:
    ошибка(ошибка_текста, размер_ошибки, "повреждённая секция бинарного модуля .lekb");
    лексус_байткод_модуль_очистить(модуль);
    return 0;
}
