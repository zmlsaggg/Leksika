/* Фиксированные 8 байт: код, назначение, левый регистр, правый регистр,
 * 32-битный операнд. Нет указателей или объектов AST в программе. */
typedef struct {
    uint8_t операция;
    uint8_t назначение;
    uint8_t а;
    uint8_t б;
    uint32_t операнд;
} ЛексусИнструкция;

typedef struct {
    uint32_t вход;
    const uint8_t *параметры;
    uint8_t число_параметров;
} ЛексусФункция;

