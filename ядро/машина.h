#ifndef ЛЕКСУС_МАШИНА_H
#define ЛЕКСУС_МАШИНА_H
#include "байткод.h"
#include <stddef.h>
#include <stdint.h>

typedef int (*ЛексусВводСреды)(void *контекст,char *буфер,size_t вместимость,size_t *длина);
typedef int (*ЛексусВыводСреды)(void *контекст,const char *данные,size_t длина);

typedef enum {
    ЛЕКСУС_РАЗРЕШИТЬ_ВВОД = 1u << 0,
    ЛЕКСУС_РАЗРЕШИТЬ_ВЫВОД = 1u << 1,
    ЛЕКСУС_РАЗРЕШИТЬ_ФАЙЛ_ЧТЕНИЕ = 1u << 2,
    ЛЕКСУС_РАЗРЕШИТЬ_ФАЙЛ_ЗАПИСЬ = 1u << 3,
    ЛЕКСУС_РАЗРЕШИТЬ_СЕТЬ = 1u << 4,
    ЛЕКСУС_РАЗРЕШИТЬ_ПРОЦЕСС = 1u << 5,
    ЛЕКСУС_РАЗРЕШИТЬ_СЕКРЕТЫ = 1u << 6
} ЛексусРазрешение;

typedef int (*ЛексусПроверкаРазрешения)(void *контекст,uint32_t действие,const char *ресурс);

typedef struct {
    void *контекст;
    /* Ввод: 1 — строка получена, 0 — конец ввода, -1 — ошибка. Перевод строки не включается. */
    ЛексусВводСреды ввод;
    /* Вывод: 1 — данные приняты, 0 — ошибка. */
    ЛексусВыводСреды вывод;
    /* Набор действий, которые среда разрешает VM. Ноль означает запрет всего. */
    uint32_t разрешения;
    /* Дополнительный allowlist/аудит конкретного ресурса; 1 — разрешено. */
    ЛексусПроверкаРазрешения проверить_разрешение;
} ЛексусСредаИсполнения;

int лексус_машина_исполнить_со_средой(const ЛексусПрограмма *программа,uint64_t предел_шагов,
                                      const ЛексусСредаИсполнения *среда,
                                      ЛексусЗначение *результат,char *ошибка,size_t размер_ошибки);
int лексус_машина_исполнить(const ЛексусПрограмма *программа,uint64_t предел_шагов,
                            ЛексусЗначение *результат,char *ошибка,size_t размер_ошибки);
#endif
