  class Разборщик {
    constructor(токены) {
      this.токены = токены;
      this.позиция = 0;
    }
    текущий(сдвиг = 0) {
      return this.токены[Math.min(this.позиция + сдвиг, this.токены.length - 1)];
    }
    слово(значение, сдвиг = 0) {
      const токен = this.текущий(сдвиг);
      return токен.вид === "слово" && токен.значение === значение;
    }
    знак(значение, сдвиг = 0) {
      const токен = this.текущий(сдвиг);
      return токен.вид === "знак" && токен.значение === значение;
    }
    взять() {
      const токен = this.текущий();
      if (токен.вид !== "конец") this.позиция += 1;
      return токен;
    }
    ошибка(сообщение) {
      throw new ОшибкаКода(сообщение, this.текущий());
    }
    ждатьЗнак(значение) {
      if (!this.знак(значение)) this.ошибка("Ожидался знак «" + значение + "»");
      return this.взять();
    }
    ждатьСлово(значение) {
      if (!this.слово(значение)) this.ошибка("Ожидалось слово «" + значение + "»");
      return this.взять();
    }
    разделители() {
      while (this.текущий().вид === "новаяСтрока"
          || (this.текущий().вид === "знак" && [".", "!", "?", ";", ","].includes(this.текущий().значение))) {
        this.взять();
      }
    }
    программа(стоп = () => false) {
      const операторы = [];
      this.разделители();
      while (this.текущий().вид !== "конец" && !стоп()) {
        const до = this.позиция;
        операторы.push(this.оператор());
        if (this.позиция === до) this.ошибка("Не удалось разобрать действие");
        this.разделители();
      }
      return операторы;
    }
    оператор() {
      const токен = this.текущий();
      if (токен.вид === "новаяСтрока") {
        this.разделители();
        return { вид: "пусто" };
      }
      if (this.слово("пусть")) return this.объявление();
      if (this.слово("сказать") || this.слово("вывести") || this.слово("показать")) return this.сказать();
      if (this.слово("вернуть")) return this.вернуть();
      if (this.слово("если")) return this.если();
      if (this.слово("пока")) return this.пока();
      if (this.слово("для")) return this.дляКаждого();
      if (this.слово("повторить")) return this.повторить();
      if (this.слово("правило")) return this.правило();
      if (this.слово("увеличить") || this.слово("уменьшить")) return this.изменить();
      if (this.слово("прервать")) {
        this.взять();
        return { вид: "прервать" };
      }
      if (this.слово("продолжить")) {
        this.взять();
        return { вид: "продолжить" };
      }
      if (токен.вид === "слово" && this.текущий(1).вид === "знак"
          && ["=", "+=", "-=", "*=", "/=", "++", "--"].includes(this.текущий(1).значение)) {
        return this.присваивание();
      }
      if (токен.вид === "слово" && this.текущий(1).вид === "слово"
          && ["равно"].includes(this.текущий(1).значение)) {
        return this.присваиваниеСловами();
      }
      const выражение = this.выражение();
      return { вид: "выражение", выражение };
    }
    конецВыражения() {
      return this.текущий().вид === "конец" || this.текущий().вид === "новаяСтрока"
        || (this.текущий().вид === "знак" && [".", "!", "?", ";", "}"].includes(this.текущий().значение));
    }
    объявление() {
      this.взять();
      const имя = this.взять();
      if (имя.вид !== "слово") this.ошибка("После «пусть» нужно русское имя переменной");
      if (this.знак("=") || this.слово("равно")) this.взять();
      else this.ошибка("После имени переменной нужно «равно» или =");
      return { вид: "объявить", имя: имя.значение, значение: this.выражение() };
    }
    сказать() {
      this.взять();
      let выражение;
      if (this.знак("(")) {
        this.взять();
        выражение = this.выражение();
        this.ждатьЗнак(")");
      } else {
        выражение = this.выражение();
      }
      return { вид: "сказать", выражение };
    }
    вернуть() {
      this.взять();
      if (this.конецВыражения() || this.слово("конец")) return { вид: "вернуть", выражение: null };
      if (this.знак("(")) {
        this.взять();
        const выражение = this.знак(")") ? null : this.выражение();
        this.ждатьЗнак(")");
        return { вид: "вернуть", выражение };
      }
      return { вид: "вернуть", выражение: this.выражение() };
    }
    присваивание() {
      const имя = this.взять().значение;
      const знак = this.взять().значение;
      if (знак === "++" || знак === "--") {
        return { вид: "изменить", имя, действие: знак === "++" ? "+" : "-", значение: { вид: "число", значение: 1 } };
      }
      return { вид: "присвоить", имя, действие: знак, значение: this.выражение() };
    }
    присваиваниеСловами() {
      const имя = this.взять().значение;
      this.ждатьСлово("равно");
      return { вид: "присвоить", имя, действие: "=", значение: this.выражение() };
    }
    изменить() {
      const действие = this.взять().значение === "увеличить" ? "+" : "-";
      const имя = this.взять();
      if (имя.вид !== "слово") this.ошибка("Нужно имя переменной");
      if (this.слово("на")) this.взять();
      return { вид: "изменить", имя: имя.значение, действие, значение: this.выражение() };
    }
    условие() {
      if (this.знак("(")) {
        this.взять();
        const условие = this.выражение();
        this.ждатьЗнак(")");
        return условие;
      }
      return this.выражение(["то"]);
    }
    тело(стопСлова = []) {
      this.разделители();
      if (this.знак("{")) {
        this.взять();
        const результат = this.программа(() => this.знак("}"));
        this.ждатьЗнак("}");
        return результат;
      }
      return this.программа(() => стопСлова.some((слово) => this.слово(слово)) || this.знак("}"));
    }
    закрытьСловесныйБлок(название) {
      if (this.слово("конец")) {
        this.взять();
        if (this.слово(название)) this.взять();
      }
    }
    если() {
      this.взять();
      const условие = this.условие();
      if (this.слово("то")) this.взять();
      const да = this.тело(["иначе", "конец"]);
      let нет = [];
      if (this.слово("иначе")) {
        this.взять();
        if (this.слово("если")) {
          нет = [this.если()];
        } else {
          нет = this.тело(["конец"]);
        }
      }
      this.закрытьСловесныйБлок("если");
      return { вид: "если", условие, да, нет };
    }
    пока() {
      this.взять();
      const условие = this.условие();
      if (this.слово("повторять")) this.взять();
      const тело = this.тело(["конец"]);
      this.закрытьСловесныйБлок("пока");
      return { вид: "пока", условие, тело };
    }
    дляКаждого() {
      this.взять();
      if (this.слово("каждого")) this.взять();
      const имя = this.взять();
      if (имя.вид !== "слово") this.ошибка("После «для каждого» нужно имя переменной");
      if (this.слово("из") || this.слово("в")) this.взять();
      else this.ошибка("Нужен предлог «из» или «в»");
      const перечень = this.выражение(["повторять"]);
      if (this.слово("повторять")) this.взять();
      const тело = this.тело(["конец"]);
      this.закрытьСловесныйБлок("для");
      return { вид: "для", имя: имя.значение, перечень, тело };
    }
    повторить() {
      this.взять();
      const количество = this.выражение(["раз"]);
      if (this.слово("раз") || this.слово("раза")) this.взять();
      const тело = this.тело(["конец"]);
      this.закрытьСловесныйБлок("повтора");
      return { вид: "повторить", количество, тело };
    }
    правило() {
      this.взять();
      const имя = this.взять();
      if (имя.вид !== "слово") this.ошибка("После «правило» нужно имя");
      const параметры = [];
      if (this.знак("(")) {
        this.взять();
        while (!this.знак(")") && this.текущий().вид !== "конец") {
          if (this.слово("целое") || this.слово("число") || this.слово("речь")) this.взять();
          const параметр = this.взять();
          if (параметр.вид !== "слово") this.ошибка("Ожидалось имя параметра");
          параметры.push(параметр.значение);
          if (this.знак(",")) this.взять();
          else break;
        }
        this.ждатьЗнак(")");
      } else if (this.слово("принимает")) {
        this.взять();
        while (this.текущий().вид === "слово" && !this.слово("повторять")
            && !this.слово("иначе") && !this.слово("конец") && !this.знак("{")) {
          if (!["и"].includes(this.текущий().значение)) параметры.push(this.взять().значение);
          else this.взять();
          if (this.знак(",")) this.взять();
        }
      }
      if (this.слово("повторять")) this.взять();
      const тело = this.тело(["конец"]);
      this.закрытьСловесныйБлок("правила");
      return { вид: "правило", имя: имя.значение, параметры, тело };
    }
    выражение(стопСлова = [], минимум = 0) {
      let левое = this.первичное();

      while (true) {
        const оп = this.операторВыражения(стопСлова);
        if (!оп || оп.приоритет < минимум) break;
        for (let шаг = 0; шаг < оп.длина; шаг += 1) this.взять();
        const правое = this.выражение(стопСлова, оп.приоритет + (оп.право ? 0 : 1));
        левое = { вид: "действие", действие: оп.знак, левое, правое };
      }
      return левое;
    }
    операторВыражения(стопСлова) {
      const токен = this.текущий();
      if (токен.вид === "новаяСтрока" || токен.вид === "конец"
          || (токен.вид === "знак" && [")", "]", "}", ",", ";", ".", "!", "?", ":"].includes(токен.значение))) return null;
      if (токен.вид === "слово" && стопСлова.includes(токен.значение)) return null;

      const следующий = this.текущий(1);
      const слово = (т, значение) => т.вид === "слово" && т.значение === значение;
      if (слово(токен, "не") && слово(следующий, "равно")) return { знак: "неравно", приоритет: 3, длина: 2 };
      if (слово(токен, "не") && слово(следующий, "меньше")) return { знак: "неменьше", приоритет: 3, длина: 2 };
      if (слово(токен, "не") && слово(следующий, "больше")) return { знак: "небольше", приоритет: 3, длина: 2 };
      if (слово(токен, "умножить") && слово(следующий, "на")) return { знак: "*", приоритет: 5, длина: 2 };
      if (слово(токен, "разделить") && слово(следующий, "на")) return { знак: "/", приоритет: 5, длина: 2 };
      if (слово(токен, "остаток") && слово(следующий, "от")) return { знак: "%", приоритет: 5, длина: 2 };
      if (слово(токен, "в") && слово(следующий, "степени")) return { знак: "**", приоритет: 6, длина: 2, право: true };

      let знак = токен.значение;
      if (токен.вид === "знак") {
        if (знак === "==") знак = "равно";
        if (знак === "!=") знак = "неравно";
        if (знак === ">=") знак = "неменьше";
        if (знак === "<=") знак = "небольше";
        if (знак === ">") знак = "больше";
        if (знак === "<") знак = "меньше";
      }
      const приоритет = {
        "или": 1, "||": 1, "и": 2, "&&": 2,
        "равно": 3, "неравно": 3, "больше": 3, "меньше": 3,
        "неменьше": 3, "небольше": 3, "содержит": 3,
        "+": 4, "-": 4, "плюс": 4, "минус": 4,
        "*": 5, "/": 5, "%": 5, "**": 6
      }[знак];
      if (приоритет === undefined) return null;
      return { знак, приоритет, длина: 1, право: знак === "**" };
    }
    первичное() {
      const токен = this.текущий();
      if (токен.вид === "число") {
        this.взять();
        return { вид: "число", значение: токен.значение };
      }
      if (токен.вид === "речь") {
        this.взять();
        return { вид: "речь", части: токен.значение };
      }
      if (токен.вид === "знак" && токен.значение === "-") {
        this.взять();
        return { вид: "унарное", действие: "минус", значение: this.выражение([], 7) };
      }
      if (this.знак("(")) {
        this.взять();
        const выражение = this.выражение();
        this.ждатьЗнак(")");
        return выражение;
      }
      if (this.знак("[")) {
        this.взять();
        const элементы = [];
        while (!this.знак("]") && this.текущий().вид !== "конец") {
          элементы.push(this.выражение());
          if (this.знак(",")) this.взять();
          else break;
        }
        this.ждатьЗнак("]");
        return { вид: "перечень", элементы };
      }
      if (токен.вид === "слово") {
        const имя = токен.значение;
        if (["минус", "не"].includes(имя)) {
          this.взять();
          return { вид: "унарное", действие: имя, значение: this.выражение([], 7) };
        }
        if (имя === "истина" || имя === "верно" || имя === "да") {
          this.взять();
          return { вид: "число", значение: true };
        }
        if (имя === "ложь" || имя === "нет") {
          this.взять();
          return { вид: "число", значение: false };
        }
        if (имя === "ничто" || имя === "пусто") {
          this.взять();
          return { вид: "число", значение: null };
        }
        if (Object.prototype.hasOwnProperty.call(ЧИСЛА, имя)) {
          let значение = 0;
          let накоплено = 0;
          while (this.текущий().вид === "слово"
              && Object.prototype.hasOwnProperty.call(ЧИСЛА, this.текущий().значение)) {
            const часть = ЧИСЛА[this.взять().значение];
            if (часть >= 1000) {
              накоплено = (накоплено || 1) * часть;
              значение += накоплено;
              накоплено = 0;
            } else if (часть >= 100) {
              накоплено = (накоплено || 1) * часть;
            } else {
              накоплено += часть;
            }
          }
          return { вид: "число", значение: значение + накоплено };
        }
        this.взять();
        if (this.знак("(")) {
          this.взять();
          const аргументы = [];
          while (!this.знак(")") && this.текущий().вид !== "конец") {
            аргументы.push(this.выражение());
            if (this.знак(",")) this.взять();
            else break;
          }
          this.ждатьЗнак(")");
          return { вид: "вызов", имя, аргументы };
        }
        return { вид: "имя", имя };
      }
      this.ошибка("Здесь ожидалось число, русское имя, речь или выражение в скобках");
    }
  }

  // Учебное сопоставление русских падежных форм имён переменных.
  // Это не замена полной морфологии Лексуса: неоднозначные совпадения не выбираются.
  function основаИмени(имя) {
    const слово = String(имя).toLowerCase().replace(/ё/g, "е");
    const окончания = [
      "иями", "ями", "ами", "ого", "его", "ому", "ему", "ыми", "ими",
      "иях", "ах", "ях", "ов", "ев", "ей", "ам", "ям",
      "ую", "юю", "ая", "яя", "ое", "ее", "ые", "ие",
      "ой", "ей", "ом", "ем", "ую", "юю", "ы", "и", "а", "я", "у", "ю", "е", "о"
    ];
    for (const окончание of окончания) {
      if (слово.length > окончание.length + 1 && слово.endsWith(окончание)) {
        return слово.slice(0, -окончание.length);
      }
    }
    return слово;
  }

  class Область {
    constructor(родитель = null) {
      this.родитель = родитель;
      this.значения = new Map();
    }
    объявить(имя, значение) {
      this.значения.set(имя, значение);
    }
    найтиИмя(имя) {
      if (this.значения.has(имя)) return имя;
      const основа = основаИмени(имя);
      const совпадения = [...this.значения.keys()].filter((кандидат) =>
        основаИмени(кандидат) === основа
      );
      if (совпадения.length === 1) return совпадения[0];
      if (совпадения.length > 1) {
        throw new Error("Форма «" + имя + "» неоднозначна. Укажите точное имя переменной: "
          + совпадения.join(", "));
      }
      return this.родитель ? this.родитель.найтиИмя(имя) : null;
    }
    найти(имя) {
      const найденное = this.найтиИмя(имя);
      if (найденное !== null) return this.значения.has(найденное)
        ? this.значения.get(найденное) : this.родитель.найти(найденное);
      throw new Error("Имя «" + имя + "» ещё не объявлено. Проверьте объявление и падеж имени.");
    }
    записать(имя, значение) {
      const найденное = this.найтиИмя(имя);
      if (найденное !== null) {
        if (this.значения.has(найденное)) this.значения.set(найденное, значение);
        else this.родитель.записать(найденное, значение);
        return;
      }
      this.значения.set(имя, значение);
    }
    есть(имя) {
      return this.найтиИмя(имя) !== null;
    }
  }

  class Исполнитель {
    constructor(печатать) {
      this.печать = печатать;
      this.главная = new Область();
      this.область = this.главная;
      this.правила = new Map();
      this.шаги = 0;
      this.глубина = 0;
    }
    шаг() {
      this.шаги += 1;
      if (this.шаги > 100000) throw new Error("Программа превысила предел в 100 000 действий");
    }
    значение(узел, область = this.область) {
      switch (узел.вид) {
        case "число": return узел.значение;
        case "имя": return область.найти(узел.имя);
        case "перечень": return узел.элементы.map((элемент) => this.значение(элемент, область));
        case "речь": return this.речь(узел.части, область);
        case "унарное": {
          const значение = this.значение(узел.значение, область);
          if (узел.действие === "не") return !this.правда(значение);
          return -this.число(значение);
        }
        case "действие": return this.действие(узел.действие,
          this.значение(узел.левое, область), this.значение(узел.правое, область));
        case "вызов": {
          const аргументы = узел.аргументы.map((аргумент) => this.значение(аргумент, область));
          return this.позвать(узел.имя, аргументы);
        }
        default: throw new Error("Неизвестное выражение «" + узел.вид + "»");
      }
    }
    число(значение) {
      if (typeof значение !== "number" || !Number.isFinite(значение)) {
        throw new Error("Ожидалось конечное число");
      }
      return значение;
    }
    правда(значение) {
      return !!значение;
    }
    действие(оператор, а, б) {
      switch (оператор) {
        case "+": case "плюс":
          if (typeof а === "string" || typeof б === "string") return String(а) + String(б);
          if (Array.isArray(а) && Array.isArray(б)) return а.concat(б);
          return this.число(а) + this.число(б);
        case "-": case "минус": return this.число(а) - this.число(б);
        case "*": return this.число(а) * this.число(б);
        case "/":
          if (this.число(б) === 0) throw new Error("Делить на ноль нельзя");
          return this.число(а) / this.число(б);
        case "%":
          if (this.число(б) === 0) throw new Error("Остаток от деления на ноль не определён");
          return this.число(а) % this.число(б);
        case "**": return this.число(а) ** this.число(б);
        case "равно": return а === б;
        case "неравно": return а !== б;
        case "больше": return а > б;
        case "меньше": return а < б;
        case "неменьше": return а >= б;
        case "небольше": return а <= б;
        case "и": case "&&": return this.правда(а) && this.правда(б);
        case "или": case "||": return this.правда(а) || this.правда(б);
        case "содержит":
          if (Array.isArray(а)) return а.includes(б);
          if (typeof а === "string") return а.includes(String(б));
          return false;
        default: throw new Error("Неизвестная операция «" + оператор + "»");
      }
    }
    речь(части, область) {
      return части.map((часть) => {
        if (часть.вид === "текст") return часть.значение;
        const разбор = new Разборщик(разобратьТокены(часть.значение));
        const дерево = разбор.выражение();
        if (разбор.текущий().вид !== "конец") throw new Error("Не удалось разобрать вставку в речи");
        return this.какРечь(this.значение(дерево, область));
      }).join("");
    }
    какРечь(значение) {
      if (значение === null) return "ничто";
      if (значение === true) return "истина";
      if (значение === false) return "ложь";
      if (Array.isArray(значение)) return "перечень(" + значение.map((x) => this.какРечь(x)).join(", ") + ")";
      if (значение instanceof Map) return "словарь(" + Array.from(значение.entries()).map(([k, v]) => this.какРечь(k) + ": " + this.какРечь(v)).join(", ") + ")";
      return String(значение);
    }
    встроенное(имя, значения) {
      const один = () => {
        if (значения.length !== 1) throw new Error("Действие «" + имя + "» принимает один аргумент");
        return значения[0];
      };
      switch (имя) {
        case "перечень": return значения;
        case "словарь": return new Map();
        case "длина": {
          const значение = один();
          if (Array.isArray(значение) || typeof значение === "string") return значение.length;
          if (значение instanceof Map) return значение.size;
          throw new Error("У этого значения нет длины");
        }
        case "корень": return Math.sqrt(this.число(один()));
        case "модуль": return Math.abs(this.число(один()));
        case "округлить": return Math.round(this.число(один()));
        case "целое": return Math.trunc(this.число(один()));
        case "строка": return this.какРечь(один());
        case "ключи": {
          const значение = один();
          if (!(значение instanceof Map)) throw new Error("Ключи есть только у словаря");
          return Array.from(значение.keys());
        }
        case "взять": {
          if (значения.length !== 2 || !Array.isArray(значения[0])) throw new Error("Взять: нужны перечень и номер");
          return значения[0][this.число(значения[1])];
        }
        case "случайное": {
          if (значения.length !== 2) throw new Error("Случайное: укажите начало и конец");
          const от = Math.ceil(this.число(значения[0]));
          const до = Math.floor(this.число(значения[1]));
          if (до < от) throw new Error("Верхняя граница меньше нижней");
          return от + Math.floor(Math.random() * (до - от + 1));
        }
        default: return undefined;
      }
    }
    позвать(имя, значения) {
      const встроенное = this.встроенное(имя, значения);
      if (встроенное !== undefined || ["ничто", "словарь"].includes(имя)) return встроенное;
      const правило = this.правила.get(имя);
      if (!правило) throw new Error("Неизвестное правило или действие «" + имя + "»");
      if (значения.length !== правило.параметры.length) {
        throw new Error("Правило «" + имя + "» ожидает " + правило.параметры.length + " аргументов, получено " + значения.length);
      }
      if (this.глубина >= 100) throw new Error("Слишком глубокая рекурсия");
      const прежняя = this.область;
      const локальная = new Область(прежняя);
      правило.параметры.forEach((параметр, индекс) => локальная.объявить(параметр, значения[индекс]));
      this.область = локальная;
      this.глубина += 1;
      try {
        const сигнал = this.операторы(правило.тело);
        return сигнал && сигнал.вид === "вернуть" ? сигнал.значение : null;
      } finally {
        this.область = прежняя;
        this.глубина -= 1;
      }
    }
    операторы(список) {
      for (const узел of список) {
        this.шаг();
        const сигнал = this.оператор(узел);
        if (сигнал) return сигнал;
      }
      return null;
    }
    оператор(узел) {
      switch (узел.вид) {
        case "пусто": return null;
        case "объявить":
          this.область.объявить(узел.имя, this.значение(узел.значение));
          return null;
        case "присвоить": {
          const прежнее = узел.действие === "=" ? null : this.область.найти(узел.имя);
          const новое = this.значение(узел.значение);
          this.область.записать(узел.имя, узел.действие === "=" ? новое
            : this.действие(({ "+=": "+", "-=": "-", "*=": "*", "/=": "/" })[узел.действие], прежнее, новое));
          return null;
        }
        case "изменить": {
          const прежнее = this.область.найти(узел.имя);
          this.область.записать(узел.имя, this.действие(узел.действие, прежнее, this.значение(узел.значение)));
          return null;
        }
        case "сказать":
          this.печать(this.какРечь(this.значение(узел.выражение)));
          return null;
        case "выражение":
          this.значение(узел.выражение);
          return null;
        case "правило":
          this.правила.set(узел.имя, узел);
          return null;
        case "вернуть":
          return { вид: "вернуть", значение: узел.выражение ? this.значение(узел.выражение) : null };
        case "если":
          return this.правда(this.значение(узел.условие))
            ? this.операторы(узел.да)
            : this.операторы(узел.нет);
        case "пока": {
          let витки = 0;
          while (this.правда(this.значение(узел.условие))) {
            if (++витки > 10000) throw new Error("Цикл превысил предел в 10 000 повторов");
            const сигнал = this.операторы(узел.тело);
            if (сигнал && сигнал.вид === "вернуть") return сигнал;
            if (сигнал && сигнал.вид === "прервать") break;
          }
          return null;
        }
        case "для": {
          const значения = this.значение(узел.перечень);
          if (!Array.isArray(значения) && typeof значения !== "string") throw new Error("Для перебора нужен перечень или речь");
          const прежняя = this.область;
          const локальная = new Область(прежняя);
          this.область = локальная;
          try {
            let витки = 0;
            for (const значение of значения) {
              if (++витки > 10000) throw new Error("Перебор превысил предел в 10 000 элементов");
              локальная.записать(узел.имя, значение);
              const сигнал = this.операторы(узел.тело);
              if (сигнал && сигнал.вид === "вернуть") return сигнал;
              if (сигнал && сигнал.вид === "прервать") break;
            }
          } finally {
            this.область = прежняя;
          }
          return null;
        }
        case "повторить": {
          const количество = Math.floor(this.число(this.значение(узел.количество)));
          if (количество < 0 || количество > 10000) throw new Error("Количество повторов должно быть от 0 до 10 000");
          for (let виток = 0; виток < количество; виток += 1) {
            const сигнал = this.операторы(узел.тело);
            if (сигнал && сигнал.вид === "вернуть") return сигнал;
            if (сигнал && сигнал.вид === "прервать") break;
          }
          return null;
        }
        case "прервать": return { вид: "прервать" };
        case "продолжить": return { вид: "продолжить" };
        default: throw new Error("Неизвестная команда «" + узел.вид + "»");
      }
    }
    запустить(операторы) {
      for (const узел of операторы) {
        if (узел.вид === "правило") this.правила.set(узел.имя, узел);
      }
      return this.операторы(операторы);
    }
  }

