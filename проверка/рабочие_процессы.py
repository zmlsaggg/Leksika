#!/usr/bin/env python3
"""Проверка, что в shell-вставках рабочих процессов нет кириллических имён.

Bash не принимает кириллические идентификаторы: `for имя in …` отвечает
«имя: not a valid identifier», причём задание при этом может выглядеть
успешным — цикл просто не выполняется ни разу. Так молча пропускались и
проверка полноты установщика, и сверка скачанных файлов релиза.

Скрипт разбирает `.github/workflows/*.yml`, вынимает блоки `run:` и ищет в них
кириллические имена переменных, параметры `for`/`read` и имена функций.
Заодно проверяются все `*.sh` в репозитории.

Запуск: python3 проверка/рабочие_процессы.py
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent

КИРИЛЛИЦА = "А-Яа-яЁё"
# for имя in … / for каталог in … / read -r имя
ЦИКЛ = re.compile(rf"\b(for|read)\s+(?:-\S+\s+)*([{КИРИЛЛИЦА}][\w]*)")
# Присваивание в начале команды: каталог="$1"
ПРИСВАИВАНИЕ = re.compile(rf"(?:^|[;&|(]|\bthen\b|\bdo\b|\belse\b)\s*([{КИРИЛЛИЦА}][\w]*)=")
# Определение функции: отправить() {
ФУНКЦИЯ = re.compile(rf"(?:^|[;&|(])\s*([{КИРИЛЛИЦА}][\w]*)\s*\(\)\s*\{{")


def скрипты_процессов(текст: str):
    """Возвращает список (номер_строки, строка) для содержимого блоков run:."""
    строки = текст.split("\n")
    вывод = []
    i = 0
    while i < len(строки):
        строка = строки[i]
        совпадение = re.match(r"^(\s*)(?:-\s+)?run:\s*[|>]", строка)
        if not совпадение:
            i += 1
            continue
        отступ = len(совпадение.group(1))
        i += 1
        while i < len(строки):
            текущая = строки[i]
            if текущая.strip() and (len(текущая) - len(текущая.lstrip())) <= отступ:
                break
            вывод.append((i + 1, текущая))
            i += 1
    return вывод


ОГРАНИЧИТЕЛЬ = re.compile(r"<<-?\s*['\"]?([A-Za-zА-Яа-яЁё_]+)['\"]?")


def нарушения(строки):
    найдено = []
    продолжение = False
    ограничитель = None
    for номер, строка in строки:
        if ограничитель is not None:
            # Внутри heredoc лежит чужой язык (Python, Ruby): его имена не наши.
            if строка.strip() == ограничитель:
                ограничитель = None
            continue
        совпало = ОГРАНИЧИТЕЛЬ.search(строка)
        if совпало:
            ограничитель = совпало.group(1)
            continue
        if продолжение:
            # Строка продолжает предыдущую команду — это её аргументы, а не
            # присваивания shell (например, переменные make: ИМЯ=значение).
            продолжение = строка.rstrip().endswith("\\")
            continue
        продолжение = строка.rstrip().endswith("\\")
        код = строка.split("#", 1)[0] if строка.lstrip().startswith("#") else строка
        for шаблон, что in ((ЦИКЛ, "имя переменной в цикле"),
                            (ПРИСВАИВАНИЕ, "имя переменной"),
                            (ФУНКЦИЯ, "имя функции")):
            for совпадение in шаблон.finditer(код):
                имя = совпадение.group(2) if шаблон is ЦИКЛ else совпадение.group(1)
                найдено.append((номер, что, имя, строка.strip()))
    return найдено


def проверить_файл(путь: Path, строки):
    ошибки = нарушения(строки)
    for номер, что, имя, строка in ошибки:
        print(f"{путь.relative_to(КОРЕНЬ)}:{номер}: {что} «{имя}»: {строка}")
    return ошибки


def самотест() -> None:
    пример = '''
    for имя in a b; do echo "$имя"; done
    каталог="$1"
    отправить() { echo раз; }
    echo "версия=${VERSION}"   # это не идентификатор, а текст в кавычках
'''
    строки = [(номер, строка) for номер, строка in enumerate(пример.split("\n"), 1)]
    ошибки = нарушения(строки)
    имена = sorted(имя for _, _, имя, _ in ошибки)
    if имена != ["имя", "каталог", "отправить"]:
        raise SystemExit(f"самотест не сработал: {имена}")
    # Латинский вариант не должен считаться нарушением.
    чистый = [(1, 'for part in a b; do echo "$part"; done'),
              (2, 'repo_dir="$1"'),
              (3, 'push_repo() { echo ok; }')]
    if нарушения(чистый):
        raise SystemExit("самотест: латинские имена приняты за нарушение")


def main() -> int:
    самотест()
    всего = 0
    файлы = sorted((КОРЕНЬ / ".github" / "workflows").glob("*.yml"))
    файлы += sorted(КОРЕНЬ.rglob("*.sh"))
    for путь in файлы:
        if any(часть in путь.parts for часть in ("node_modules", ".git", "сборка/груз")):
            continue
        текст = путь.read_text(encoding="utf-8")
        строки = скрипты_процессов(текст) if путь.suffix == ".yml" else \
            list(enumerate(текст.split("\n"), 1))
        всего += len(проверить_файл(путь, строки))
    if всего:
        print(f"\nкириллических имён в shell: {всего} — bash их не принимает", file=sys.stderr)
        return 1
    print(f"кириллических имён в shell нет: проверено файлов {len(файлы)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
