#!/usr/bin/env python3
"""Сверка нативной таблицы служебных словоформ с эталонным словарём.

Ядро не может импортировать Python-словарь, поэтому `ядро/словарь_формы.h`
собран вручную. Эта проверка ловит расхождения, которые иначе всплыли бы
только на живом пользователе:

1. каждую словоформу Python-словаря ядро обязано знать с той же леммой;
2. каждая запись C-таблицы должна свестись к лемме из Python-словаря;
3. регистр — это не отдельная словоформа: таблица хранит варианты написания,
   проверка отдельно сообщает, сколько их.

Запуск: python3 проверка/словарь_ядра.py
"""

import re
import sys
import unittest
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ))

if not getattr(sys, "_лексика_загрузка", False):
    _загрузка = КОРЕНЬ / "лексика" / "загрузка.lek"
    exec(compile(_загрузка.read_text(encoding="utf-8"), str(_загрузка), "exec"),
         {"__name__": "лексика.загрузка", "__file__": str(_загрузка)})

from лексика import словарь  # noqa: E402

ТАБЛИЦА = КОРЕНЬ / "ядро" / "словарь_формы.h"
ЗАПИСЬ = re.compile(r'\{"([^"]+)", "([^"]+)"\}')


def нативная_таблица():
    return dict(ЗАПИСЬ.findall(ТАБЛИЦА.read_text(encoding="utf-8")))


def эталон():
    формы = {}
    for лемма, свои in словарь.СЛУЖЕБНЫЕ.items():
        формы[лемма] = лемма
        for форма in свои:
            формы.setdefault(форма, лемма)
    for лемма in словарь.КОМАНДЫ:
        формы.setdefault(лемма, лемма)
    return формы


class СловарьЯдра(unittest.TestCase):
    def setUp(self):
        self.нативные = нативная_таблица()
        self.эталон = эталон()

    def test_каждая_форма_эталона_известна_ядру(self):
        пропущенные = sorted(форма for форма in self.эталон if форма not in self.нативные)
        self.assertEqual(пропущенные, [],
                         "эти формы Python-словаря ядро не знает и не поймёт")

    def test_леммы_совпадают(self):
        расхождения = [(форма, self.нативные[форма], self.эталон[форма])
                       for форма in self.нативные
                       if форма in self.эталон and self.нативные[форма] != self.эталон[форма]]
        self.assertEqual(расхождения, [], "ядро сводит форму не к той лемме")

    def test_таблица_не_разрастается_мусором(self):
        # Варианты регистра пишутся в трёх видах: строчные, ПРОПИСНЫЕ, С прописной.
        лишние = [форма for форма in self.нативные
                  if форма.lower() not in self.эталон and форма not in self.эталон]
        self.assertEqual(лишние, [], "в таблице ядра есть формы, которых нет в языке")

    def test_регистр_покрыт(self):
        # Для каждой строчной формы должны быть ПРОПИСНАЯ и С прописной:
        # язык русский, и предложение начинается с заглавной буквы.
        без_вариантов = []
        for форма in self.эталон:
            if форма != форма.lower():
                continue
            for вариант in (форма.upper(), форма.capitalize()):
                if вариант not in self.нативные:
                    без_вариантов.append(вариант)
        self.assertEqual(sorted(без_вариантов), [],
                         "эти написания с заглавной буквы ядро не узнает")


if __name__ == "__main__":
    unittest.main(verbosity=2)
